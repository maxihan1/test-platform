// 프로젝트 QA 리포트 날짜 셈 · 문서 글 도우미
import { describe, expect, it } from 'vitest';

import { 바뀐날글, 반복글 } from './qaProjectReportDoc.js';
import { 기간까닭, 날수, 다음기간, 빠른기간, 회차수 } from './qaProjectReportShape.js';

describe('프로젝트 QA 리포트 기간', () => {
  it('양 끝을 넣어 92일까지 · 오늘까지 · 날짜 꼴만 받는다', () => {
    expect(기간까닭('2026-08-16', '2026-11-15', '2026-11-15')).toBeNull();
    expect(날수('2026-08-16', '2026-11-15')).toBe(92);
    expect(기간까닭('2026-08-15', '2026-11-15', '2026-11-15')).toBe('기간은 92일까지입니다');
    expect(기간까닭('2026-11-01', '2026-11-16', '2026-11-15')).toBe('종료일은 오늘까지입니다');
    expect(기간까닭('2026-11-02', '2026-11-01', '2026-11-15')).toBe('시작일이 종료일보다 늦습니다');
    expect(기간까닭('2026-02-30', '2026-03-01', '2026-11-15')).toBe('기간은 YYYY-MM-DD 날짜입니다');
  });

  it('이번 주는 월요일부터, 이번 달은 1일부터 오늘까지다', () => {
    expect(빠른기간('2026-11-15', '주')).toEqual({ from: '2026-11-09', to: '2026-11-15' });
    expect(빠른기간('2026-11-09', '주')).toEqual({ from: '2026-11-09', to: '2026-11-09' });
    expect(빠른기간('2026-11-15', '달')).toEqual({ from: '2026-11-01', to: '2026-11-15' });
  });

  it('다음 기간은 같은 길이로 바로 뒤고, 세트 회차는 요일 · 한 번 날짜로 센다', () => {
    expect(다음기간('2026-11-01', '2026-11-07')).toEqual({ from: '2026-11-08', to: '2026-11-14' });
    expect(회차수({ days: [1, 3], onceOn: null }, '2026-11-08', '2026-11-14')).toBe(2);
    expect(회차수({ days: null, onceOn: '2026-11-20' }, '2026-11-08', '2026-11-14')).toBe(0);
    expect(회차수({ days: null, onceOn: '2026-11-10' }, '2026-11-08', '2026-11-14')).toBe(1);
  });

  it('반복은 매일 · 평일 · 요일 이름으로, 추이는 바뀐 날만 적는다', () => {
    expect(반복글({ at: '02:00', days: [0, 1, 2, 3, 4, 5, 6], onceOn: null })).toBe('매일 02:00');
    expect(반복글({ at: '09:00', days: [5, 1, 2, 3, 4], onceOn: null })).toBe('평일 09:00');
    expect(반복글({ at: '18:00', days: [4, 1], onceOn: null })).toBe('월 · 목 18:00');
    expect(반복글({ at: '10:00', days: null, onceOn: '2026-11-20' })).toBe('11/20 한 번 10:00');
    const 점 = [7, 6, 6, 6, 4].map((값, i) => ({ day: `2026-11-1${String(i)}`, 값 }));
    expect(바뀐날글(점)).toBe('11/10 7 → 11/11 6 → 11/14 4');
  });
});
