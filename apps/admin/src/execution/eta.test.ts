// 남은 시간 계산의 순수 부분 — 중간값 · 기록 없음 대체 · 칸 수로 나눔 · 기준 시각부터 줄어듦
import { describe, expect, it } from 'vitest';

import { 가장긴케이스, 남은시간계산, 줄어든남은시간, 칸수, 중간값 } from './eta.js';

describe('중간값', () => {
  it('홀수 개면 가운데, 짝수 개면 가운데 둘의 평균이다', () => {
    expect(중간값([500, 100, 300])).toBe(300);
    expect(중간값([100, 200, 300, 400])).toBe(250);
  });

  it('값이 없으면 null 이다', () => {
    expect(중간값([])).toBeNull();
  });
});

describe('남은시간계산', () => {
  it('안 끝난 항목이 없으면 0 이다', () => {
    expect(남은시간계산([], null, 2)).toBe(0);
  });

  it('예상 합을 칸 수로 나눈다', () => {
    expect(남은시간계산([400, 600, 1000, 1000], null, 2)).toBe(1500);
    expect(남은시간계산([400, 600, 1000, 1000], null, 0.5)).toBe(6000);
  });

  it('지난 기록이 없는 항목은 이번 실행에서 끝난 항목의 평균으로 채운다', () => {
    expect(남은시간계산([400, null], 1000, 2)).toBe(700);
  });

  it('채울 평균도 없으면 null 이다 — 화면은 계산 중', () => {
    expect(남은시간계산([400, null], null, 2)).toBeNull();
  });

  it('기록이 모든 항목에 있으면 평균이 없어도 계산한다', () => {
    expect(남은시간계산([400, 600], null, 2)).toBe(500);
  });
});

describe('가장긴케이스 (PRD-F9-36)', () => {
  it('같은 케이스 항목은 하나씩 돌아 그 합이 남은 시간의 바닥이다 — 60초 5회 + 10초 하나면 300초', () => {
    const 미완 = [1, 2, 3, 4, 5].map(() => ({ tcId: 'A', 예상: 60_000 }));
    expect(가장긴케이스([...미완, { tcId: 'B', 예상: 10_000 }], null)).toBe(300_000);
  });

  it('예상이 빈 항목은 끝난 평균으로 채우고, 그것도 없으면 0 으로 센다', () => {
    expect(가장긴케이스([{ tcId: 'A', 예상: 100 }, { tcId: 'A', 예상: null }], 50)).toBe(150);
    expect(가장긴케이스([{ tcId: 'A', 예상: 100 }, { tcId: 'A', 예상: null }], null)).toBe(100);
    expect(가장긴케이스([], null)).toBe(0);
  });
});

describe('칸수', () => {
  it('동시 수와 안 끝난 항목 수 중 작은 쪽이다', () => {
    expect(칸수(2, 5, 1)).toBe(2);
    expect(칸수(2, 1, 1)).toBe(1);
  });

  it('도는 실행이 여럿이면 나눠 쓴다. 1 아래로는 안 내려간다', () => {
    expect(칸수(4, 10, 2)).toBe(2);
    expect(칸수(2, 10, 4)).toBe(1);
    expect(칸수(2, 10, 0)).toBe(2);
  });
});

describe('줄어든남은시간', () => {
  it('기준 시각에서 지금까지 흐른 만큼 줄어든다', () => {
    expect(줄어든남은시간(5000, 1000, 1000)).toBe(5000);
    expect(줄어든남은시간(5000, 1000, 3500)).toBe(2500);
  });

  it('0 아래로는 안 내려간다', () => {
    expect(줄어든남은시간(5000, 1000, 9000)).toBe(0);
  });

  it('셈이 null 이면 null 이다', () => {
    expect(줄어든남은시간(null, 1000, 3500)).toBeNull();
  });
});
