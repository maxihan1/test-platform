// 남은 시간 계산의 순수 부분 — 중간값 · 기록 없음 대체 · 동시 수로 나눔
import { describe, expect, it } from 'vitest';

import { 남은시간계산, 중간값 } from './eta.js';

describe('중간값', () => {
  it('홀수 개면 가운데, 짝수 개면 가운데 둘의 평균이다', () => {
    expect(중간값([500, 100, 300])).toBe(300);
    expect(중간값([100, 200, 300, 400])).toBe(250);
  });

  it('값이 없으면 null 이다', () => {
    expect(중간값([])).toBeNull();
  });
});

describe('남은시간계산', () => {
  it('안 끝난 항목이 없으면 0 이다', () => {
    expect(남은시간계산([], null, 2)).toBe(0);
  });

  it('예상 합을 동시 실행 수로 나눈다', () => {
    expect(남은시간계산([400, 600, 1000, 1000], null, 2)).toBe(1500);
  });

  it('안 끝난 항목이 동시 수보다 적으면 항목 수로 나눈다', () => {
    expect(남은시간계산([400], null, 2)).toBe(400);
  });

  it('지난 기록이 없는 항목은 이번 실행에서 끝난 항목의 평균으로 채운다', () => {
    expect(남은시간계산([400, null], 1000, 2)).toBe(700);
  });

  it('채울 평균도 없으면 null 이다 — 화면은 계산 중', () => {
    expect(남은시간계산([400, null], null, 2)).toBeNull();
  });

  it('기록이 모든 항목에 있으면 평균이 없어도 계산한다', () => {
    expect(남은시간계산([400, 600], null, 2)).toBe(500);
  });
});
