// 경로 번호 검사가 문(auth/scope.ts)과 같은 엄격함인지 본다 (scope.ts 의 번호로 주석)

import { describe, expect, it } from 'vitest';

import { 번호로 } from './auth/scope.js';
import { 정수 } from './routeParams.js';

describe('경로 번호 검사', () => {
  it('열 자리 숫자 글자만 받는다', () => {
    expect(정수('1')).toBe(1);
    expect(정수('42')).toBe(42);
    expect(정수('9007199254740991')).toBe(9_007_199_254_740_991);
  });

  // 문이 /^\d+$/ 로 막는 모양들이다. 라우트가 더 느슨하면 문과 라우트가 다른 값을 본다 —
  // 2026-09-19 에 /api/runs/1e3 으로 실측된 구멍을 문 쪽에서 막은 근거가 이 등식이다
  it('숫자 글자가 아닌 모양은 전부 막는다', () => {
    for (const 값 of ['0x10', '0b101', '0o17', '1e3', '+1', '1.0', '1.', ' 1 ', '\n5\t', '.5', 'Infinity', 'abc', '']) {
      expect(정수(값)).toBeNull();
    }
  });

  it('0 과 음수는 막는다', () => {
    expect(정수('0')).toBeNull();
    expect(정수('-1')).toBeNull();
  });

  // 자리수만 맞으면 통과시키면 그 값이 그대로 Postgres 로 가 범위 초과가 잡히지 않은 500 이 된다.
  // id 칸은 전부 BIGSERIAL 이라 자바스크립트가 정확히 셀 수 있는 한계가 실질 상한이다
  it('자바스크립트가 정확히 셀 수 없는 크기는 막는다', () => {
    expect(정수('9007199254740992')).toBeNull();
    expect(정수('1000000000000000000000')).toBeNull();
  });

  // 라우트가 문보다 느슨하면 문이 막은 글자를 라우트가 번호로 읽는다.
  // 반대 방향(문이 0 을 돌려주고 라우트가 막는 것)은 안전한 쪽이라 같을 것을 요구하지 않는다
  it('라우트가 받는 값은 문도 같은 값으로 읽는다', () => {
    for (const 값 of ['1', '42', '9007199254740991', '0x10', '1e3', '+1', ' 1 ', '0', 'abc', '9007199254740992']) {
      const 읽은값 = 정수(값);
      if (읽은값 !== null) expect(읽은값).toBe(번호로(값));
    }
  });
});
