// 한국 시각 변환 — 서버가 어느 시간대에 떠 있든 같은 글자가 나온다
import { describe, expect, it } from 'vitest';

import { 한국시각 } from './kst.js';

describe('한국시각', () => {
  it('UTC 에 9시간을 더해 분까지 적는다', () => {
    expect(한국시각('2026-11-24T05:00:00.000Z')).toBe('2026-11-24 14:00');
  });

  it('UTC 자정 근처는 한국에서 다음 날로 넘어간다', () => {
    expect(한국시각('2026-11-23T15:30:00.000Z')).toBe('2026-11-24 00:30');
    expect(한국시각('2026-12-31T15:00:00.000Z')).toBe('2027-01-01 00:00');
  });

  it('UTC 전날 15시 직전은 같은 날에 남는다', () => {
    expect(한국시각('2026-11-23T14:59:00.000Z')).toBe('2026-11-23 23:59');
  });
});
