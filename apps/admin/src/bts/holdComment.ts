// 배포 스모크 보류 댓글 글 — 스모크 실패와 테스트 데이터 준비 실패를 가른다 (도메인/BTS §3.12 「새 기능 바퀴」 4). deployFlow.ts 가 300줄에 닿지 않게 뗐다

/** 준비 실패로 닫힌 스모크 — 미실행이라 보류지만 빌드가 깨진 것이 아니라 테스트 데이터 준비가 안 됐다 (도메인/실행 §3.2 「실행 전 준비」) */
export interface 준비실패앱 {
  prefix: string;
  note: string | null;
}

/**
 * 보류 댓글 — 스모크가 깨진 애플리케이션이 하나라도 있으면 머리는 「스모크 실패 — 보류」, 준비만 실패했으면 「테스트 데이터 준비 실패 — 보류」다.
 * 준비 실패 애플리케이션은 한 줄씩 까닭을 단다 (도메인/BTS 「새 기능 바퀴」 4)
 */
export function 보류글(buildNo: string, 깨진앱: string[], 준비실패: 준비실패앱[]): string {
  const 머리 = 깨진앱.length > 0 ? '스모크 실패 — 보류' : '테스트 데이터 준비 실패 — 보류';
  return [
    `${머리} · 빌드 ${buildNo}`,
    ...(깨진앱.length > 0 ? [`스모크가 실패한 애플리케이션: ${깨진앱.join(', ')}`] : []),
    ...준비실패.map((a) => `테스트 데이터 준비 실패: ${a.prefix}${a.note === null ? '' : ` · ${a.note}`}`),
    '이슈는 「QA 요청」에 그대로 두고 다음 배포에서 다시 확인합니다',
  ].join('\n');
}
