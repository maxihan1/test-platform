const 여기 = dirname(fileURLToPath(import.meta.url));

// 훑을 대상은 화면 코드뿐이다. 표 자신과 검사 파일은 `t(` 를 부르지 않거나 일부러 어긴 예를 담는다
function 화면파일들(폴더: string): string[] {
  return readdirSync(폴더).flatMap((이름) => {
    const 길 = join(폴더, 이름);
    if (statSync(길).isDirectory()) return 이름 === 'dist' || 이름 === 'messages' ? [] : 화면파일들(길);
    if (!/\.tsx?$/.test(이름) || /\.test\.tsx?$/.test(이름)) return [];
    if (이름 === 'i18n.ts' || 이름 === 'messages.ts') return [];
    return [길];
  });
}

const 소스 = 화면파일들(여기).map((길) => ({ 길, 글: readFileSync(길, 'utf8') }));

interface 훑음 {
  /** 주석을 걷어낸 코드. JSX 사이의 글자를 여기서 찾는다 */
  밖: string;
  /** 따옴표 문자열의 알맹이 */
  글자: string[];
  /** 템플릿 문자열 원문 */
  템플릿: string[];
}

/**
 * 소스를 한 글자씩 걸으며 주석을 걷고 문자열을 모은다.
 *
 * **정규식으로는 못 한다. 두 번 데었다.**
 * ① `${location.protocol}//${host}` 의 `//` 를 주석으로 읽어 줄 끝까지 지우고 백틱 짝이 깨졌다.
 * ② `'html', 라벨: 'HTML'` 에서 **닫는 따옴표와 다음 여는 따옴표를 짝지어** `, 라벨: ` 을
 *    화면 글자로 잡았다. 따옴표 짝 맞추기는 어디가 시작인지 알아야 맞는다.
 */
function 훑는다(글: string): 훑음 {
  let 밖 = '';
  const 글자: string[] = [];
  const 템플릿: string[] = [];
  let i = 0;
  while (i < 글.length) {
    const c = 글[i] ?? '';
    const 다음 = 글[i + 1] ?? '';

    if (c === '/' && 다음 === '/') {
      while (i < 글.length && 글[i] !== '\n') i += 1;
      continue;
    }
    if (c === '/' && 다음 === '*') {
      i += 2;
      while (i < 글.length && !(글[i] === '*' && 글[i + 1] === '/')) i += 1;
      i += 2;
      밖 += ' ';
      continue;
    }

    if (c === "'" || c === '"' || c === '`') {
      const 시작 = i;
      let 알맹이 = '';
      i += 1;
      while (i < 글.length && 글[i] !== c) {
        if (글[i] === '\\') { 알맹이 += 글.slice(i, i + 2); i += 2; continue; }
        알맹이 += 글[i];
        i += 1;
      }
      i += 1;
      if (c === '`') {
        템플릿.push(글.slice(시작, i));
        // 자리표 안은 코드다. 거기 든 `t('…')` 키도 봐야 한다 —
        // 안 보면 그 키가 「표에만 있는 고아 키」로 잘못 잡힌다
        for (const 식 of 알맹이.matchAll(/\$\{([^}]*)\}/gu)) {
          const 속 = 훑는다(식[1] ?? '');
          글자.push(...속.글자);
          템플릿.push(...속.템플릿);
        }
      } else {
        글자.push(알맹이);
      }
      밖 += 글.slice(시작, i);
      continue;
    }

    밖 += c;
    i += 1;
  }
  return { 밖, 글자, 템플릿 };
}

/**
 * 한국어지만 **화면에 안 나가는** 글자.
 *
 * 브라우저 저장소 키와 도메인 타입의 값이다. 옮기면 저장된 값을 못 찾거나 타입이 깨진다.
 * **여기에 더할 때는 「화면에 안 나간다」를 실제로 확인하고 더한다** — 빠져나갈 구멍이다.
 */
const 화면밖 = new Set([
  '고른서비스', '사이드바접음', '화면언어', // localStorage 키. 옮기면 저장된 값을 못 찾는다
  '돌아갈자리', // sessionStorage 키 (api.ts)
  '멈춤', '증적만들기', '증적받기', '입력값저장', // role.ts 의 `할일` 타입 값
  // 개발자가 콘솔에서 읽는 줄. 화면에 안 나온다
  '[설정] 고친 뒤 /auth/me 를 다시 읽지 못했다. 새로고침하면 맞다',
  '묻는중', '밖', '안', // main.tsx 의 로그인 상태 태그
]);

// **`실행`·`설정` 은 일부러 안 넣었다.** `할일` 타입 값이기도 하지만 **화면 글자이기도 하다**
// (자리 넷의 `설정`, 줄 끝의 `실행` 버튼). 예외에 넣으면 그 둘이 안 옮겨져도 검사가 초록이 된다.
// 표에 있기만 하면 되므로 예외가 필요 없다.
// 견주기 응답 값(`새로깨짐` 등)도 같은 이유로 안 넣는다 — 화면이 그 글자를 그대로 보여준다

// **JSX 사이에서 뽑은 것에만 건다.** 거기서는 `{...}` 바깥의 코드 조각이 글자처럼 잡힌다.
// 문자열 리터럴에는 걸지 않는다 — 훑개가 정확히 잘라 오므로 거를 것이 없고,
// 걸면 `케이스 번호(PAY-001) 안에` 처럼 **괄호가 든 멀쩡한 화면 글자가 번역에서 빠진다.**
// 실제로 그것 때문에 제품 워딩에서 괄호를 뺄 뻔했다 — 검사가 제품을 바꾸게 두면 안 된다
const 코드냄새 = /===|!==|&&|\|\||=>|\bnull\b|\bundefined\b|\.\w|\s[?:]\s|[{}]/u;

const JSX글자 = />\s*([^<>{}\n'"`]*[가-힣][^<>{}'"`]*?)\s*</gu;

const 다듬 = (글: string): string => 글.replace(/\s+/gu, ' ').trim();
const 한글있나 = (글: string): boolean => /[가-힣]/u.test(글);

function 화면글자들(글: string): string[] {
  const { 밖, 글자 } = 훑는다(글);
  // 문자열 리터럴은 **원문 그대로** 쓴다. 공백을 줄이면 `진행 중입니다  3/40` 처럼
  // 두 칸을 띄운 키가 표와 안 맞아 「표에만 있는 고아 키」로 잘못 잡힌다
  const 모음 = 글자.filter(한글있나);
  for (const m of 밖.matchAll(JSX글자)) {
    const 자 = 다듬(m[1] ?? '');
    if (한글있나(자) && !코드냄새.test(자)) 모음.push(자);
  }
  return 모음.filter((글) => 글 !== '' && !화면밖.has(글));
}

/** 자리표(`${…}`)를 걷어낸 템플릿 문자열. 한국어 **식별자**는 여기서 사라진다 */
function 템플릿속글자(글: string): string[] {
  return 훑는다(글)
    .템플릿.filter((t) => 한글있나(t.replace(/\$\{[^}]*\}/gu, '')))
    .map(다듬);
}

// 번역 규칙은 실제 표와 떼어 놓고 잰다. 표가 자라도 이 단언들이 흔들리지 않는다
const 예시표 = { '진행 중': 'Running', '모두 {건수}건': 'All {건수}', '실행§버튼': 'Run', '실행§집계': 'Runs' };

describe('언어 표', () => {
  it('영어 표에 있는 글자는 영어로 낸다', () => {
    expect(글자('진행 중', 'en', 예시표)).toBe('Running');
  });

  it('한국어는 키가 곧 답이다. 표를 거치지 않는다', () => {
    expect(글자('진행 중', 'ko', 예시표)).toBe('진행 중');
  });

  it('영어 표에 없으면 한국어가 그대로 나온다. 빠진 번역이 화면을 깨지 않는다', () => {
    expect(글자('표에 아직 없는 글자', 'en', 예시표)).toBe('표에 아직 없는 글자');
  });

  it('값이 박힌 글자는 자리표를 값으로 바꾼다', () => {
    expect(글자('RUN {번호} 이 진행 중입니다 {끝난}/{전체}', 'ko', 예시표, { 번호: 12, 끝난: 3, 전체: 40 })).toBe(
      'RUN 12 이 진행 중입니다 3/40',
    );
  });

  it('영어로 낼 때도 자리표를 바꾼다', () => {
    expect(글자('모두 {건수}건', 'en', 예시표, { 건수: 42 })).toBe('All 42');
  });

  it('값을 안 주면 자리표를 그대로 둔다. 지어내지 않는다', () => {
    expect(글자('모두 {건수}건', 'ko', 예시표)).toBe('모두 {건수}건');
  });

  it('키 뒤의 괄호 꼬리는 화면에 나오지 않는다. 같은 한국어를 자리마다 다르게 번역하려고 붙인 것이다', () => {
    expect(글자('실행§버튼', 'ko', 예시표)).toBe('실행');
  });

  it('꼬리가 붙은 키도 영어 표를 탄다. 자리마다 다른 영어가 나온다', () => {
    expect(글자('실행§버튼', 'en', 예시표)).toBe('Run');
    expect(글자('실행§집계', 'en', 예시표)).toBe('Runs');
  });
});

// 「다 옮겼나」에 기계가 답하는 유일한 길이다.
// `t('…')` 호출만 세면 아직 안 감싼 글자는 세지도 못한다 — 남은 것을 세야 남은 것을 안다
describe('화면에 한국어가 남아 있으면 표에 있어야 한다', () => {
  it('소스의 모든 한국어 글자가 영어 표의 키다', () => {
    const 빠진것: string[] = [];
    for (const { 길, 글 } of 소스) {
      for (const 자 of 화면글자들(글)) if (!(자 in 말)) 빠진것.push(`${길.split('/web/')[1]}: ${자}`);
    }
    expect(빠진것).toEqual([]);
  });

  it('영어 표의 키가 전부 화면에 있다. 워딩을 고친 뒤 옛 키가 남지 않게', () => {
    const 있는것 = new Set(소스.flatMap(({ 글 }) => 화면글자들(글)));
    expect(Object.keys(말).filter((키) => !있는것.has(키.replace(/§[^§]*$/u, '')))).toEqual([]);
  });

  // 값이 박힌 글자를 템플릿 문자열로 쓰면 키를 만들 수 없다. 자리표를 쓰게 만든다 —
  // 못 잡는 모양을 잡으려 애쓰는 대신 금지한다 (계획 게이트 1 BLOCKER 2)
  it('한국어가 든 템플릿 문자열이 하나도 없다', () => {
    const 어긴것: string[] = [];
    for (const { 길, 글 } of 소스) {
      for (const 자 of 템플릿속글자(글)) 어긴것.push(`${길.split('/web/')[1]}: ${자}`);
    }
    expect(어긴것).toEqual([]);
  });
});

// **표에 키가 있다 ≠ 그 자리가 옮겨진다.** 위 검사는 키의 존재만 본다 —
// 그래서 `mask.ts` 가 `'예'` 를 그대로 돌려주는데도 초록이었다. 그 낱말이 *다른 파일*의
// 키로 있었기 때문이다 (2026-09-22 자기검사에서 손으로 찾았다). 기계가 보게 옮긴다
describe('한국어를 내는 파일은 옮기기도 한다', () => {
  const 화면밖파일 = new Set([
    'api.ts', // 서버가 주는 열거값과 저장소 키. 화면에 그대로 안 나간다
    'role.ts', // `할일` 타입의 값
  ]);

  it('화면 글자가 있는 파일은 전부 t() 를 부른다', () => {
    const 안부름: string[] = [];
    for (const { 길, 글 } of 소스) {
      const 이름 = 길.split('/web/')[1] ?? '';
      if (화면밖파일.has(이름)) continue;
      if (화면글자들(글).length === 0) continue;
      const { 밖 } = 훑는다(글);
      if (!/(?<![\w$.])t\s*\(|use말\s*\(/u.test(밖)) 안부름.push(이름);
    }
    expect(안부름).toEqual([]);
  });
});
