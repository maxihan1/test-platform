import { describe, expect, it } from 'vitest';

import { 실패글 } from './authoringFailText.js';

describe('에이전트 실패 글을 화면 말로 (⑫ 점검 12.7)', () => {
  it('반말 개발자 글을 사람 말로 옮기고 원문을 남긴다', () => {
    const r = 실패글('자식이 남긴 프로세스를 거두지 못했다 — 올리지 않는다', 'ko', false);
    expect(r.글).toBe('작성 도구가 끝나지 않아 결과를 올리지 않았습니다. 같은 자료로 다시 작성하세요');
    expect(r.원문).toBe('자식이 남긴 프로세스를 거두지 못했다 — 올리지 않는다');
  });

  it('글 안의 값(대상 서버 · 건수)을 옮긴 말에 그대로 싣는다', () => {
    expect(실패글('대상 서버 「stg」 가 「운영 서버」로 체크돼 작성이 가지 않는다 — 다른 대상 서버로 새 요청을 넣어라', 'ko', false).글).toBe(
      '대상 서버 「stg」은 실서비스 서버라 작성하지 않습니다. 다른 대상 서버로 새 요청을 넣으세요',
    );
    expect(실패글('겹치는 케이스 3건 — 케이스마다 고른 뒤 다시 반영한다', 'ko', false).글).toContain('3건');
  });

  it('설정을 고쳐야 풀리는 글은 운영자에게만 설정으로 가라고 한다 (점검 11.3)', () => {
    const 원문 = '피그마 자료가 있는데 피그마 토큰이 없다. 설정 화면에 피그마 토큰을 넣어라.';
    expect(실패글(원문, 'ko', true).글).toContain('설정 > 애플리케이션');
    expect(실패글(원문, 'ko', false).글).toContain('관리자에게');
  });

  it('표에 없는 글은 지어내지 않고 첫 줄을 그대로 낸다', () => {
    expect(실패글('처음 보는 실패\n자세히', 'ko', false)).toEqual({ 글: '처음 보는 실패', 원문: null });
  });
});
