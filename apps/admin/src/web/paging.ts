// 다음 페이지가 있는지 판단한다 (SPEC §8.1 · §8.7)
//
// **총건수로 페이지 수를 계산하지 않는다.** 그 숫자는 안내로만 쓴다 —
// 근사치가 되는 날(검색엔진을 붙이는 날) 마지막 페이지 뒤에 빈 페이지가 생긴다.
//
// 받은 건수가 한 쪽 크기와 같으면 「더 있을 수 있다」로 본다.
// 마지막 쪽이 정확히 한 쪽 크기면 빈 쪽을 한 번 보게 되지만,
// 총건수를 믿다가 있지도 않은 쪽으로 넘어가는 것보다 낫다 — 다음을 누르면 0건이 뜨고 거기서 멈춘다.

// 필요한 둘만 받는다. total 을 인자로 아예 안 받는 것이
// 「이 값으로 판단하지 않는다」를 타입으로 말하는 가장 확실한 방법이다
export function 다음이있나(한쪽: { items: readonly unknown[]; pageSize: number }): boolean {
  return 한쪽.items.length >= 한쪽.pageSize;
}
