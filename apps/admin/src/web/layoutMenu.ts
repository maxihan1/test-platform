// 사이드바 자리 목록 — 고른 애플리케이션의 종류 · 권한으로 메뉴와 QA 단계 구분선을 정한다 (SPEC 공통/5-화면공통 §8 「자리 목록」)
// layout.ts 가 300줄을 넘어 떼어 냈다. 바깥은 지금처럼 layout.ts 에서 가져간다

import type { User } from './api.js';
import { t, type 언어 } from './i18n.js';
import type { 아이콘이름 } from './icons.js';
import { 종류, 종류키 } from './kind.js';
import { 기능보나, 할수있나 } from './role.js';
import { 대시보드보나 } from './route.js';

export interface 자리 {
  이름: string;
  해시: string;
  /** 글자 곁에 서는 메뉴 아이콘 (DESIGN.md 원칙 5). 하위 메뉴에는 없다 — 묶음의 아이콘이 이미 말한다 */
  아이콘: 아이콘이름;
  /** Grafana 는 이 플랫폼 밖이다. 화살표로 그렇게 표시한다 (SPEC §8) */
  바깥?: boolean;
  /** 늘 펼쳐 두는 하위 메뉴 (화면공통 §8 「자리 목록」 · PR #132) */
  하위?: 하위자리[];
  /** QA 단계 — 앞 자리와 다르면 그 위에 구분선 제목이 선다. 설정처럼 단계 밖 자리는 없다 (화면공통 §8 「자리 목록」 「단계 구분선」 · 2026-11-12 사용자) */
  단계?: string;
}

/** 같은 글자(「UI 테스트」)가 두 묶음에 나온다 — 화면 읽기 프로그램이 어느 묶음 것인지 알게 라벨에 묶음 이름을 붙인다 */
export interface 하위자리 {
  이름: string;
  해시: string;
  라벨: string;
}

/** 묶음 이름을 단 하위 하나 — 같은 글자(「기능 테스트」)가 두 묶음에 나와 읽어 주는 이름에 묶음을 붙인다 */
const 하위하나 = (묶음: string, 글: string, 해시: string, 언어: 언어): 하위자리 => ({
  이름: t(글, 언어),
  해시,
  라벨: `${묶음} · ${t(글, 언어)}`,
});

/**
 * Grafana 주소. admin 이 로그인·대시보드 권한을 보고 `/grafana/` 아래를 대신 연다 (도메인/인증 §7 「Grafana 통로」).
 * 2026-09-27 까지는 다른 포트라 빌드 때 구웠다 — 같은 서버 경로가 되며 구울 값이 사라졌다 (공통/6 §9.2)
 */
const 그래프주소 = '/grafana/';

/**
 * 자리 목록 (화면공통 §8 「자리 목록」).
 *
 * 기능이 `none` 이면 그 자리가 없고, 설정은 운영 계정에게만 뜬다. **흐리게 두지 않고 아예 없다** —
 * 누를 수 없는 메뉴가 있으면 사람이 그것이 올 때까지 기다린다 (§8.6).
 * 케이스·작성·실행은 **고른 서비스**의 칸을 보고, 그래프는 사람의 대시보드 칸을 본다.
 * 앱 대시보드는 배정 서비스 전체의 실행 칸이다 — 둘은 이름만 같고 칸이 다르다 (화면공통 §8).
 */
export function 자리목록(user: User, prefix: string | null, 언어: 언어): 자리[] {
  const 목록: 자리[] = [];
  // 메뉴는 고른 애플리케이션 종류 하나로만 정한다 — 케이스 유무로 자리가 생기거나 사라지지 않는다 (화면공통 §8 「자리 목록」 · 2026-10-29 사용자 메뉴 C안)
  const 고른 = user.services.find((서비스) => 서비스.prefix === prefix);
  const 줄 = 종류(고른?.kind);
  const API = 종류키(고른?.kind) === 'API';
  const 실행 = 기능보나(user, prefix, 'runs');
  // QA 단계 구분선 넷 — 메뉴만 훑어도 품질 현황 → 설계 → 수행 → 결과 분석이 읽힌다 (2026-11-12 사용자 · 시안 LrgxrskjP1hxHEFj3qRjsZ)
  const 현황 = t('품질 현황', 언어);
  const 설계 = t('테스트 설계', 언어);
  const 수행 = t('테스트 수행', 언어);
  const 결과 = t('결과 분석', 언어);

  // 맨 위다. 고른 서비스가 아니라 배정 서비스 전체의 실행 칸을 본다 (route.ts 의 `대시보드보나`)
  if (대시보드보나(user)) 목록.push({ 이름: t('대시보드', 언어), 해시: '#/dashboard', 아이콘: 'dashboard', 단계: 현황 });
  if (기능보나(user, prefix, 'authoring')) {
    // 작성이 읽는 기준 문서는 다 여기 모인다 — API 문서도 API 애플리케이션이면 PRD 옆 하위다. 네 종류의 맨 위 메뉴가 같아진다 (2026-10-29 사용자)
    const 이름 = t('PRD 관리', 언어);
    목록.push({
      이름,
      해시: '#/prd',
      아이콘: 'prd',
      단계: 설계,
      하위: [하위하나(이름, '요구사항', '#/prd', 언어), ...(API ? [하위하나(이름, 'API 문서', '#/api/docs', 언어)] : []), 하위하나(이름, 줄.가이드, '#/prd/guide', 언어)],
    });
    // 새 케이스를 설계하는 곳은 여기뿐이다 — 아래 수행 메뉴는 이미 쓴 케이스를 골라 묶어 돌린다
    목록.push({ 이름: t('테스트 작성', 언어), 해시: '#/authoring', 아이콘: 'authoring', 단계: 설계 });
  }
  // 수행 — 테스트 종류마다 메인 메뉴 하나. 만들고 돌리는 일은 그 화면에서 하고 결과는 아래 「실행 기록」에 모은다 (2026-11-12 사용자)
  if (기능보나(user, prefix, 'cases')) {
    // API 애플리케이션은 화면이 없어 UI 테스트가 없다(도메인/API §3.1) — 이름도 「기능 테스트」이고 하위 없이 바로 그 목록이다.
    // 주소는 지금 자리(`지금자리` 의 `#/cases/fn`)와 같아야 밑줄이 간다
    if (API) 목록.push({ 이름: t('기능 테스트', 언어), 해시: '#/cases/fn', 아이콘: 'cases', 단계: 수행 });
    else {
      // 묶음을 누르면 기능으로 간다(route.ts — 종류 없는 주소는 기능). 첫 하위가 그 화면이어야 누른 자리와 열린 화면이 맞는다
      const 이름 = t('기능 · UI 테스트', 언어);
      목록.push({ 이름, 해시: '#/cases', 아이콘: 'cases', 단계: 수행, 하위: [하위하나(이름, '기능 테스트', '#/cases/fn', 언어), 하위하나(이름, 'UI 테스트', '#/cases/ui', 언어)] });
    }
  }
  if (실행) {
    // 시나리오는 이미 있는 케이스를 이어 돌린다 — 새 케이스를 설계하지 않아 수행이다. 실행 칸을 쓴다 (도메인/시나리오 §7)
    목록.push({ 이름: t('E2E 테스트', 언어), 해시: '#/scenarios', 아이콘: 'scenarios', 단계: 수행 });
    // 폰에서 도는 종류(웹 · 앱 · 게임)에만 선다. 실행 칸을 쓴다 (도메인/호환성 §8.17 「메뉴」)
    if (!API) 목록.push({ 이름: t('호환성 테스트', 언어), 해시: '#/compat', 아이콘: 'compat', 단계: 수행 });
    // 페이지 성능 · 기기 성능은 고른 애플리케이션 종류에 맞을 때만 선다 (kind.ts). 부하 테스트 하나뿐인 API 는 하위 없이 바로 그 목록이다
    const 성능 = t('성능 테스트', 언어);
    const 성능하위 = [
      // 「시나리오」는 「E2E 시나리오」와 헷갈렸다 — 만드는 것이 부하 시나리오라 「부하 테스트」 (2026-10-29 사용자)
      하위하나(성능, '부하 테스트', '#/perf/scenarios', 언어),
      ...(줄.페이지성능 ? [하위하나(성능, '페이지 성능', '#/perf/pages', 언어)] : []),
      ...(줄.기기성능 === null ? [] : [하위하나(성능, 줄.기기성능, '#/perf/devices', 언어)]),
    ];
    목록.push({ 이름: 성능, 해시: '#/perf/scenarios', 아이콘: 'perf', 단계: 수행, ...(성능하위.length > 1 ? { 하위: 성능하위 } : {}) });
    // 이미 만든 테스트를 정한 시각에 돌린다 — 수행의 맨 끝. 프로젝트 공통이고 네 종류 모두 선다 (도메인/정기실행 §3.16 결정 1 · §8.20 「자리」)
    목록.push({ 이름: t('정기 실행', 언어), 해시: '#/sched', 아이콘: 'sched', 단계: 수행 });

    // 결과 분석 — 돌린 결과는 종류와 상관없이 여기 한 곳이다. 성능 결과도 2026-11-12 에 성능 테스트 아래에서 옮겨 왔다
    const 기록 = t('실행 기록', 언어);
    목록.push({
      이름: 기록,
      해시: '#/runs',
      아이콘: 'runs',
      단계: 결과,
      하위: [
        하위하나(기록, '기능 테스트', '#/runs/fn', 언어),
        ...(API ? [] : [하위하나(기록, 'UI 테스트', '#/runs/ui', 언어)]),
        // E2E 는 돌린 기록에만 있다. 시나리오는 케이스가 아니라 케이스 목록에 없다 (도메인/실행 §8.7)
        하위하나(기록, 'E2E', '#/runs/e2e', 언어),
        ...(API ? [] : [하위하나(기록, '호환성', '#/runs/compat', 언어)]),
        하위하나(기록, '성능', '#/perf/runs', 언어),
      ],
    });
    // 웹 · Android 앱 · 게임만 선다 — API 는 세는 로그가 없다 (도메인/안정화 §3.15 결정 7 · 13)
    if (!API) 목록.push({ 이름: t('안정화 지표', 언어), 해시: '#/stability', 아이콘: 'stability', 단계: 결과 });
  }
  // Issue Bunker 를 이은 프로젝트에만 선다 — 결함은 거기서 관리한다. 바깥 제품이라 새 탭이다 (2026-11-12 사용자).
  // 서버도 https:// 만 저장하지만(bts/link.ts) href 에 그대로 꽂는 값이라 여기서 한 번 더 거른다.
  // 기능 칸(케이스 · 작성 · 실행)이 하나도 없으면 세우지 않는다 — 이 줄만 남으면 「권한을 받지 않았습니다」 안내(layout.ts 빈띠사유)가 사라진다
  const 칸있음 = 기능보나(user, prefix, 'cases') || 기능보나(user, prefix, 'authoring') || 실행;
  if (칸있음 && 고른?.btsUrl?.startsWith('https://') === true) 목록.push({ 이름: t('결함 관리', 언어), 해시: 고른.btsUrl, 아이콘: 'defect', 바깥: true, 단계: 결과 });
  if (user.dashboard === 'read') 목록.push({ 이름: t('그래프(Grafana)', 언어), 해시: 그래프주소, 아이콘: 'graph', 바깥: true, 단계: 결과 });
  if (할수있나(user, prefix, '설정')) 목록.push({ 이름: t('설정', 언어), 해시: '#/settings', 아이콘: 'settings' });
  return 목록;
}
