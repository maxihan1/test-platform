// 증적 문서 버튼의 상태와 받는 법 (SPEC §8.4)
// 증적은 실행 단위 1부이므로 버튼은 항목 상세가 아니라 실행 결과의 RUN 머리에 둔다

import type { EvidenceRow } from './api.js';
import { 할수있나, type 등급 } from './role.js';
import { 도는중 } from './runState.js';

export interface 증적버튼모양 {
  format: string;
  라벨: string;
  글: string;
  누를수있나: boolean;
  /** 실패했을 때 사람이 읽을 한 문장. 원문 오류를 그대로 쓰지 않는다 */
  사유: string | null;
}

export interface 증적버튼줄 {
  버튼들: 증적버튼모양[];
  /**
   * 버튼이 없을 때 그 자리에 대신 적을 한 문장.
   *
   * **`사유` 와 같은 자리에 싣지 않는다** — 화면은 `사유` 를 빨간 띠로 그린다.
   * 아무것도 실패하지 않았는데 실패로 보이게 된다.
   */
  안내: string | null;
}

/**
 * 내는 형식 (SPEC §8.4 「내는 형식」 표).
 *
 * **이 표가 형식의 정본이다.** 개수를 다른 곳에 적지 않는다 —
 * 형식이 늘거나 줄면 여기만 고친다. 버튼도 받는 법도 전부 이것을 읽는다.
 * `새창` 은 브라우저가 열 수 있는가다. 나머지는 파일로 떨어진다.
 */
const 형식들 = [
  { format: 'PDF', 라벨: 'PDF', 새창: true },
  { format: 'XLSX', 라벨: '엑셀', 새창: false },
  { format: 'HTML', 라벨: 'HTML', 새창: true },
];

/**
 * 한 형식의 버튼 하나.
 *
 * **형식마다 따로 본다.** 하나가 실패했다고 다른 형식까지 막으면
 * 엑셀이 안 나왔을 때 낼 수 있는 PDF 까지 못 만든다.
 */
function 한형식(꼴: (typeof 형식들)[number], 문서들: EvidenceRow[]): 증적버튼모양 {
  const 그것들 = 문서들.filter((it) => it.format.toUpperCase() === 꼴.format);
  const 바탕 = { format: 꼴.format, 라벨: 꼴.라벨 };

  // **「만드는 중」은 화면이 아니라 DB 가 기억한다** — `PENDING` 행이 그 표시다.
  // 화면 상태로만 막으면 새로고침할 때마다 또 눌리고 문서 행이 쌓인다
  if (그것들.some((it) => it.status === 'PENDING')) {
    return { ...바탕, 누를수있나: false, 글: `${꼴.라벨} 만드는 중`, 사유: null };
  }

  // **마지막 행을 본다.** 서버가 id 오름차순으로 주므로 `find` 는 언제나 옛것을 잡는다 —
  // 한 번 실패한 뒤 다시 만들어 성공해도 옛 실패 사유 띠가 영영 남는다
  const 마지막 = 그것들.at(-1);
  if (마지막?.status === 'FAILED') {
    return {
      ...바탕,
      누를수있나: true,
      글: `${꼴.라벨} 다시 만들기`,
      사유: 마지막.error ?? '알 수 없는 사유로 만들지 못했습니다',
    };
  }

  // 이미 만든 것이 있어도 다시 만들 수 있다.
  // 같은 실행의 증적은 언제 뽑아도 같은 문서가 나오므로 내용이 달라지지 않는다 (§3.3)
  return {
    ...바탕,
    누를수있나: true,
    글: `${꼴.라벨} ${그것들.length === 0 ? '만들기' : '다시 만들기'}`,
    사유: null,
  };
}

/**
 * RUN 머리의 증적 버튼들 (SPEC §8.4 표).
 *
 * 보기만 등급에게는 `null` 이다. 만드는 것은 서버에 파일을 남기는 쓰기라
 * 실행까지부터다 (§3.5). **받기는 보기만도 할 수 있다** — 그건 아래 `받는법` 이 맡는다.
 *
 * 도는 중에는 버튼을 하나도 주지 않고 안내 문장만 준다.
 * 못 누르는 버튼을 셋이나 늘어놓으면 무엇을 기다리는지가 오히려 안 보인다.
 */
export function 증적버튼들(status: string, 문서들: EvidenceRow[], role: 등급 | null): 증적버튼줄 | null {
  if (!할수있나(role, '증적만들기')) return null;

  if (도는중(status)) {
    return { 버튼들: [], 안내: '실행이 끝나면 증적 문서를 만들 수 있습니다' };
  }

  return { 버튼들: 형식들.map((꼴) => 한형식(꼴, 문서들)), 안내: null };
}

/**
 * 만든 문서를 어떻게 받나 (SPEC §8.4).
 *
 * **「열린다」고 해 놓고 파일이 떨어지면 사람이 어디로 갔는지 찾는다.**
 * 그래서 버튼 글자가 형식에 따라 다르다. 표에 없는 형식은 받기로 둔다 —
 * 틀리는 방향을 「파일이 떨어진다」 쪽에 두면 적어도 어디 있는지는 안다.
 */
export function 받는법(format: string): { 글: string; 새창: boolean } {
  const 새창 = 형식들.find((it) => it.format === format.toUpperCase())?.새창 === true;
  return { 글: 새창 ? '열기 ↗' : '받기', 새창 };
}
