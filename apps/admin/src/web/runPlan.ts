// 실행을 걸기 전에 몇 건이 만들어지는지 세고 상한에서 막는다 (SPEC §8.2)
// 서버도 같은 것을 본다 — 화면만 막으면 직접 찌르는 요청을 못 막는다

/**
 * 한 번에 만들 수 있는 실행 항목 수.
 *
 * **막는 것은 반복 횟수가 아니라 만들어질 건수다.** 그래야 케이스 수가 늘어도 같이 보호된다.
 * 숫자를 바꾸려면 SPEC §8.2 를 고친다 — 설정값으로 빼지 않는다.
 * 코드에서는 여기 한 곳에만 적는다 (CLAUDE.md §2.7 ⑤).
 */
export const 상한 = 1000;

/** 케이스 수 × 디바이스 수 × 반복 횟수 */
export function 항목수(케이스수: number, 디바이스수: number, 반복: number): number {
  // 0 을 곱하면 아무것도 안 도는데 버튼은 살아 있다. 빈 칸은 1회로 읽는다
  return 케이스수 * 디바이스수 * Math.max(1, Math.floor(반복));
}

export function 넘었나(건수: number): boolean {
  return 건수 > 상한;
}
