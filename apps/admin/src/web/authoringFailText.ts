/**
 * 실패 글의 첫 줄을 화면 말로. 옮겼으면 `원문` 에 첫 줄을 남긴다 — 「원문 보기」로 접어 둔다.
 * 표에 없는 글은 `원문` 이 null 이고 `글` 이 원문 첫 줄이다(지어내지 않는다)
 */
export function 실패글(error: string, 언어: 언어, 운영자: boolean): { 글: string; 원문: string | null } {
  const 첫줄 = error.split('\n')[0] ?? '';
  for (const 줄 of 표) {
    const m = 줄.꼴.exec(첫줄);
    if (m === null) continue;
    const 말 = 운영자 && 줄.운영자말 !== undefined ? 줄.운영자말 : 줄.말;
    return { 글: t(말, 언어, { 1: m[1] ?? '' }), 원문: error };
  }
  return { 글: 첫줄, 원문: null };
}
