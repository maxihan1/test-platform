import { describe, expect, it } from 'vitest';

import { 빈이유 } from './catalogView.js';

describe('목록이 비었을 때 갈래 (SPEC §8.1)', () => {
  it('아직 한 번도 안 불러왔으면 그렇게 말한다. 「찾는」이라고 하면 안 된다', () => {
    const 것 = 빈이유({ scannedAt: null, 스캔문제: false, 전체건수: 0, 건조건: false, 친글자: '' }, 'ko');
    expect(것.무엇).toBe('아직 케이스를 불러오지 않았습니다');
    expect(것.버튼).toBe('케이스 불러오기');
  });

  it('불러왔는데 스캔 문제 없이 0건이면 아직 테스트가 없는 애플리케이션다 — 작성으로 보낸다 (PRD-F9-19)', () => {
    const 것 = 빈이유({ scannedAt: '2026-09-19T00:00:00.000Z', 스캔문제: false, 전체건수: 0, 건조건: false, 친글자: '' }, 'ko');
    expect(것.무엇).toBe('아직 테스트가 없습니다');
    expect(것.왜).toBe('「테스트 작성」에서 처음 작성을 시작합니다');
    expect(것.버튼).toBe('다시 스캔');
  });

  it('불러왔는데 스캔 문제가 있고 0건이면 왜인지 볼 길을 준다', () => {
    const 것 = 빈이유({ scannedAt: '2026-09-19T00:00:00.000Z', 스캔문제: true, 전체건수: 0, 건조건: false, 친글자: '' }, 'ko');
    expect(것.무엇).toBe('불러왔지만 케이스가 하나도 없습니다');
    // 사유는 화면 위 스캔 결과 줄이 이미 보여준다. 버튼은 다시 훑는 길을 준다
    expect(것.버튼).toBe('다시 스캔');
    expect(것.왜).toContain('사유는 위 스캔 결과에 있습니다');
  });

  it('검색에 안 걸린 것이면 친 글자를 그대로 넣는다', () => {
    const 것 = 빈이유(
      {
        scannedAt: '2026-09-19T00:00:00.000Z',
        스캔문제: false,
        전체건수: 20,
        건조건: true,
        친글자: '장바구니',
      },
      'ko',
    );
    expect(것.무엇).toBe('「장바구니」에 맞는 케이스가 없습니다');
    expect(것.버튼).toBe('조건 초기화');
  });

  it('글자 없이 칩만 걸었어도 검색에 안 걸린 것이다', () => {
    const 것 = 빈이유(
      {
        scannedAt: '2026-09-19T00:00:00.000Z',
        스캔문제: false,
        전체건수: 20,
        건조건: true,
        친글자: '',
      },
      'ko',
    );
    expect(것.무엇).toBe('조건에 맞는 케이스가 없습니다');
    expect(것.버튼).toBe('조건 초기화');
  });
});

