import { describe, expect, it } from 'vitest';

import { 넘었나, 상한, 항목수 } from './runPlan.js';

describe('실행 항목 수', () => {
  it('케이스마다 디바이스 수가 달라 곱이 아니라 합이다', () => {
    expect(항목수([1, 2, 1], 1)).toBe(4);
  });

  it('고른 케이스가 없으면 0건이다', () => {
    expect(항목수([], 1)).toBe(0);
  });

  it('반복은 합에 곱한다', () => {
    expect(항목수([1, 2, 1], 3)).toBe(12);
  });

  it('케이스마다 디바이스가 둘이면 케이스 수 × 2 다', () => {
    expect(항목수(디바이스수들(10, 2), 5)).toBe(100);
    expect(항목수([2, 2, 2], 1)).toBe(6);
  });

  it('반복이 0 이하면 1회로 본다. 0을 곱하면 아무것도 안 도는데 버튼은 살아 있다', () => {
    expect(항목수([2, 2, 2], 0)).toBe(6);
    expect(항목수([2, 2, 2], -1)).toBe(6);
  });

  it('디바이스를 하나도 안 고르면 0건이다', () => {
    expect(항목수([0, 0, 0], 5)).toBe(0);
  });
});

describe('한 번에 만들 수 있는 상한', () => {
  it('상한은 1000이다. SPEC §8.2 가 정본이고 숫자는 여기 한 번만 적는다', () => {
    expect(상한).toBe(1000);
  });

  it('정확히 1000건은 통과한다', () => {
    expect(넘었나(1000)).toBe(false);
  });

  it('1001건부터 막는다', () => {
    expect(넘었나(1001)).toBe(true);
  });

  it('막는 것은 반복 횟수가 아니라 만들어질 건수다. 케이스가 늘어도 같이 보호된다', () => {
    expect(넘었나(항목수(디바이스수들(10, 2), 51))).toBe(true);
    expect(넘었나(항목수([2], 10))).toBe(false);
  });
});

function 디바이스수들(케이스수: number, 케이스당: number): number[] {
  return Array.from({ length: 케이스수 }, () => 케이스당);
}
