import { describe, expect, it } from 'vitest';

import { 넘었나, 상한, 항목수 } from './runPlan.js';

describe('실행 항목 수', () => {
  it('케이스 수 × 디바이스 수 × 반복 횟수다', () => {
    expect(항목수(10, 2, 5)).toBe(100);
  });

  it('반복이 1이면 케이스 수 × 디바이스 수다', () => {
    expect(항목수(3, 2, 1)).toBe(6);
  });

  it('반복이 0 이하면 1회로 본다. 0을 곱하면 아무것도 안 도는데 버튼은 살아 있다', () => {
    expect(항목수(3, 2, 0)).toBe(6);
    expect(항목수(3, 2, -1)).toBe(6);
  });

  it('디바이스를 하나도 안 고르면 0건이다', () => {
    expect(항목수(3, 0, 5)).toBe(0);
  });
});

describe('한 번에 만들 수 있는 상한', () => {
  it('상한은 1000이다. SPEC §8.2 가 정본이고 숫자는 여기 한 번만 적는다', () => {
    expect(상한).toBe(1000);
  });

  it('정확히 1000건은 통과한다', () => {
    expect(넘었나(1000)).toBe(false);
  });

  it('1001건부터 막는다', () => {
    expect(넘었나(1001)).toBe(true);
  });

  it('막는 것은 반복 횟수가 아니라 만들어질 건수다. 케이스가 늘어도 같이 보호된다', () => {
    // 케이스 10 × 디바이스 2 × 반복 51 = 1020
    expect(넘었나(항목수(10, 2, 51))).toBe(true);
    // 반복이 10만이어도 케이스가 하나면 20건이다
    expect(넘었나(항목수(1, 2, 10))).toBe(false);
  });
});
