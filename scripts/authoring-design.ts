// 요구 글 하나에서 테스트 설계 기법이 요구하는 경계 근거 · 시험 값 · 예외 근거를 뽑는 순수 판정

export type 기법 = '경계값 분석' | '동등 분할' | '결정 테이블' | '상태 전이';
export interface 경계근거 { 근거: string; 값: string[] }
export interface 예외근거 { 기법: 기법; 근거: string }
export interface 설계 { 경계: 경계근거[]; 예외: 예외근거[] }

// 경계값 분석 — 한도가 붙는 단위만. 층 · 호 · 년도 같은 숫자는 한도가 아니다. 긴 단위를 앞에 둔다(「6자리」가 「자」에 밀리지 않게).
// 「개월」 · 「분기」는 기간이지 입력 한도가 아니다
const 단위 = '(?:글자|자리|시간|자|개(?!월)|원|명|회|번|건|일|분(?!기)|초|%|장|MB|KB|GB|px)';
// 경계값 분석 — 숫자 한가운데서 다시 잡지 않고, 요구 번호(「REQ-401」 · 「MEM-001~003」)의 숫자는 한도가 아니다
const 수 = '(?<![\\d,.A-Za-z-])(\\d[\\d,]*(?:\\.\\d+)?)';
// 경계값 분석 · 범위 — 「5~15초 사이 어느 시점」 같은 무작위 범위와 「늦게」 앞 범위는 한도가 아니다. 「8~16자 사이로」는 한도다
const 범위식 = new RegExp(`${수}\\s*(${단위})?(?:\\s*(?:뒤|후))?\\s*[~～]\\s*${수}\\s*(${단위})(?!\\S{0,3}\\s*(?:사이\\s*(?:어느|아무|임의|무작위)|늦게))`, 'g');
// 경계값 분석 · 한도 — 「20자를 초과」처럼 조사가 끼어도 잡고, 「이상이어도」는 한도가 아니라 양보다
const 한도식 = new RegExp(`${수}\\s*(${단위})\\s*(?:[을를이가]\\s*)?(이상|이하|초과|미만|까지|이내)(?!이어도|여도|라도)`, 'g');
// 경계값 분석 · 최대 · 최소 — 한도 낱말이 숫자 앞에 온다
const 최대식 = new RegExp(`(최대|최소)(?!한)\\D{0,8}?${수}\\s*(${단위})?`, 'g');
// 경계값 분석 · 한 번에 보여 주는 양 — N개 다음 하나가 넘친다
const 씩식 = new RegExp(`${수}\\s*(개|건)씩`, 'g');
// 경계값 분석 · 연속 횟수 — N 번째에 상태가 바뀌므로 바로 앞이 바깥 값이다
const 연속식 = new RegExp(`${수}\\s*(번|회)\\s*연속`, 'g');
// 경계값 분석 · 0건(R2) — 비었을 때 화면이 달라지면 0건과 1건이 경계다
const 빈식 = /(?:없으면|없을 때|비어 있으면|비어 있을 때|(?<!\d)0개면|(?<!\d)0건이면)[^.]{0,40}?(?:보여 준다|나온다|숨긴다|보이지 않|붙지 않|사라진다)/;
// 경계값 분석 · 연속 단위 — 바로 다음 정수가 없어서 바깥 값을 「초과」 · 「미만」으로 적는다
const 연속단위 = new Set(['MB', 'KB', 'GB']);
// 경계값 분석 · px — 화면 배치(너비)는 UI 몫이라 내리기 · 끌기 같은 조작 한도만 기능 경계다
const px조작 = /^[^.]{0,6}?(?:내리|올리|스크롤|끌|움직)/;

const 예외식: [기법, RegExp][] = [
  // 동등 분할 · 형식 위반 — 규칙에 맞지 않는 입력 묶음
  ['동등 분할', /맞지 않(?:으면|는)|형식(?:이 아니|에 맞지)|일치하지 않|다르면|틀리면|어기면|올바르지 않|고를 수 없|잘못(?:되|된|입력)/],
  // 동등 분할 · 빈 입력 — 필수 칸을 비우거나 공백만 넣은 묶음
  ['동등 분할', /[가-힣A-Za-z]+\(필수|공백만|(?:않고|않으면)[^.]{0,40}?(?:토스트|눌리지 않|넘어가지 않|되지 않|안내)/],
  // 동등 분할 · 허용 밖 종류 — 받는 글자 · 파일 종류 밖의 묶음
  ['동등 분할', /숫자만|외의 글자|만,?\s*(?:올릴|고를|입력|담을|달) 수/],
  // 동등 분할 · 없는 대상 · 겹침 — 「중복 없이」는 보여 주는 방식이지 오류가 아니다
  ['동등 분할', /없는 (?:아이디|글|주소|번호|상품|게시글)|존재하지 않|삭제된 글|이미 (?:있는|사용)|중복(?!\s*없)/],
  // 동등 분할 · 권한 — 남의 것 · 로그인 안 한 사람 묶음
  ['동등 분할', /남의|본인(?:에게)?만|\(본인|권한|관리자(?:에게)?만|작성자가 아닌|비로그인(?:이면|으로 들어|\s*상태에서\s*\S+\s*누르)|로그인이 필요/],
  // 동등 분할 · 실패 응답 — 「결제 실패 내역」 같은 명사는 빼고, HTTP 번호는 조건(「…면 409」) · 오류 말 뒤이거나 응답 코드(`LOCKED`)가 붙을 때만.
  // 「400ms」 · 「401호」 · 「500,000원」 · 「점수가 450을 넘으면」 · 요구 번호 「REQ-401」은 아니다
  ['동등 분할', /실패(?:하면|하는|할|한|로|\s?시)|오류|에러|불러오지 못|재고가 (?:모자라|부족)|모자라게|(?<=(?:면|오류|에러|상태|코드|HTTP)\s?)[45]\d{2}(?!\d|[,.]\d|\s*[KMG]B)|(?<![\d,.A-Za-z-])[45]\d{2}(?=\s*`|\s*[A-Z_]{2,})/],
  // 결정 테이블 — 조건이 모두 맞아야 넘어가거나, 하나라도 빠지면 막히는 갈림길
  ['결정 테이블', /해야[^.]{0,40}?(?:눌린|넘어|할 수 있|담을 수)|(?:때|경우|에서)만 (?:넘어|눌린|보인)|않거나|않았거나|(?<![화전측표평단정장지])면[^.]{0,60}?(?:(?:눌리|넘어가|등록되|저장하|등록하|주문하|담기)지 않|안 (?:눌|넘어|등록|저장|담)|비활성)|미(?:입력|선택|동의|체크)\s?시[^.]{0,40}?(?:비활성|눌리지 않|안 눌|넘어가지 않)/],
  // 상태 전이 — 잠김 · 특정 상태에서만 되는 동작
  ['상태 전이', /상태에서만|까지만 달 수|잠기|잠긴|잠금/],
];

const 숫자 = (s: string) => Number(s.replace(/,/g, ''));

/**
 * 한도 하나 → 2값. 아래쪽 한도(이상 · 미만 · 최소 · 연속)는 N−1 · N, 위쪽은 N · N+1. 한 칸은 원문의 소수 자릿수만큼이다(2.2 → 0.1).
 * 0 아래 값은 싣지 않는다 — 개수 · 금액에 음수 입력은 없다
 */
function 두값(본: string, 아래: boolean, 쉼표: boolean, u: string): string[] {
  const n = 숫자(본);
  const 자릿수 = 본.split('.')[1]?.length ?? 0;
  const 쓰기 = (v: number) => `${자릿수 > 0 ? v.toFixed(자릿수) : 쉼표 ? v.toLocaleString('en-US') : String(v)}${u}`;
  if (연속단위.has(u)) return 아래 ? [`${쓰기(n)} 미만`, 쓰기(n)] : [쓰기(n), `${쓰기(n)} 초과`];
  const 칸 = 10 ** -자릿수;
  return (아래 ? [n - 칸, n] : [n, n + 칸]).filter((v) => v >= 0).map(쓰기);
}

/** 요구 글 하나 → 경계 · 예외 근거. 같은 글이면 같은 결과 */
export function 설계하기(원글: string): 설계 {
  // 서버 변환(pandoc)의 표 칸 사이 넓은 빈칸 · 탭은 `|` 로 남기고 빈칸을 접는다 — 그냥 접으면 「409 아니오」처럼 다음 칸 글이 붙어
  // md 꼴(「409 |」)과 판정이 갈린다. 줄바꿈은 남긴다 — 맥 변환(textutil)은 칸마다 줄을 바꾸고(HTTP 번호는 줄 끝도 칸 끝으로 본다),
  // 손으로 꺾은 md 문장(「2자⏎이상」)은 `\s` 가 이어 읽는다. `|` 로 바꾸면 그 문장의 한도를 놓친다
  const 글 = 원글.replace(/\t| {2,}/g, ' | ').replace(/[^\S\n]+/g, ' ').replace(/ ?\n ?/g, '\n');
  const 한줄 = (s: string) => s.replace(/\s+/g, ' ').trim();
  const 경계: 경계근거[] = [];
  const 넣기 = (m: RegExpMatchArray, u: string, 값: (쉼표: boolean) => string[]) => {
    if (u === 'px' && !px조작.test(글.slice((m.index ?? 0) + m[0].length))) return;
    // 「12월 31일까지」 같은 날짜는 한도가 아니다 — 「매월 3회까지」는 한도라 단위가 「일」일 때만 거른다
    if (u === '일' && /[월년]\s?$/.test(글.slice(0, m.index))) return;
    const v = 값(/\d,\d/.test(m[0]));
    if (!경계.some((b) => b.값.join() === v.join())) 경계.push({ 근거: 한줄(m[0]).replace(/[,.\s]+$/, ''), 값: v });
  };
  // 범위 안에서 다시 잡은 한도(「4~12자 이내」의 「12자 이내」)는 같은 경계라 뺀다
  const 범위자리: [number, number][] = [];
  for (const m of 글.matchAll(범위식)) {
    const u = m[4];
    범위자리.push([m.index, m.index + m[0].length]);
    if (숫자(m[3]) > 숫자(m[1])) 넣기(m, u, (c) => [...두값(m[1], true, c, u), ...두값(m[3], false, c, u)]);
  }
  for (const m of 글.matchAll(한도식)) {
    if (범위자리.some(([가, 나]) => m.index >= 가 && m.index < 나)) continue;
    넣기(m, m[2], (c) => 두값(m[1], m[3] === '이상' || m[3] === '미만', c, m[2]));
  }
  for (const m of 글.matchAll(최대식)) {
    const u = m[3] ?? '';
    넣기(m, u, (c) => 두값(m[2], m[1] === '최소', c, u));
  }
  for (const m of 글.matchAll(씩식)) 넣기(m, m[2], (c) => 두값(m[1], false, c, m[2]));
  for (const m of 글.matchAll(연속식)) 넣기(m, m[2], (c) => 두값(m[1], true, c, m[2]));
  const 빈 = 빈식.exec(글);
  if (빈) 넣기(빈, '', () => ['0건', '1건']);
  const 예외: 예외근거[] = [];
  for (const [기, re] of 예외식) {
    const m = re.exec(글);
    if (m && !예외.some((e) => e.기법 === 기 && e.근거 === 한줄(m[0]))) 예외.push({ 기법: 기, 근거: 한줄(m[0]) });
  }
  return { 경계, 예외 };
}

/** `설계: 요구 N 중 경계 a · 예외 b` — PR 머리 줄과 설계 목록 명령이 같은 식을 쓴다 */
export function 설계요약(항목들: readonly { 설계?: 설계 }[]): string {
  const 셈 = (축: keyof 설계) => String(항목들.filter((h) => (h.설계?.[축].length ?? 0) > 0).length);
  return `설계: 요구 ${String(항목들.length)} 중 경계 ${셈('경계')} · 예외 ${셈('예외')}`;
}

/** 설계 목록 — 설계가 있는 요구만 한 줄씩, 끝에 요약 */
export function 설계글(항목들: readonly { 번호: string; 설계?: 설계 }[]): string {
  const 줄들 = 항목들.flatMap(({ 번호, 설계: 설 }) => {
    const 칸 = [
      ...(설?.경계 ?? []).map((b) => `경계 「${b.근거}」 ${b.값.join(' · ')}`),
      ...(설?.예외 ?? []).map((e) => `예외 ${e.기법} 「${e.근거}」`),
    ];
    return 칸.length > 0 ? [[번호, ...칸].join(' · ')] : [];
  });
  return [...줄들, 설계요약(항목들)].join('\n');
}
