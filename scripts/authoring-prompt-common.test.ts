// 단발 AI 지시문의 낱말 목록이 docs/WORDS.md 표를 그대로 옮기는지 본다
import { describe, expect, it } from 'vitest';

import { 낱말, 말투 } from './authoring-prompt-common.js';

const 표 = `# 표준 낱말

## 1. 화면 낱말

| 뜻 | 쓰는 말 | 쓰지 않는 말 | 걸러 내는 무늬 |
|----|---------|--------------|----------------|
| 처음 생기는 것 | 신규 | 새로 | \`새로\` |
| 이 제품 | Test Commander | — | — |

### 개발자 말 풀어 쓰기

| 쓰는 말 | 쓰지 않는 말 | 비고 |
|---|---|---|
| 검토용 PR | 초안 PR | |

## 2. 제품 이름

| 쓰는 말 | 옛 이름 | 무엇 | 비고 |
|---|---|---|---|
| Device VISION | 팜 | 디바이스 관제 | |
`;

describe('낱말', () => {
  it('§1 큰 표의 줄만 「쓰지 않는 말 → 쓰는 말」로 옮긴다 — 머리 · 쓰지 않는 말이 없는 줄 · 칸 차례가 다른 작은 표 · 다른 절은 뺀다', () => {
    expect(낱말(표)).toEqual([
      '■ 낱말 — 왼쪽 말을 쓰지 않고 오른쪽 말을 쓴다. 대상 서비스의 화면 문구를 「」로 옮길 때는 원문 그대로 둔다',
      '- 「새로」 → 「신규」',
    ]);
  });

  it('지시문의 말투 절이 저장소 정본 표에서 뽑은 낱말을 싣는다', () => {
    const 글 = 말투('해요', 'Issue Bunker 댓글').join('\n');
    expect(글).toContain('- 「요구」 → 「요구사항」');
    expect(글).toContain('- 「기기 · 폰 · 스마트폰」 → 「디바이스 (실제 디바이스 · 가상 디바이스)」');
  });
});
