// 단발 AI 지시문의 낱말 목록이 docs/WORDS.md 표를 그대로 옮기는지 본다
import { describe, expect, it } from 'vitest';

import { 낱말, 말투 } from './authoring-prompt-common.js';

const 표 = `# 표준 낱말

## 1. 화면 낱말

| 뜻 | 쓰는 말 | 쓰지 않는 말 | 걸러 내는 무늬 |
|----|---------|--------------|----------------|
| 처음 생기는 것 (2026-11-08) | 신규 | 새로 | \`새로\` |
| 이슈 트래킹 제품 | Issue Bunker (화면은 \`btsName.ts\` 상수로 쓴다) | BTS | \`BTS\` |
| 개발용 안쪽 말 | 쓰지 않는다 — 사용자가 아는 말로 푼다 | 관문 · 원장 | \`관문\\|원장\` |
| 「PRD 관리」의 출처 목록 — 이유를 뜻하면 둔다 | 출처 | 근거 | — |
| 이 제품 | Test Commander | — | — |

### 개발자 말 풀어 쓰기

| 쓰는 말 | 쓰지 않는 말 | 비고 |
|---|---|---|
| 검토용 PR | 초안 PR | |

## 2. 제품 이름

| 쓰는 말 | 옛 이름 | 무엇 | 비고 |
|---|---|---|---|
| Device VISION | 팜 | 디바이스 관제 | \`팜\` |
`;

describe('낱말', () => {
  it('§1 큰 표에서 무늬가 있는 줄만 뜻과 함께 옮긴다 — 코드 메모 · 뜻에 따라 갈리는 줄 · 칸 차례가 다른 작은 표 · 다른 절은 뺀다', () => {
    expect(낱말(표)).toEqual([
      '■ 낱말 — 왼쪽 말을 쓰지 않고 오른쪽 말을 쓴다. 대상 서비스의 화면 문구를 「」로 옮길 때와 GitHub 의 「PR 병합」처럼 다른 도구의 말은 원문 그대로 둔다',
      '- 처음 생기는 것: 「새로」 → 「신규」',
      '- 이슈 트래킹 제품: 「BTS」 → 「Issue Bunker」',
      '- 개발용 안쪽 말: 「관문 · 원장」은 쓰지 않는다 — 사용자가 아는 말로 푼다',
    ]);
  });

  it('지시문의 말투 절이 저장소 정본 표에서 뽑은 낱말을 싣고, 이유를 뜻하는 「근거」는 막지 않는다', () => {
    const 글 = 말투('해요', 'Issue Bunker 댓글').join('\n');
    expect(글).toContain('- 기획서 · PRD 의 한 줄: 「요구」 → 「요구사항」');
    expect(글).toContain('- 테스트를 돌리는 폰 · 태블릿: 「기기 · 폰 · 스마트폰」 → 「디바이스 (실제 디바이스 · 가상 디바이스)」');
    expect(글).not.toContain('「근거」');
  });
});
