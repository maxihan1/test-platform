// 남은 요구로 이어 작성 — 에이전트가 기준(main) 표로 남은 번호를 세고 자식에게 절을 준다 (도메인/작성 §3.6 「★ 원장」 「남은 요구로 이어 작성」)
// 저장된 셈(later · missing)은 쓰지 않는다 — 사본이라 사람이 병합 뒤 표를 고치면 낡는다. 판단은 여기 순수 함수, 읽기 · 쓰기는 authoring-ledger-io

import type { 원장 } from './authoring-ledger.js';
import { 원장대조 } from './authoring-ledger-check.js';

/** 자식에게 주는 남은 번호 사본 — 자료 폴더 안. 판정은 에이전트 메모리의 원장으로 한다(자식이 고쳐도 안 흔들린다) */
export const 이어작성사본이름 = 'continue.json';
/** 줄 프롬프트에 싣는 번호 수 — 나머지는 사본에서 읽는다. 124개를 다 실으면 프롬프트가 번호로 찬다 */
const 절에싣는수 = 20;

export interface 이어작성입력 {
  원본: number;
  남은: string[];
  사본: string;
}

/**
 * 남은 번호 — 원장 가운데 기준 표에서 「빠짐」이거나 「다음 요청」 제외인 것, 원장 순서로.
 * 케이스로 덮은 것 · 닫힌 제외(되돌릴 수 없음 · 자료 없음 · 요구 아님 · 기준 표에 있던 사람이 뺌)는 앞 요청이 끝낸 것이다.
 * 올리기 판정과 같은 대조(에이전트 모드)를 쓴다 — 둘이 다르면 셈에 남은 것이 이어 작성에서 안 잡히거나 그 반대가 된다
 */
export function 남은번호(원장값: 원장, 표글: string, 있는케이스: Set<string>, 사람이뺌: Set<string>): string[] {
  const r = 원장대조(원장값.항목, 표글, { 있는케이스, 에이전트: true, 사람이뺌 });
  const 남음 = new Set([...r.빠짐, ...[...r.제외번호].filter(([, 종류]) => 종류 === '다음 요청').map(([b]) => b)]);
  return 원장값.항목.map((h) => h.번호).filter((b) => 남음.has(b));
}

/**
 * 자식을 띄우지 않고 FAILED 로 끝낼 까닭. 없으면 null.
 * 끝났다는 뜻으로 적고 폐기를 권한다 — 폐기하면 원본이 풀린다(게이트 1 사용자 — 실패로 닫고 안내). 설정 · 자료 문제라 다시 해도 같다
 */
export function 이어작성막힘(원장값: 원장 | { 없음: string }, 남은: string[]): string | null {
  if ('없음' in 원장값) return `원장이 없어 남은 요구를 모른다 — ${원장값.없음}. 이 요청은 폐기해도 된다`;
  if (남은.length === 0) {
    return '남은 요구가 없다 — 앞 요청들이 기획서 요구를 모두 케이스로 만들었거나 제외했다. 이 요청은 폐기해도 된다';
  }
  return null;
}

/** 줄 프롬프트의 이어 작성 절. 무엇을 어떻게 하는지는 자식 스킬 참고 파일이 정본이다 */
export function 이어작성절(입력: 이어작성입력): string[] {
  const 앞 = 입력.남은.slice(0, 절에싣는수).join(' · ');
  const 더 = 입력.남은.length > 절에싣는수 ? ` …(전체는 사본)` : '';
  return [
    '',
    '--- 이어 작성 ---',
    `이 요청은 작성 요청 ${String(입력.원본)} 이 반영된 뒤 남은 요구 ${String(입력.남은.length)}개만 맡는다: ${앞}${더}`,
    `남은 번호 전체: ${입력.사본}`,
    '`.claude/skills/tpx-author/references/continue.md` 를 먼저 읽고 따라라. 표의 다른 줄과 앞 요청의 케이스는 손대지 마라.',
  ];
}
