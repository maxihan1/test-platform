// 설계 대조 검사 — 요구사항 표가 설계가 요구한 경계 · 예외 칸을 덮었는지와 PR 머리 줄 꼴
import { describe, expect, it } from 'vitest';

import { 설계대조, 설계줄들, type 설계대조결과 } from './authoring-design-check.js';
import type { 설계 } from './authoring-design.js';
import { type 표줄, 기준줄열쇠 } from './authoring-slots.js';

const 경계만: 설계 = { 경계: [{ 근거: '4~12자', 값: ['3자', '4자', '12자', '13자'] }], 예외: [] };
const 예외만: 설계 = { 경계: [], 예외: [{ 기법: '동등 분할', 근거: '맞지 않으면' }] };
const 둘다: 설계 = { 경계: 경계만.경계, 예외: 예외만.예외 };
const 줄 = (차례: number, 출처: string, 축: string, tcId = ''): 표줄 => ({ 차례, 출처, 축, tcId });
const 대조 = (
  원장: { 번호: string; 설계?: 설계 }[],
  줄들: 표줄[],
  선택: { 거절?: Record<string, string>[]; 제외?: string[]; 기준?: 표줄[] } = {},
) => 설계대조(원장, 줄들, 선택.거절 ?? [], new Set(선택.제외), new Set((선택.기준 ?? []).map(기준줄열쇠)));

describe('설계대조 — 빠짐', () => {
  it('경계를 요구한 요구에 경계 줄이 없으면 빠짐이다', () => {
    const r = 대조([{ 번호: 'REQ-A-001', 설계: 둘다 }], [줄(0, 'REQ-A-001', '정상'), 줄(1, 'REQ-A-001', ' 예외 ')]);
    expect(r.빠짐).toEqual(['REQ-A-001 경계']);
  });

  it('빠짐은 원장 차례, 한 요구 안에서 경계 → 예외', () => {
    const r = 대조(
      [
        { 번호: 'REQ-A-002', 설계: 둘다 },
        { 번호: 'REQ-A-001', 설계: 둘다 },
      ],
      [줄(0, 'REQ-A-001', '정상'), 줄(1, 'REQ-A-002', '정상')],
    );
    expect(r.빠짐).toEqual(['REQ-A-002 경계', 'REQ-A-002 예외', 'REQ-A-001 경계', 'REQ-A-001 예외']);
  });

  it('보류 · 미확정 · 기준 경계 줄도 칸을 채운다', () => {
    const 기준경계 = 줄(4, 'REQ-A-003', '경계', 'P-FN-008');
    const r = 대조(
      [
        { 번호: 'REQ-A-001', 설계: 경계만 },
        { 번호: 'REQ-A-002', 설계: 경계만 },
        { 번호: 'REQ-A-003', 설계: 경계만 },
      ],
      [
        줄(0, 'REQ-A-001 · 보류 — 값 없음', '경계'),
        줄(1, 'REQ-A-002 · 화면 검사 — 칸', '경계'),
        줄(2, 'REQ-A-003', '정상'),
        기준경계,
      ],
      { 기준: [기준경계] },
    );
    expect(r.빠짐).toEqual([]);
  });

  it('범위 출처 한 줄이 범위 안 요구를 다 채우고, 한 줄에 번호가 여럿이어도 든 번호 전부를 채운다', () => {
    const r = 대조(
      [
        { 번호: 'REQ-R-001', 설계: 경계만 },
        { 번호: 'REQ-R-002', 설계: 경계만 },
        { 번호: 'REQ-R-003', 설계: 경계만 },
        { 번호: 'REQ-A-001', 설계: 예외만 },
        { 번호: 'REQ-A-002', 설계: 예외만 },
      ],
      [줄(0, '기획서 REQ-R-001~003', '경계'), 줄(1, 'REQ-A-001 · REQ-A-002', '예외')],
    );
    expect(r.빠짐).toEqual([]);
  });

  it('제외된 요구 · 줄이 없는 요구 · 줄이 전부 기준 줄인 요구 · 설계가 없는 요구는 안 본다', () => {
    const 기준정상 = 줄(1, 'REQ-A-003', '정상', 'P-FN-007');
    const r = 대조(
      [
        { 번호: 'REQ-A-001', 설계: 둘다 },
        { 번호: 'REQ-A-002', 설계: 둘다 },
        { 번호: 'REQ-A-003', 설계: 둘다 },
        { 번호: 'REQ-A-004', 설계: 경계만 },
        { 번호: 'REQ-A-005' },
      ],
      [줄(0, 'REQ-A-001', '정상'), 기준정상, 줄(2, 'REQ-A-004', '정상'), 줄(3, 'REQ-A-005', '정상')],
      { 제외: ['REQ-A-001'], 기준: [기준정상] },
    );
    expect(r.빠짐).toEqual(['REQ-A-004 경계']);
  });
});

describe('설계대조 — 설계 거절', () => {
  const 원장 = [
    { 번호: 'REQ-A-001', 설계: 경계만 },
    { 번호: 'REQ-A-002', 설계: 경계만 },
  ];
  const 줄들 = [줄(0, 'REQ-A-001', '정상'), 줄(1, 'REQ-A-002', '정상')];

  it('맞는 거절 줄은 그 칸을 채우고 거절 목록에 든다', () => {
    const r = 대조(원장, 줄들, { 거절: [{ 요구: ' REQ-A-001 ', 축: ' 경계 ', 까닭: '「12월 31일까지」는 날짜다' }] });
    expect(r.빠짐).toEqual(['REQ-A-002 경계']);
    expect(r.거절).toEqual(['REQ-A-001 경계']);
    expect(r.형식오류).toEqual([]);
  });

  it('번호 둘 · 범위 · 모르는 축 · 빈 까닭은 형식 오류이고 칸을 안 채운다 — 설계가 요구하지 않는 칸의 거절 줄은 무시한다', () => {
    const r = 대조(원장, 줄들, {
      거절: [
        { 요구: 'REQ-A-001 · REQ-A-002', 축: '경계', 까닭: '날짜다' },
        { 요구: 'REQ-A-001~002', 축: '경계', 까닭: '날짜다' },
        { 요구: 'REQ-A-002', 축: '정상', 까닭: '날짜다' },
        { 요구: 'REQ-A-002', 축: '경계', 까닭: '  ' },
        { 요구: 'REQ-A-002', 축: '예외', 까닭: '날짜다' },
        { 요구: 'REQ-A-009', 축: '경계', 까닭: '날짜다' },
        {},
      ],
    });
    expect(r.형식오류).toEqual([
      '설계 거절 줄 「REQ-A-001 · REQ-A-002」 — 요구 번호가 하나가 아니다',
      '설계 거절 줄 「REQ-A-001~002」 — 범위는 안 된다',
      '설계 거절 줄 「REQ-A-002」 — 축은 경계 · 예외 중 하나다',
      '설계 거절 줄 「REQ-A-002」 — 까닭이 비었다',
      '설계 거절 줄 「」 — 요구 번호가 하나가 아니다',
    ]);
    expect(r.거절).toEqual([]);
    expect(r.빠짐).toEqual(['REQ-A-001 경계', 'REQ-A-002 경계']);
  });
});

describe('설계대조 — 설계 밖 칸', () => {
  it('설계에 없는 축의 정식 비기준 경계 · 예외 줄만 원장 차례로 한 번씩 센다', () => {
    const 기준예외 = 줄(9, 'REQ-A-002', '예외', 'P-FN-006');
    const r = 대조(
      [{ 번호: 'REQ-A-001', 설계: 경계만 }, { 번호: 'REQ-A-002' }],
      [
        줄(0, 'REQ-A-002', '예외'),
        줄(1, 'REQ-A-002', '경계'),
        줄(2, 'REQ-A-002 둘째 문장', '경계'),
        줄(3, 'REQ-A-001', '예외'),
        줄(4, 'REQ-A-001', '경계'),
        줄(5, 'REQ-A-002 · REQ-A-001', '경계'),
        줄(6, '보류 — 값 없음 REQ-A-002', '예외'),
        줄(7, '화면 검사 — REQ-A-002', '예외'),
        줄(8, '모킹 — REQ-A-002', '예외'),
        기준예외,
        줄(10, '기획서에 없는 동작', '예외'),
        줄(11, 'REQ-Z-001', '경계'),
        줄(12, 'REQ-A-002', '정상'),
      ],
      { 기준: [기준예외] },
    );
    expect(r.밖).toEqual(['REQ-A-001 예외', 'REQ-A-002 경계', 'REQ-A-002 예외']);
  });

  it('출처에 원장 번호가 여럿이면 원장 차례가 가장 앞인 번호로 적는다', () => {
    const r = 대조(
      [{ 번호: 'REQ-A-001', 설계: 경계만 }, { 번호: 'REQ-A-002' }, { 번호: 'REQ-A-003' }],
      [줄(0, 'REQ-A-003 · REQ-A-002', '예외')],
    );
    expect(r.밖).toEqual(['REQ-A-002 예외']);
  });
});

describe('설계줄들 — PR 머리 줄', () => {
  const 원장 = [{ 번호: 'REQ-A-001', 설계: 둘다 }, { 번호: 'REQ-A-002', 설계: 경계만 }, { 번호: 'REQ-A-003' }];
  const 빈결과: 설계대조결과 = { 빠짐: [], 밖: [], 거절: [], 형식오류: [] };

  it('결과가 없으면 요약 한 줄만', () => {
    expect(설계줄들(원장, null)).toEqual(['설계: 요구 3 중 경계 2 · 예외 1']);
  });

  it('빈 목록은 줄을 안 낸다', () => {
    expect(설계줄들(원장, 빈결과)).toEqual(['설계: 요구 3 중 경계 2 · 예외 1']);
  });

  it('빠짐 · 형식 오류 · 거절 · 밖 차례로, 앞 10 · 3 개만 싣고 넘치면 …', () => {
    const 빠짐 = Array.from({ length: 11 }, (_, i) => `REQ-B-${String(i + 1).padStart(3, '0')} 경계`);
    const 줄들 = 설계줄들(원장, {
      빠짐,
      형식오류: ['가', '나', '다', '라'],
      거절: ['REQ-A-001 경계'],
      밖: ['REQ-A-001 예외', 'REQ-A-002 경계'],
    });
    expect(줄들).toEqual([
      '설계: 요구 3 중 경계 2 · 예외 1',
      `⚠️ 설계 칸 빠짐 11 — ${빠짐.slice(0, 10).join(' · ')} …`,
      '⚠️ 설계 거절 형식 오류 4 — 가 · 나 · 다 …',
      '설계 거절 1 — REQ-A-001 경계',
      '설계 밖 칸 2 — REQ-A-001 예외 · REQ-A-002 경계',
    ]);
  });
});
