// 요구사항 표 합치기 — 같은 서비스를 동시에 작성한 두 요청이 표 끝에 줄을 더한 것을 잇는다 (작성 §3.6 「★ 반영 때 겹침 검사」)
import { describe, expect, it } from 'vitest';

import { 새형식오류, 요구번호다시매기기, 표덩이풀기 } from './authoring-table-merge.js';

const 머리 = '| 요구 | 축 | 전제 | 조작 | 결과 | 출처 | tcId | 작성 시점 |\n|------|----|------|------|------|------|------|----------|';
const 줄 = (번호: number, tcId: string) => `| ${String(번호)} | 정상 | 전제 | 조작 | 결과 | 9 REQ-PAY-${String(번호).padStart(3, '0')} | ${tcId} | 2026-10-01 |`;

function 충돌(우리: string[], 바탕: string[], 그쪽: string[]): string {
  return ['<<<<<<< HEAD', ...우리, '||||||| 바탕', ...바탕, '=======', ...그쪽, '>>>>>>> main'].join('\n');
}

describe('표 덩이 풀기', () => {
  it('양쪽이 같은 자리에 줄을 더하기만 했으면 main 줄 → 이 요청 줄 순으로 잇는다', () => {
    const 글 = ['## 요구사항', '', 머리, 줄(1, 'PAY-001'), 충돌([줄(2, 'PAY-031')], [], [줄(2, 'PAY-040')]), ''].join('\n');
    const 풀림 = 표덩이풀기(글);
    expect(풀림).toEqual({ 글: ['## 요구사항', '', 머리, 줄(1, 'PAY-001'), 줄(2, 'PAY-040'), 줄(2, 'PAY-031'), ''].join('\n') });
  });

  it('덮는 범위 줄을 양쪽이 고쳤으면 이 요청 것을 남긴다', () => {
    const 글 = 충돌(['**덮는 범위** — 자료 9 원장: 요구 4'], ['**덮는 범위** — 자료 1 원장: 요구 2'], ['**덮는 범위** — 자료 7 원장: 요구 3']);
    expect(표덩이풀기(글)).toEqual({ 글: '**덮는 범위** — 자료 9 원장: 요구 4' });
  });

  it('그 밖에 양쪽이 같은 곳을 고쳤으면 풀지 않고 까닭을 낸다', () => {
    const 글 = 충돌([줄(1, 'PAY-001').replace('결과', '바뀐 결과')], [줄(1, 'PAY-001')], [줄(1, 'PAY-001').replace('전제', '다른 전제')]);
    expect(표덩이풀기(글)).toEqual({ 사유: expect.stringContaining('같은 곳') });
  });

  it('충돌 표시가 없으면 그대로 둔다', () => {
    expect(표덩이풀기('그대로\n')).toEqual({ 글: '그대로\n' });
  });
});

describe('요구 차례 번호 다시 매기기', () => {
  it('겹친 번호를 가진 뒤쪽 줄을 그 표의 가장 큰 번호 뒤로 옮긴다', () => {
    const 글 = ['## 요구사항', '', 머리, 줄(1, 'PAY-001'), 줄(2, 'PAY-040'), 줄(3, 'PAY-041'), 줄(2, 'PAY-031'), 줄(3, 'PAY-032'), '', '## 제외', ''].join('\n');
    const 결과 = 요구번호다시매기기(글);
    expect(결과).toContain('| 4 | 정상 | 전제 | 조작 | 결과 | 9 REQ-PAY-002 | PAY-031 |');
    expect(결과).toContain('| 5 | 정상 | 전제 | 조작 | 결과 | 9 REQ-PAY-003 | PAY-032 |');
    expect(결과).toContain(줄(2, 'PAY-040'));
  });

  it('겹친 번호가 없으면 그대로다', () => {
    const 글 = ['## 요구사항', '', 머리, 줄(1, 'PAY-001'), 줄(2, 'PAY-002'), ''].join('\n');
    expect(요구번호다시매기기(글)).toBe(글);
  });
});

describe('합친 표의 새 형식 오류', () => {
  it('양쪽에 없던 형식 오류만 낸다 — main 에 원래 있던 것으로 반영을 막지 않는다', () => {
    const 있는 = new Set(['PAY-001', 'PAY-031']);
    const 그쪽 = ['## 요구사항', '', 머리, 줄(1, 'PAY-001'), ''].join('\n');
    const 우리 = ['## 요구사항', '', 머리, 줄(1, 'PAY-001'), 줄(2, 'PAY-031'), ''].join('\n');
    expect(새형식오류(우리, [우리, 그쪽], 있는)).toEqual([]);
    const 깨진 = ['## 요구사항', '', 머리, 줄(1, 'PAY-001'), 줄(2, 'PAY-031'), 줄(3, 'PAY-099'), ''].join('\n');
    expect(새형식오류(깨진, [우리, 그쪽], 있는)).toEqual([expect.stringContaining('PAY-099')]);
  });
});
