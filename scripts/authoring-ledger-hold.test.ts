// 계정 보류 읽기 · 원장 대조 — 「계정 미등록」 제외와 사람이 제거한 보류가 빠짐으로 안 세어지는지 (도메인/작성 §3.6 「★ 역할별 계정」)
import { describe, expect, it } from 'vitest';

import { 남은번호 } from './authoring-continue.js';
import { 계정보류읽기, 제거함번호들, 제거함읽기 } from './authoring-ledger-hold.js';
import { 원장대조 } from './authoring-ledger-check.js';
import { 기준결정만들기 } from './authoring-ledger-io.js';

const 표 = (요구줄: string[], 제외줄: string[] = []) =>
  [
    '## 요구사항',
    '',
    '| 요구 | 축 | 전제 | 조작 | 결과 | 출처 | tcId | 작성 시점 |',
    '|---|---|---|---|---|---|---|---|',
    ...요구줄,
    '',
    '## 제외',
    '',
    '| 요구 | 종류 | 사유 |',
    '|---|---|---|',
    ...제외줄,
    '',
  ].join('\n');
const 줄 = (출처: string, tcId: string) => `| 1 | 정상 | 전 | 조 | 결 | ${출처} | ${tcId} | 2026-10-12 |`;
const 항목 = ['REQ-A-1', 'REQ-A-2', 'REQ-A-3', 'REQ-A-4'].map((번호) => ({ 번호, 자료: 'a', 지문: '0000000000000000' }));
const 원장값 = { 항목, 가족: { 'REQ-A': 4 }, 모드: { a: '번호' as const }, 경고: [], 빠진자료: [], 꼴: { a: '.md/그대로' } };

describe('제거함 줄 읽기', () => {
  it('출처 칸의 「보류 — <역할> 계정」에서 역할을 뽑고, 없으면 null 이다', () => {
    expect(제거함읽기({ 출처: 'REQ-A-1 · 보류 — 관리자 계정 비밀번호', tcId: '제거함(X-001)' })).toEqual({ 번호들: ['REQ-A-1'], 역할: '관리자' });
    expect(제거함읽기({ 출처: 'REQ-A-2 · 보류 — 일반 회원 계정 아이디', tcId: '`제거함(X-002)`' })?.역할).toBe('일반 회원');
    expect(제거함읽기({ 출처: 'REQ-A-3 · 보류 — 쿠폰 기준이 없다', tcId: '제거함(X-003)' })?.역할).toBeNull();
    expect(제거함읽기({ 출처: 'REQ-A-1', tcId: 'X-001' })).toBeNull();
  });

  it('계정보류읽기는 계정 미등록 제외 줄과 역할이 적힌 제거함 줄을 합친다 — 판정 불가로 뺀 제거함은 안 든다', () => {
    const 글 = 표(
      [줄('REQ-A-1 · 보류 — 관리자 계정 비밀번호', '제거함(X-001)'), 줄('REQ-A-2 · 보류 — 값이 없다', '제거함(X-002)')],
      ['| REQ-A-3 | 계정 미등록 |  판매자  |', '| REQ-A-4 | 계정 미등록 | |'],
    );
    expect([...계정보류읽기(글)]).toEqual([
      ['REQ-A-3', '판매자'],
      ['REQ-A-1', '관리자'],
    ]);
    expect([...제거함번호들(글)]).toEqual(['REQ-A-1', 'REQ-A-2']);
  });
});

describe('원장대조 — 계정 보류', () => {
  it('계정 미등록 제외 줄은 빠짐이 아니고 셈에 종류별로 센다. 역할은 사유 칸이다', () => {
    const r = 원장대조(항목, 표([줄('REQ-A-1', 'X-001')], ['| REQ-A-2 | 계정 미등록 | 관리자 |', '| REQ-A-3 | 계정 미등록 | 관리자 |']), { 에이전트: true, 있는케이스: new Set(['X-001']) });
    expect(r.빠짐).toEqual(['REQ-A-4']);
    expect(r.형식오류).toEqual([]);
    expect(r.셈.제외).toEqual({ '계정 미등록': 2 });
    expect([...r.계정보류]).toEqual([
      ['REQ-A-2', '관리자'],
      ['REQ-A-3', '관리자'],
    ]);
  });

  it('사유가 비면 계정 미등록도 형식 오류다', () => {
    const r = 원장대조(항목, 표([], ['| REQ-A-1 | 계정 미등록 |   |']), { 에이전트: false });
    expect(r.형식오류).toEqual(['제외 줄 「REQ-A-1」 — 사유가 비었다']);
  });

  it('제거함 + 보류 줄은 계정 미등록, 제거함 + 판정 불가 줄은 사람이 뺌으로 센다', () => {
    const 글 = 표([줄('REQ-A-1 · 보류 — 관리자 계정 비밀번호', '제거함(X-001)'), 줄('REQ-A-2 · 보류 — 기준이 없다', '제거함(X-002)')]);
    const r = 원장대조(항목, 글, { 에이전트: false });
    expect(r.빠짐).toEqual(['REQ-A-3', 'REQ-A-4']);
    expect(r.셈.제외).toEqual({ '계정 미등록': 1, '사람이 뺌': 1 });
    expect([...r.계정보류]).toEqual([['REQ-A-1', '관리자']]);
  });

  it('에이전트는 기준 표에 있던 제거함 번호만 인정한다 — 새로 쓴 제거함은 빠짐이다', () => {
    const 글 = 표([줄('REQ-A-1 · 보류 — 관리자 계정 비밀번호', '제거함(X-001)'), 줄('REQ-A-2 · 보류 — 관리자 계정 비밀번호', '제거함(X-002)')]);
    const r = 원장대조(항목, 글, { 에이전트: true, 제거함: new Set(['REQ-A-1']) });
    expect(r.빠짐).toEqual(['REQ-A-2', 'REQ-A-3', 'REQ-A-4']);
    expect(r.셈.제외).toEqual({ '계정 미등록': 1 });
    expect(원장대조(항목, 글, { 에이전트: true }).빠짐).toEqual(['REQ-A-1', 'REQ-A-2', 'REQ-A-3', 'REQ-A-4']);
  });

  it('케이스로 덮인 번호는 케이스가 이긴다 — 제외 셈 · 계정보류에서 빠진다', () => {
    const 글 = 표([줄('REQ-A-1 · 보류 — 관리자 계정 비밀번호', '제거함(X-001)'), 줄('REQ-A-1', 'X-005')], ['| REQ-A-2 | 계정 미등록 | 관리자 |']);
    const r = 원장대조(항목, 글, { 에이전트: false });
    expect(r.셈.케이스).toBe(1);
    expect(r.셈.제외).toEqual({ '계정 미등록': 1 });
    expect([...r.계정보류.keys()]).toEqual(['REQ-A-2']);
  });
});

describe('기준결정과 남은 번호', () => {
  const 기준표글 = 표([줄('REQ-A-1 · 보류 — 관리자 계정 비밀번호', '제거함(X-001)')], ['| REQ-A-2 | 계정 미등록 | 관리자 |', '| REQ-A-3 | 계정 미등록 | 판매자 |']);

  it('기준결정만들기가 기준 표의 제거함 번호를 싣는다', () => {
    expect([...(기준결정만들기({ 표글: 기준표글, 있는케이스: new Set(), 접두사: 'X' }, ['REQ-A-1']).제거함 ?? [])]).toEqual(['REQ-A-1']);
    expect([...(기준결정만들기(null, []).제거함 ?? [])]).toEqual([]);
  });

  it('남은번호는 계정 미등록(제거함 + 보류 줄 포함) 가운데 등록한 역할의 번호만 더한다', () => {
    const 기준 = { 사람이뺌: new Set<string>(), 다음요청: new Set<string>(), 제거함: new Set(['REQ-A-1']) };
    expect(남은번호(원장값, 기준표글, new Set(), 기준)).toEqual(['REQ-A-4']);
    expect(남은번호(원장값, 기준표글, new Set(), 기준, new Set(['관리자']))).toEqual(['REQ-A-1', 'REQ-A-2', 'REQ-A-4']);
    expect(남은번호(원장값, 기준표글, new Set(), 기준, new Set(['관리자', '판매자']))).toEqual(['REQ-A-1', 'REQ-A-2', 'REQ-A-3', 'REQ-A-4']);
  });
});
