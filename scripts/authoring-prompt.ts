// authoring-rules.ts 가 300줄에 닿아 뗐다 (2026-09-30)

import { type 읽을자료, 자료목록글, 자료출처 } from './authoring-assets.js';
import type { 집은것 } from './authoring-rules.js';
import { type 이어작성입력, 이어작성절 } from './authoring-continue.js';
import { type 반영입력, 반영요청인가, 반영절 } from './authoring-apply.js';
import type { 표준기획서입력 } from './authoring-prd-io.js';
import { 역방향절 } from './authoring-reverse.js';

/**
 * 줄에서 집은 작성 요청으로 자식 세션에게 시킬 일.
 *
 * **기획서는 맥이 받아 둔 자료 목록으로 넘긴다** (도메인/작성 §7 「자료」). 경로는 서버의 것이 아니라
 * 맥의 임시 폴더다 — 맥은 다른 기계라 서버의 경로를 못 읽는다.
 * 자료가 없는 옛 행만 본문(`specText`)을 그대로 싣는다.
 */
export function 줄프롬프트(
  것: 집은것,
  서비스: string,
  계획: 읽을자료[],
  대상?: { 폴더: string; 서버들: { env: string; baseUrl: string }[] },
  역방향?: { 화면만: boolean; 산출물폴더: string; 제외?: readonly string[] },
  이어하기?: { 번호: number; 이유: string | null; 까닭: string | null },
  원장?: 원장입력,
  이어작성?: 이어작성입력,
  메모경로?: string,
  표준기획서?: 표준기획서입력 & { 원본: 원장입력; 자료폴더: string },
  반영?: 반영입력,
): string {
  return [
    `/tpx-author 아래 자료로 테스트케이스를 만들어줘. tcId 접두사는 ${서비스} 다.`,
    // tpx-author 가 입력으로 기대한다. 테스트 폴더(서비스 설정의 testsDir — 2026-09-25 계약 변경 승인)와 대상 서버 모두 /api/auth/me 응답의 것이다
    ...(대상 === undefined
      ? []
      : [
          `- 테스트 폴더는 \`tests/${대상.폴더}\` 다.`,
          '- 대상 서버:',
          ...대상.서버들.map((s) => `  - ${s.env} — ${s.baseUrl}`),
        ]),
    '- tpx-author 스킬을 따라라. 다른 체인 스킬은 부르지 마라.',
    '',
    '이 실행에는 답할 사람이 없다. 그래서 이것을 지켜라.',
    '',
    '1. **AskUserQuestion 을 부르지 마라.** 요구사항 표를 파일로 쓰고 그대로 진행해라.',
    '2. **git·gh 를 부르지 마라.** commit·push·PR 은 맥이 한다.',
    '3. **Bash 의 run_in_background 를 쓰지 마라.** 모든 명령을 끝까지 기다려라. **Agent 도구도 백그라운드로 띄우지 마라** — 서브에이전트가 끝날 때까지 기다려라.',
    '4. **끝내기 전에 띄운 명령이 전부 끝났는지 확인해라.** 먼저 끝내면 맥이 멈춘다.',
    '5. **마지막에 tpx-author 의 결과 요약을 찍어라.** 맥이 그것을 PR 본문에 싣는다.',
    // 멈췄다 이어받는 자식에게 넘기는 것은 대화가 아니라 이 파일이다 — 대화를 이어 붙이면 한도를 2배 넘게 쓴다 (§7 「이어하기」 · 2026-10-04)
    ...(메모경로 === undefined ? [] : [`6. **단계 표지를 말할 때마다 진행 메모 \`${메모경로}\` 를 고쳐 써라.** 칸과 규칙은 tpx-author SKILL.md 「진행 메모」다.`]),
    '',
    '관문 넷(형식·표 대조·3회 연속·일부러 부수기)은 전부 돌려라.',
    '',
    // 화면만 · 반영은 기획서가 없다 — 빈 기획서 절을 싣으면 자식이 「기획서가 비었다」로 멈춘다
    ...(계획.length > 0 ? 자료목록글(계획) : 역방향?.화면만 === true || 반영요청인가(것) ? [] : ['--- 기획서 ---', 것.specText ?? '']),
    ...(역방향 === undefined ? [] : 역방향절({ ...역방향, 요청번호: 자료출처(것) })),
    ...(이어하기 === undefined ? [] : 이어하기절(이어하기, 메모경로)),
    ...(원장 === undefined ? [] : 원장절(원장, 서비스, 대상?.폴더)),
    ...(표준기획서 === undefined ? [] : 표준기획서절(표준기획서)),
    ...(이어작성 === undefined ? [] : 이어작성절(이어작성)),
    ...(반영 === undefined ? [] : 반영절(반영, 대상?.서버들)),
  ].join('\n');
}

/** 에이전트가 만든 원장 — 자식에게는 사본 경로만 준다. 판정은 에이전트가 메모리의 원장으로 한다 (§3.6 「★ 원장」) */
export type 원장입력 = { 사본: string; 요약: string; /** main 표의 옛 줄(출처가 원본 번호뿐) 수 — 옮기는 요청만 */ 옛줄?: number } | { 없음: string };

function 원장절(원장: 원장입력, 서비스: string, 폴더: string | undefined): string[] {
  if ('없음' in 원장) {
    return ['', '--- 원장 ---', `원장 없음 — ${원장.없음}. 관문 0 은 건너뛴다. 결과 요약에 「원장 없음」을 적어라.`];
  }
  const 케이스자리 = 폴더 === undefined ? '' : ` --tests tests/${폴더}`;
  return [
    '',
    '--- 원장 ---',
    `표준 기획서 항목이 요구 목록이다(케이스는 표준 기획서만 읽는다): ${원장.사본} — ${원장.요약}`,
    '요구사항 표의 번호마다 **케이스 줄(출처 칸) 또는 「제외」 한 줄**을 둬라. 출처 칸에는 이 사본의 번호(`<접두사>-REQ-001` · 새 항목은 임시 번호 `<접두사>-NEW-001`)를 적는다. 규칙은 `tpx-cases` `references/2-requirements.md` 「원장」이다.',
    `관문 넷 앞에 관문 0(원장 대조)을 돌려라: \`npm run check:ledger -- ${원장.사본} docs/cases/${서비스}.md${케이스자리} --agent\``,
    '**올리기 직전에 에이전트가 같은 대조를 다시 한다** — 빠진 번호는 거절하지 않고 PR 본문 머리와 요청의 셈에 「빠짐」으로 남는다. 그래도 관문 0 을 초록으로 만들어라.',
    ...(원장.옛줄 === undefined || 원장.옛줄 === 0
      ? []
      : [`**옛 표다** — main 표의 요구 줄 ${String(원장.옛줄)}개가 표준 기획서 번호가 아니라 원본 번호를 출처에 적었다(표준 기획서 전에 만든 표). \`.claude/skills/tpx-author/references/prd.md\` §6 대로 표를 표준 기획서 번호로 새로 쓰고 옛 줄과 새 표에 없는 옛 케이스 파일을 지워라. tcId 는 번호 명령이 옛 번호를 물려준다.`]),
  ];
}

/** 옮기기 절 — 자식은 결과 파일을 쓰고 원장 사본을 다시 만든다. 대조 · 올리기 · 번호 바꿔 적기는 에이전트가 한다 (§3.6 「★ 표준 기획서」 「옮기기」) */
function 표준기획서절(입력: 표준기획서입력 & { 원본: 원장입력; 자료폴더: string }): string[] {
  return [
    '',
    '--- 표준 기획서 ---',
    '자료를 다 읽은 뒤 요구사항 표 앞에 자료를 표준 기획서로 옮겨라. 표 · 케이스는 옮긴 표준 기획서만 보고 쓴다. `.claude/skills/tpx-author/references/prd.md` 를 먼저 읽고 따라라.',
    `- 지금 판(판 ${String(입력.판)} · 항목 ${String(입력.항목수)}): ${입력.지금판}`,
    `- 결과를 쓸 곳: ${입력.결과} — 폴더가 없으면 만든다`,
    `- 원본 원장(근거 번호를 적을 때 본다): ${'없음' in 입력.원본 ? `없음 — ${입력.원본.없음}` : `${입력.원본.사본} — ${입력.원본.요약}`}`,
    `- 결과 파일을 쓰거나 고칠 때마다 원장 사본을 다시 만들어라: \`npm run prd:ledger -- ${입력.자료폴더}\``,
    '- 올리기 직전에 에이전트가 이 파일을 원본 원장과 대조하고 서버에 올린 뒤 표의 임시 번호를 받은 번호로 바꿔 적는다. 못 올리면 올리기 거절로 멈춘다.',
  ];
}

/** 중단 이유를 자식에게 사람 말로. 화면 라벨과 같은 말이다 (web/authoringView 의 중단이유라벨) */
const 이유말: Record<string, string> = {
  USER: '사용자가 멈춤',
  TIMEOUT: '시간초과',
  LIMIT: '구독 한도',
  AGENT_RESTART: '에이전트 재시작',
  AGENT_LOST: '에이전트 응답 없음',
  CRASH: '작성 중 끊김',
  REJECTED: '올리기 거절',
};

/** 이어받은 실행에 붙는 절 (도메인/작성 §7 「이어하기」). 무엇을 어떻게 이어가는지는 스킬 참고 파일이 정본이다 */
function 이어하기절(이어하기: { 번호: number; 이유: string | null; 까닭: string | null }, 메모경로?: string): string[] {
  const 이유 = 이어하기.이유 === null ? '기록 없음' : (이유말[이어하기.이유] ?? 이어하기.이유);
  return [
    '',
    '--- 이어하기 ---',
    `이 작업방은 작성 요청 ${이어하기.번호} 이 멈춘 자리다. 멈춘 까닭: ${이유}${이어하기.까닭 === null ? '' : ` — ${이어하기.까닭}`}`,
    '`.claude/skills/tpx-author/references/resume.md` 를 먼저 읽고 따라라. 이미 있는 표·케이스·차이 파일을 버리고 처음부터 하지 마라.',
    ...(메모경로 === undefined
      ? []
      : [`앞 실행의 진행 메모는 \`${메모경로}\` 다(없을 수 있다). 멈춘 까닭이 올리기 거절이면 그것부터 고친 뒤 읽고, 「다음 할 일」부터 하되, 관문은 이어받은 케이스까지 전부 다시 돈다 — 메모의 「끝낸 것」은 관문 통과 기록이 아니다.`]),
  ];
}
