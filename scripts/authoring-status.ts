// 작업방 상태 글을 읽어 올릴 파일 · 지울 새 파일을 고르는 순수 함수 (SPEC 도메인/작성 §3.6 마무리)

/**
 * 작업방 상태(`status --porcelain -uall`)에서 바뀐 파일을 뽑는다. 자식은 커밋을 안 하므로
 * 새 파일은 추적되지 않은 채 남는다 — `diff` 만 보면 새 케이스를 통째로 놓친다.
 * 이름 바꾸기는 옛 자리도 낸다. 옛 자리가 지워진 것도 올려야 하고, 판정도 둘 다 봐야 한다.
 */
export function 바뀐파일들(상태글: string): string[] {
  return 상태글
    .split('\n')
    .filter((줄) => 줄.length > 3)
    .flatMap((줄) => 줄.slice(3).split(' -> '));
}

/**
 * 올리기 전에 지울 파일 — 자식이 tests · docs 밖에 **새로** 남긴 것(실행 로그를 `$로그` 로 저장한 것 같은).
 * 11203 은 그 파일 하나로 케이스 142개를 못 올리고 이어서 작성을 70분 더 돌았다 (작성 §3.6 마무리 · 2026-10-03).
 * 고친 파일 · tests · docs 안의 엉뚱한 파일은 케이스가 쓰는 것일 수 있어 지우지 않고 판정에 맡긴다.
 * 상태는 `-z` 로 읽는다 — 따옴표 · 줄바꿈이 든 이름이 따옴표로 싸여 와 지우기가 헛돈다.
 */
export function 치울새파일들(z글: string): string[] {
  return z글
    .split('\0')
    .filter((항목) => 항목.startsWith('?? '))
    .map((항목) => 항목.slice(3))
    .filter((f) => {
      const 마디 = f.split('/');
      // / 로 끝나는 것은 안쪽 저장소다 — 통째로 지우지 않고 판정이 거절하게 둔다
      return !f.endsWith('/') && !f.startsWith('/') && !마디.includes('..') && 마디[0] !== 'tests' && 마디[0] !== 'docs';
    });
}

const 실을수 = 10;

/**
 * 지운 파일을 사람에게 알리는 한 줄. 작성 요약 머리에 실려 PR 본문 크기를 깎지 않게 열 개까지만 싣는다 —
 * 머리는 통째로 두는 자리라 수천 개면 끝의 바이트 자르기가 관문 3 근거를 깎는다(spec-review B14).
 * 이름의 줄바꿈은 가짜 로그 줄 · 마크다운 줄이 되지 않게 ⏎ 로 바꾼다.
 * 케이스가 그 파일을 쓰면 반영 뒤에 실패하므로 눈에 띄게 경고로 적는다 — 가벼운 길의 CI 는 새 케이스를 안 돌린다.
 */
export function 지운말(지운것: string[]): string | null {
  if (지운것.length === 0) return null;
  const 이름 = 지운것.slice(0, 실을수).map((f) => f.replace(/[\r\n]/g, '⏎'));
  const 나머지 = 지운것.length > 실을수 ? ` 외 ${지운것.length - 실을수}개` : '';
  return `⚠️ 케이스 밖 새 파일 ${지운것.length}개를 지우고 올렸다(케이스가 쓰는 파일이면 tests 안으로 옮겨야 한다): ${이름.join(' · ')}${나머지}`;
}
