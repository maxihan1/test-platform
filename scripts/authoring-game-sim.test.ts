// 게임플레이 시뮬레이션 — 손으로 셀 수 있는 작은 판으로 처치 시각 · 몰림 · 자라는 시간 · 줍기 · 손 빠르기 · 정책 차례 · 쿨타임 · 업그레이드 · 문턱 찾기 · 재현 · 입력 오류를 본다
import { describe, expect, it } from 'vitest';

import { 시뮬 } from './authoring-game-calc.js';
import { type 모델, 입력읽기 } from './authoring-game-sim-input.js';
import { 찾기 } from './authoring-game-sim-run.js';
import { type 행동, 돌리기 } from './authoring-game-sim.js';

const 기본 = (덧: Record<string, unknown> = {}): Record<string, unknown> => ({
  계산: '시뮬',
  곳: 'stage:시험',
  지킬것: { 체력: 10, 자리: [10, 0] },
  길: { 가: [[0, 0], [10, 0]] },
  적종류: [{ 이름: '슬라임', 체력: 10, 속도: 1, 닿으면피해: 5, 보상: 1 }],
  웨이브: [{ 이름: '1웨이브', 출현: [{ 종류: '슬라임', 수: 1, 간격: 0, 길: '가' }] }],
  설치물종류: [{ 이름: '탑', 레벨: [{ 값: 0, 사거리: 3, 공격력: 5, 간격: 2 }] }],
  자리후보: [[5, 1]],
  캐릭터: { 자리: [5, 1], 걷기속도: 1 },
  재화: { 시작: 0 },
  볼값연결: { 웨이브: '웨이브', 지킬것: '세계수', 재화: '고기' },
  정책: [{ 조건: [], 행동: { 무엇: '놓기', 대상: '탑' } }],
  ...덧,
});
const 모델로 = (입력: Record<string, unknown>): 모델 => {
  const m = 입력읽기(입력);
  if ('틀림' in m) throw new Error(m.틀림);
  return m;
};
const 한판 = (입력: Record<string, unknown>) => { const m = 모델로(입력); return 돌리기(m, m.정책들[0]!); };

describe('시간을 흘리기', () => {
  it('적이 사거리에 든 때부터 간격마다 맞아 손으로 센 시각에 죽는다', () => {
    const r = 한판(기본());
    expect(r.이김).toBe(true);
    expect(r.웨이브[0]).toMatchObject({ 처치: 1, 새어나감: 0, 끝지킬것: 10 });
    // 사거리 3 원에 x ≥ 5 − √8 ≈ 2.17 에서 들고(2.1초) 두 대째가 2초 뒤
    expect(r.웨이브[0]!.끝초).toBeCloseTo(4.1, 1);
  });

  it('같은 설치물로 퍼져 오면 버티고 몰려 오면 못 버틴다 — 체력 합만 보던 계산이 못 가르던 것', () => {
    const 웨 = (간격: number) => [{ 출현: [{ 종류: '슬라임', 수: 5, 간격, 길: '가' }] }];
    expect(한판(기본({ 지킬것: { 체력: 20, 자리: [10, 0] }, 웨이브: 웨(6) })).이김).toBe(true);
    const 몰림 = 한판(기본({ 지킬것: { 체력: 20, 자리: [10, 0] }, 웨이브: 웨(0) }));
    expect(몰림.이김).toBe(false);
    expect(몰림.짐).toMatchObject({ 웨이브: '1웨이브' });
  });

  it('자라는 시간 동안은 안 때려 그 사이 적이 지나간다', () => {
    const r = 한판(기본({ 설치물종류: [{ 이름: '탑', 자라는초: 10, 레벨: [{ 값: 0, 사거리: 3, 공격력: 5, 간격: 2 }] }] }));
    expect(r.이김).toBe(true);
    expect(r.웨이브[0]).toMatchObject({ 처치: 0, 새어나감: 1, 끝지킬것: 5 });
  });

  it('줍기 게임은 처치 자리에 떨어진 재화를 주워야 들어온다', () => {
    const 정책 = [{ 조건: [], 행동: { 무엇: '놓기', 대상: '탑' } }, { 조건: [], 행동: { 무엇: '줍기' } }];
    expect(한판(기본({ 정책 })).웨이브[0]!.끝재화).toBe(1);
    expect(한판(기본({ 재화: { 시작: 0, 줍기: true } })).웨이브[0]!.끝재화).toBe(0);
    const 주움 = 한판(기본({ 재화: { 시작: 0, 줍기: true }, 웨이브: [{ 출현: [{ 종류: '슬라임', 수: 1, 간격: 0, 길: '가' }] }, { 쉬는초: 20, 출현: [{ 종류: '슬라임', 수: 1, 간격: 0, 길: '가' }] }], 정책 }));
    expect(주움.웨이브[0]!.끝재화).toBe(0);
    expect(주움.웨이브[1]!.끝재화).toBe(2);
    expect(주움.행동기록.map((x) => x.행동)).toContain('줍기');
  });

  it('손이 느리면 놓는 것이 늦어 진다', () => {
    expect(한판(기본({ 손: { 행동초: 0.5 } })).웨이브[0]!.처치).toBe(1);
    expect(한판(기본({ 손: { 행동초: 7 } })).웨이브[0]).toMatchObject({ 처치: 0, 새어나감: 1 });
  });

  it('웨이브는 앞 웨이브가 끝나고 쉬는초 뒤에 시작하고, 2초마다 볼값 이름으로 예상 값을 남긴다', () => {
    const r = 한판(기본({ 웨이브: [{ 출현: [{ 종류: '슬라임', 수: 1, 간격: 0, 길: '가' }] }, { 쉬는초: 5, 보스: true, 출현: [{ 종류: '슬라임', 수: 1, 간격: 0, 길: '가' }] }] }));
    expect(r.웨이브.map((w) => w.끝초)).toEqual([expect.closeTo(4.1, 1), expect.closeTo(13.2, 1)]);
    expect(r.예상[0]).toEqual({ 초: 0, 값: { 웨이브: 1, 세계수: 10, 고기: 0 } });
    expect(r.예상.find((x) => x.초 === 6)?.값.웨이브).toBe(1);
    expect(r.예상.find((x) => x.초 === 10)?.값.웨이브).toBe(2);
  });
});

describe('캐릭터 판단 — 정책', () => {
  it('위에서부터 할 수 있는 첫 규칙을 한다 — 재화가 되면 키우기가 놓기보다 먼저', () => {
    const r = 한판(기본({ 재화: { 시작: 10 }, 설치물종류: [{ 이름: '탑', 레벨: [{ 값: 5, 사거리: 3, 공격력: 5, 간격: 2 }, { 값: 5, 사거리: 3, 공격력: 10, 간격: 2 }] }], 정책: [{ 조건: [], 행동: { 무엇: '키우기', 대상: '탑' } }, { 조건: [], 행동: { 무엇: '놓기', 대상: '탑' } }] }));
    expect(r.행동기록.map((x) => `${x.행동}:${String(x.됨)}`)).toEqual(['놓기:true', '키우기:true']);
    expect(r.웨이브[0]).toMatchObject({ 처치: 1, 끝재화: 1 });
  });

  it('아이템은 쿨타임 동안 다시 안 쓴다', () => {
    const r = 한판(기본({
      지킬것: { 체력: 100, 자리: [10, 0] },
      웨이브: [{ 출현: [{ 종류: '슬라임', 수: 3, 간격: 3, 길: '가' }] }],
      아이템: [{ 이름: '폭탄', 쿨타임: 10, 사거리: 50, 범위: 10, 피해: 100 }],
      정책: [{ 조건: [{ 값: '지킬것둘레적수', 반경: 100, 비교: '>=', 기준: 1 }], 행동: { 무엇: '아이템', 대상: '폭탄' } }],
    }));
    expect(r.이김).toBe(true);
    expect(r.행동기록.filter((x) => x.행동 === '아이템').map((x) => x.끝초)).toEqual([0, 10]);
    expect(r.웨이브[0]).toMatchObject({ 처치: 3, 새어나감: 0 });
  });

  it('캐릭터가 길 끝 바로 앞에서 죽인 적은 다음 칸에 새어 나가지 않고 처치로 센다', () => {
    const r = 한판(기본({
      지킬것: { 체력: 10, 자리: [10.25, 0] },
      길: { 가: [[0, 0], [10.25, 0]] },
      적종류: [{ 이름: '슬라임', 체력: 10, 속도: 5, 닿으면피해: 5, 보상: 1 }],
      설치물종류: [{ 이름: '탑', 레벨: [{ 값: 99, 사거리: 3, 공격력: 5, 간격: 2 }] }],
      아이템: [{ 이름: '폭탄', 쿨타임: 100, 사거리: 50, 범위: 0.5, 피해: 100 }],
      정책: [{ 조건: [{ 값: '지킬것가까운적거리', 비교: '<=', 기준: 0.3 }], 행동: { 무엇: '아이템', 대상: '폭탄' } }],
    }));
    expect(r.웨이브[0]).toMatchObject({ 처치: 1, 새어나감: 0, 끝지킬것: 10, 끝재화: 1 });
  });

  it('쿨타임은 걷는 동안에도 돈다 — 걸어간 뒤 쿨타임을 또 기다리지 않는다', () => {
    const r = 한판(기본({
      지킬것: { 체력: 100, 자리: [100, 0] },
      길: { 가: [[0, 0], [100, 0]], 나: [[0, 6], [100, 6]] },
      적종류: [{ 이름: '슬라임', 체력: 10, 속도: 0.1, 닿으면피해: 5, 보상: 1 }],
      웨이브: [{ 출현: [{ 종류: '슬라임', 수: 1, 간격: 0, 길: '가' }, { 종류: '슬라임', 수: 1, 간격: 0, 길: '나' }] }],
      설치물종류: [{ 이름: '탑', 레벨: [{ 값: 99, 사거리: 3, 공격력: 5, 간격: 2 }] }],
      캐릭터: { 자리: [0, 0], 걷기속도: 1, 공격: { 사거리: 1, 공격력: 10, 간격: 3 } },
      정책: [{ 조건: [], 행동: { 무엇: '공격' } }],
    }));
    const 끝 = r.행동기록.filter((x) => x.행동 === '공격').map((x) => x.끝초!);
    expect(r.웨이브[0]!.처치).toBe(2);
    expect(끝[1]! - 끝[0]!).toBeLessThan(6);
  });

  it('놓기는 덮는 길이가 같으면 자리후보에 적은 차례로 고른다 — 판 함수가 받는 자리차례와 같다', () => {
    const r = 한판(기본({ 자리후보: [[5, -1], [5, 1]], 캐릭터: { 자리: [5, 1], 걷기속도: 1 } }));
    expect(r.행동기록[0]!.자리).toEqual([5, -1]);
  });

  it('회복은 재화를 내고 지킬것을 채운다', () => {
    const r = 한판(기본({ 재화: { 시작: 3 }, 웨이브: [{ 출현: [{ 종류: '슬라임', 수: 2, 간격: 15, 길: '가' }] }], 설치물종류: [{ 이름: '탑', 자라는초: 10, 레벨: [{ 값: 0, 사거리: 3, 공격력: 5, 간격: 2 }] }], 회복: [{ 이름: '물주기', 대상: '지킬것', 값: 3, 양: 4 }], 정책: [{ 조건: [{ 값: '지킬것비율', 비교: '<', 기준: 1 }], 행동: { 무엇: '회복', 대상: '물주기' } }, { 조건: [], 행동: { 무엇: '놓기', 대상: '탑' } }] }));
    expect(r.웨이브[0]).toMatchObject({ 처치: 1, 새어나감: 1, 끝지킬것: 9, 끝재화: 1 });
  });

  it('문턱 후보를 다 돌려 이기는 조합을 고르고, 이웃 문턱이 지면 여유가 낮다', () => {
    const m = 모델로(기본({
      지킬것: { 체력: 5, 자리: [10, 0] },
      설치물종류: [{ 이름: '탑', 레벨: [{ 값: 99, 사거리: 3, 공격력: 5, 간격: 2 }] }],
      아이템: [{ 이름: '폭탄', 쿨타임: 100, 사거리: 50, 범위: 0.5, 피해: 100 }],
      손: { 행동초: 1.5 },
      정책: [{ 조건: [{ 값: '지킬것가까운적거리', 비교: '<=', 기준: '$거리' }], 행동: { 무엇: '아이템', 대상: '폭탄' } }],
      문턱후보: { 거리: [1, 8] },
    }));
    const r = 찾기(m);
    expect(r).toMatchObject({ 이긴수: 1, 전체: 2, 가장: { 문턱: { 거리: 8 }, 여유: 0 } });
  });

  it('재현은 정책 대신 판 행동기록을 그 시각에 그대로 한다', () => {
    const m = 모델로(기본());
    const 빨리: 행동[] = [{ 초: 0, 행동: '놓기', 대상: '탑', 자리: [5, 1], 끝초: 0.1 }];
    const 늦게: 행동[] = [{ 초: 0, 행동: '놓기', 대상: '탑', 자리: [5, 1], 도착초: 6, 끝초: 7.5 }];
    expect(돌리기(m, [], undefined, 빨리).웨이브[0]!.처치).toBe(1);
    expect(돌리기(m, [], undefined, 늦게).웨이브[0]).toMatchObject({ 처치: 0, 새어나감: 1 });
  });
});

describe('길 끝 머무름 피해 · 유지비', () => {
  it('끝초당피해 가 있는 적은 길 끝에 서서 죽을 때까지 지킬것을 깎는다 — 한 번 깎고 사라지면 낙관적이다(16100 첫 맵)', () => {
    const 서는적 = [{ 이름: '슬라임', 체력: 10, 속도: 1, 닿으면피해: 0, 보상: 1, 끝초당피해: 0.5 }];
    const 진 = 한판(기본({ 적종류: 서는적, 설치물종류: [{ 이름: '탑', 레벨: [{ 값: 99, 사거리: 3, 공격력: 5, 간격: 2 }] }] }));
    expect(진.이김).toBe(false);
    expect(진.짐).toMatchObject({ 웨이브: '1웨이브' });
    const 끝탑 = 한판(기본({ 적종류: 서는적, 자리후보: [[10, 1]], 캐릭터: { 자리: [0, 5], 걷기속도: 0.5 }, 설치물종류: [{ 이름: '탑', 레벨: [{ 값: 0, 사거리: 2, 공격력: 5, 간격: 2 }] }] }));
    expect(끝탑.이김).toBe(true);
    expect(끝탑.웨이브[0]).toMatchObject({ 처치: 1, 새어나감: 1 });
    expect(끝탑.웨이브[0]!.끝지킬것).toBeLessThan(10);
  });

  it('유지 가 있는 설치물은 체력이 시간에 따라 줄어 다하면 멈추고, 먹이를 주면 다시 차고, 유지없음 레벨은 안 준다', () => {
    const 늦은웨이브 = [{ 시작초: 120, 출현: [{ 종류: '슬라임', 수: 1, 간격: 0, 길: '가' }] }];
    const 유지 = { 체력: 5, 초당감소: 0.05, 다하면: '멈춤', 먹이: { 값: 3, 양: 5, 초: 10 }, 근거: 'rule:식물 유지' };
    expect(입력읽기(기본({ 설치물종류: [{ 이름: '탑', 유지: { ...유지, 근거: undefined }, 레벨: [{ 값: 0, 사거리: 3, 공격력: 5, 간격: 2 }] }] }))).toMatchObject({ 틀림: expect.stringContaining('근거') });
    const 탑 = (레벨덧 = {}) => [{ 이름: '탑', 유지, 레벨: [{ 값: 0, 사거리: 3, 공격력: 5, 간격: 2, ...레벨덧 }] }];
    const 굶음 = 한판(기본({ 웨이브: 늦은웨이브, 설치물종류: 탑() }));
    expect(굶음.웨이브[0]).toMatchObject({ 처치: 0, 새어나감: 1 });
    const 먹임 = 한판(기본({ 웨이브: 늦은웨이브, 설치물종류: 탑(), 재화: { 시작: 30 }, 정책: [{ 조건: [{ 값: '유지최저비율', 비교: '<', 기준: 0.5 }], 행동: { 무엇: '먹이', 대상: '탑' } }, { 조건: [], 행동: { 무엇: '놓기', 대상: '탑' } }] }));
    expect(먹임.웨이브[0]).toMatchObject({ 처치: 1, 새어나감: 0 });
    const 먹이들 = 먹임.행동기록.filter((x) => x.행동 === '먹이');
    expect(먹이들.length).toBeGreaterThanOrEqual(2);
    expect(먹이들[0]!.끝초! - 먹이들[0]!.도착초!).toBeGreaterThanOrEqual(10);
    expect(먹임.웨이브[0]!.끝재화).toBe(30 - 3 * 먹이들.length + 1);
    expect(한판(기본({ 웨이브: 늦은웨이브, 설치물종류: 탑({ 유지없음: true }) })).웨이브[0]).toMatchObject({ 처치: 1 });
    const 올림 = 한판(기본({ 웨이브: 늦은웨이브, 재화: { 시작: 0, 초당: 0.1 }, 설치물종류: [{ 이름: '탑', 유지, 레벨: [{ 값: 0, 사거리: 3, 공격력: 5, 간격: 2 }, { 값: 10.5, 사거리: 3, 공격력: 5, 간격: 2, 유지없음: true }] }], 정책: [{ 조건: [], 행동: { 무엇: '키우기', 대상: '탑' } }, { 조건: [], 행동: { 무엇: '놓기', 대상: '탑' } }] }));
    expect(올림.행동기록.find((x) => x.행동 === '키우기')!.끝초).toBeGreaterThan(100);
    expect(올림.웨이브[0]).toMatchObject({ 처치: 1, 새어나감: 0 });
    const 사라짐 = 한판(기본({ 웨이브: 늦은웨이브, 설치물종류: [{ ...탑()[0]!, 유지: { ...유지, 다하면: '사라짐' } }] }));
    expect(사라짐.행동기록.filter((x) => x.행동 === '놓기').length).toBe(2);
    expect(사라짐.웨이브[0]).toMatchObject({ 처치: 1 });
  });
});

describe('입력 · 계산기', () => {
  it('정책이 쓴 문턱의 후보가 없거나 대상이 없으면 무엇이 틀렸나 알린다', () => {
    expect(입력읽기(기본({ 정책: [{ 조건: [{ 값: '재화', 비교: '>=', 기준: '$값' }], 행동: { 무엇: '놓기', 대상: '탑' } }] }))).toMatchObject({ 틀림: expect.stringContaining('$값') });
    expect(입력읽기(기본({ 정책: [{ 조건: [], 행동: { 무엇: '놓기', 대상: '성' } }] }))).toMatchObject({ 틀림: expect.stringContaining('설치물종류') });
    expect(입력읽기(기본({ 정책: [{ 조건: [{ 값: '지킬것둘레적수', 비교: '>=', 기준: 1 }], 행동: { 무엇: '줍기' } }] }))).toMatchObject({ 틀림: expect.stringContaining('반경') });
    expect(입력읽기(기본({ 웨이브: [{ 출현: [{ 종류: '유령', 수: 1, 간격: 0, 길: '가' }] }] }))).toMatchObject({ 틀림: expect.stringContaining('웨이브 1번') });
  });

  it('계산기 시뮬은 고른 정책과 웨이브마다 결과를 줄 data 에 싣고, 못 이기면 가장 멀리 간 안을 알린다', () => {
    const r = 시뮬(기본({ 자리후보: [[5, 9], [5, 1]] }));
    expect('줄글' in r && r.줄글.join('\n')).toContain('"자리차례":{"탑":[[5,1],[5,9]]}');
    expect(r).toMatchObject({ 이름: '시뮬', 글: expect.stringContaining('이기는 안 있음'), 결과: { 계산: '시뮬', 이김: true, 정책: [{ 행동: { 무엇: '놓기' } }], 손: { 행동초: 0.5 } }, 입력요약: { 엔진판: 2, 웨이브수: 1, 보스: false } });
    expect(시뮬(기본({ 지킬것: { 체력: 4, 자리: [10, 0] }, 설치물종류: [{ 이름: '탑', 레벨: [{ 값: 0, 사거리: 3, 공격력: 1, 간격: 2 }] }] }))).toMatchObject({ 글: expect.stringContaining('이기는 안 없음'), 결과: { 이김: false, 짐: { 웨이브: '1웨이브' } } });
  });
});
