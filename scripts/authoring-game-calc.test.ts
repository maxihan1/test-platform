// 게임 전략 계산기 — 길 덮기 · 버티기 · 재화 예산 · 설치 자리 · 입력 형태 오류를 손으로 센 값과 비교한다
import { describe, expect, it } from 'vitest';

import { 계산하기, 버티기, 예산, 원안길이, 자리, 줄초안 } from './authoring-game-calc.js';

const 직선 = [[0, 0], [10, 0]] as const;
type 결과 = Exclude<ReturnType<typeof 버티기>, { 틀림: string }>;

describe('길 덮기', () => {
  it('원이 길을 가로지르면 현의 길이, 길 한쪽 끝이 원 안이면 거기까지, 안 닿으면 0', () => {
    expect(원안길이(직선, { 중심: [5, 0], 반지름: 3 })).toBeCloseTo(6);
    expect(원안길이(직선, { 중심: [5, 3], 반지름: 5 })).toBeCloseTo(8);
    expect(원안길이(직선, { 중심: [0, 0], 반지름: 2 })).toBeCloseTo(2);
    expect(원안길이(직선, { 중심: [5, 4], 반지름: 3 })).toBe(0);
  });

  it('꺾인 길은 선분마다 더하고, 선분 밖으로 이어진 직선 부분은 안 센다', () => {
    expect(원안길이([[0, 0], [4, 0], [4, 6]], { 중심: [4, 0], 반지름: 2 })).toBeCloseTo(4);
    expect(원안길이([[0, 0], [2, 0]], { 중심: [10, 0], 반지름: 7 })).toBe(0);
  });
});

describe('버틸 수 있나', () => {
  const 입력 = (체력: number) => ({
    길: [[0, 0], [10, 0]],
    설치물: [{ 이름: '화살탑', 자리: [5, 0], 사거리: 3, 공격력: 10, 간격: 2, 타깃수: 2 }],
    웨이브: [{ 이름: '1웨이브', 적: [{ 종류: '슬라임', 수: 4, 체력, 속도: 2 }] }],
  });

  it('피해 합은 공격력 / 간격 × 덮은 길 / 속도 × 적 수이고 체력 합과 비교해 모자란 양을 낸다', () => {
    const 못 = 버티기(입력(20)) as 결과;
    expect(못.결과).toMatchObject({ 웨이브: [{ 체력합: 80, 피해합: 60, 버팀: false, 모자란: 20 }], 처음못버팀: '1웨이브' });
    expect(못.줄글.join('\n')).toContain('초당 10');
    expect(못.글).toContain('1웨이브 에서 못 버틴다');
    expect(버티기(입력(15))).toMatchObject({ 결과: { 웨이브: [{ 체력합: 60, 버팀: true, 모자란: 0 }], 처음못버팀: null } });
  });

  it('부터 를 쓰면 그 웨이브부터만 피해에 든다', () => {
    const 늦음 = { ...입력(10), 설치물: [{ ...입력(10).설치물[0]!, 부터: 2 }] };
    expect(버티기(늦음)).toMatchObject({ 결과: { 웨이브: [{ 피해합: 0, 버팀: false }] } });
  });

  it('입력 형태가 틀리면 무엇이 틀렸나 돌려준다', () => {
    expect(버티기({ ...입력(10), 길: [[0, 0]] })).toMatchObject({ 틀림: expect.stringContaining('길') });
    expect(버티기({ ...입력(10), 웨이브: [{ 적: [{ 종류: 'a', 수: 1, 체력: 1, 속도: 0 }] }] })).toMatchObject({ 틀림: expect.stringContaining('웨이브 1번') });
    expect(버티기({ ...입력(10), 설치물: [{ 이름: 'x' }] })).toMatchObject({ 틀림: expect.stringContaining('설치물 1번') });
  });
});

describe('재화 예산', () => {
  it('웨이브마다 남는 양을 쌓고, 시작에 가진 양보다 지출이 큰 첫 웨이브를 알려 준다', () => {
    const r = 예산({
      시작: 100,
      웨이브: [
        { 이름: '1웨이브', 지출: [{ 무엇: '탑 설치', 값: 60 }], 처치: 10, 보상: 5 },
        { 이름: '2웨이브', 웨이브보상: 20, 지출: [{ 무엇: '레벨업', 값: 50, 수: 2 }], 처치: 10, 보상: 5 },
        { 이름: '3웨이브', 지출: [{ 무엇: '치료', 값: 10 }], 유지비: 5 },
      ],
    }) as 결과;
    expect(r.결과).toMatchObject({ 웨이브: [{ 남음: 90, 모자람: false }, { 가진: 110, 지출: 100, 남음: 60, 모자람: false }, { 남음: 45 }], 처음모자람: null });
    expect(예산({ 시작: 10, 웨이브: [{ 이름: 'a', 지출: [{ 무엇: '탑', 값: 20 }] }] })).toMatchObject({ 결과: { 처음모자람: 'a' } });
  });

  it('입력 형태 오류', () => {
    expect(예산({ 웨이브: [] })).toMatchObject({ 틀림: expect.stringContaining('웨이브') });
    expect(예산({ 웨이브: [{ 지출: [{ 무엇: '탑' }] }] })).toMatchObject({ 틀림: expect.stringContaining('웨이브 1번') });
  });
});

describe('설치 자리 고르기', () => {
  it('길을 많이 덮는 자리 순으로 놓고 못 놓는 원 안은 뺀다', () => {
    const r = 자리({ 길: 직선, 사거리: 3, 후보: [{ 이름: '끝', 자리: [0, 0] }, { 이름: '가운데', 자리: [5, 0] }, { 이름: '멀리', 자리: [5, 9] }, { 이름: '웅덩이', 자리: [6, 1] }], 못놓는곳: [{ 중심: [6, 1], 반지름: 1 }] }) as 결과;
    expect(r.결과).toMatchObject({ 순서: [{ 이름: '가운데', 덮음: 6 }, { 이름: '끝', 덮음: 3 }, { 이름: '멀리', 덮음: 0 }], 뺌: ['웅덩이'] });
    expect(자리({ 길: 직선, 사거리: 0, 후보: [] })).toMatchObject({ 틀림: expect.any(String) });
  });
});

describe('계산하기 · CALC 줄 초안', () => {
  it('계산 이름이 틀리면 알려 주고, 이름은 입력의 이름 · 없으면 파일 이름이며 줄은 짐작(GUESS) CALC 다', () => {
    expect(계산하기({ 계산: '점치기' }, 'x')).toMatchObject({ 틀림: expect.stringContaining('버티기') });
    const 입력 = { 계산: '예산', 곳: 'stage:둘째 맵', 빌드데이터: true, 시작: 5, 웨이브: [{ 지출: [{ 무엇: 'a', 값: 1 }] }] };
    const r = 계산하기(입력, '둘째 맵 예산');
    expect(r).not.toHaveProperty('틀림');
    expect(줄초안(r as 결과, 입력)).toMatchObject({ kind: 'CALC', key: 'calc:둘째 맵 예산', learned: { belief: 'GUESS', data: { 곳: 'stage:둘째 맵', 출처: '빌드 데이터' } } });
  });
});
