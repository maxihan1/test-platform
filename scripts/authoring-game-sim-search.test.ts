// 순서 찾기 — 규칙 자리를 바꿔 이기는 순서를 찾나 · 문턱 격자 · 점수 차례 · 입력 규칙으로 만든 순서만 받나 · 손 재기
import { describe, expect, it } from 'vitest';

import { type 모델, 입력읽기 } from './authoring-game-sim-input.js';
import { 손넣기, 손셈 } from './authoring-game-sim-run.js';
import { 나은가, 문턱격자, 입력정책인가, 점수, 정책글, 찾기 } from './authoring-game-sim-search.js';

const 기본 = (덧: Record<string, unknown> = {}): Record<string, unknown> => ({
  계산: '시뮬',
  곳: 'stage:시험',
  지킬것: { 체력: 5, 자리: [10, 0] },
  길: { 가: [[0, 0], [10, 0]] },
  적종류: [{ 이름: '슬라임', 체력: 10, 속도: 1, 닿으면피해: 5, 보상: 1 }],
  웨이브: [{ 이름: '1웨이브', 출현: [{ 종류: '슬라임', 수: 1, 간격: 0, 길: '가' }] }],
  설치물종류: [{ 이름: '탑', 레벨: [{ 값: 0, 사거리: 3, 공격력: 5, 간격: 2 }] }],
  자리후보: [[5, 1]],
  캐릭터: { 자리: [5, 1], 걷기속도: 1 },
  재화: { 시작: 0 },
  정책: [{ 조건: [], 행동: { 무엇: '놓기', 대상: '탑' } }],
  ...덧,
});
const 모델로 = (입력: Record<string, unknown>): 모델 => {
  const m = 입력읽기(입력);
  if ('틀림' in m) throw new Error(m.틀림);
  return m;
};
const 찾은 = (m: 모델) => {
  const r = 찾기(m);
  if ('틀림' in r) throw new Error(r.틀림);
  return r;
};

describe('순서 찾기', () => {
  it('AI 가 적은 순서가 지면 규칙 자리를 바꿔 이기는 순서를 찾는다', () => {
    const 멀리먼저 = [{ 조건: [], 행동: { 무엇: '이동', 자리: [5, 21] } }, { 조건: [], 행동: { 무엇: '놓기', 대상: '탑' } }];
    const r = 찾은(모델로(기본({ 정책: 멀리먼저 })));
    expect(r.가장?.정책.map((x) => x.행동.무엇)).toEqual(['놓기', '이동']);
    expect(r.가장멀리).toBe(r.가장);
    expect(r).toMatchObject({ 이긴수: 1, 전체: 2 });
  });

  it('이기는 순서가 없으면 가장 멀리 간 순서를 낸다', () => {
    const r = 찾은(모델로(기본({ 설치물종류: [{ 이름: '탑', 레벨: [{ 값: 0, 사거리: 3, 공격력: 1, 간격: 2 }] }] })));
    expect(r.가장).toBeNull();
    expect(r.가장멀리.결과.짐).toMatchObject({ 웨이브: '1웨이브' });
  });

  it('문턱은 AI 후보에 엔진이 더한다 — 재화는 모델의 값표, 비율과 마릿수는 정해 둔 값', () => {
    const m = 모델로(기본({
      설치물종류: [{ 이름: '탑', 레벨: [{ 값: 5, 사거리: 3, 공격력: 5, 간격: 2 }, { 값: 4, 사거리: 3, 공격력: 5, 간격: 2 }, { 값: 8, 사거리: 3, 공격력: 5, 간격: 2 }] }],
      정책: [
        { 조건: [{ 값: '재화', 비교: '>=', 기준: '$모음' }], 행동: { 무엇: '키우기', 대상: '탑' } },
        { 조건: [{ 값: '지킬것비율', 비교: '<', 기준: '$낮음' }, { 값: '지킬것둘레적수', 반경: 5, 비교: '>=', 기준: '$몰림' }, { 값: '지킬것가까운적거리', 비교: '<=', 기준: '$거리' }], 행동: { 무엇: '놓기', 대상: '탑' } },
      ],
      문턱후보: { 모음: [6], 낮음: [0.4], 몰림: [2], 거리: [4] },
    }));
    expect(문턱격자(m)).toEqual({ 모음: [4, 5, 6, 8, 9, 17], 낮음: [0.2, 0.35, 0.4, 0.5, 0.65, 0.8], 몰림: [1, 2, 3, 5, 8], 거리: [4] });
  });

  it('점수는 이김 → 손이 느려도 이김 → 지킬것이 가장 낮았던 값 → 남은 재화 차례다', () => {
    const 안 = (이김: boolean, 느려도이김: boolean, 지킬것들: number[], 끝재화: number) => 점수({ 느려도이김, 결과: { 이김, 웨이브: 지킬것들.map((끝지킬것, i) => ({ 이름: `${i + 1}웨이브`, 처치: 0, 새어나감: 0, 끝지킬것, 끝재화, 끝초: 0 })), 예상: [], 행동기록: [], ...(이김 ? {} : { 짐: { 웨이브: '', 초: 30, 새어나간체력: 0, 쥔재화: 0 } }) } });
    expect(나은가(안(true, false, [50, 50], 0), 안(false, false, [50, 50, 50], 99))).toBe(true);
    expect(나은가(안(true, true, [20, 20], 0), 안(true, false, [50, 50], 99))).toBe(true);
    expect(나은가(안(true, true, [50, 30], 0), 안(true, true, [20, 40], 99))).toBe(true);
    expect(나은가(안(true, true, [50, 30], 5), 안(true, true, [50, 30], 4))).toBe(true);
    expect(나은가(안(false, false, [50, 50], 0), 안(false, false, [50], 0))).toBe(true);
    expect(나은가(안(true, true, [50], 5), 안(true, true, [50], 5))).toBe(false);
  });

  it('입력 파일의 규칙으로 만든 순서만 받는다 — 자리 · 문턱 값 · 키우기 고르기는 달라도 되고 다른 행동은 안 된다', () => {
    const m = 모델로(기본({
      설치물종류: [{ 이름: '탑', 레벨: [{ 값: 0, 사거리: 3, 공격력: 5, 간격: 2 }, { 값: 9, 사거리: 3, 공격력: 5, 간격: 2 }] }],
      정책: [{ 조건: [{ 값: '재화', 비교: '>=', 기준: '$모음' }], 행동: { 무엇: '키우기', 대상: '탑' } }, { 조건: [], 행동: { 무엇: '놓기', 대상: '탑' } }],
      문턱후보: { 모음: [4] },
    }));
    const 놓기 = { 조건: [], 행동: { 무엇: '놓기' as const, 대상: '탑' } };
    const 키우기 = (기준: number | string, 비교: '>=' | '<' = '>=') => ({ 조건: [{ 값: '재화' as const, 비교, 기준 }], 행동: { 무엇: '키우기' as const, 대상: '탑', 고르기: '높은' as const } });
    expect(입력정책인가(m, [놓기, 키우기(9)])).toBe(true);
    expect(입력정책인가(m, [놓기, 키우기('$모음')])).toBe(false);
    expect(입력정책인가(m, [놓기, 키우기(9, '<')])).toBe(false);
    expect(입력정책인가(m, [놓기, { 조건: [], 행동: { 무엇: '줍기' } }])).toBe(false);
    expect(입력정책인가(m, [])).toBe(false);
    expect(정책글([놓기, 키우기(9)])).toBe('놓기 탑 > 키우기 탑·높은(재화≥9)');
  });
});

describe('손 재기', () => {
  it('행동 하나에 든 초는 읽고 고른 시간과 도착해서 끝낸 시간의 합이고, 종류는 셋 이상일 때만, 걷는 속도는 3초 넘게 걸었을 때만 낸다', () => {
    const 줍 = (초: number) => ({ 초, 행동: '줍기', 시작초: 초 + 0.2, 도착초: 초 + 2.2, 끝초: 초 + 2.2, 걸음: 4 });
    const 잰 = 손셈([줍(0), 줍(3), 줍(6), { 초: 9, 행동: '놓기', 시작초: 9.5, 도착초: 10.5, 끝초: 12, 걸음: 0.5 }]);
    expect(잰).toEqual({ 행동초: 0.2, 종류별: { 줍기: 0.2 }, 걷기속도: 2 });
    expect(손셈([{ 초: 0, 행동: '놓기', 도착초: 1, 끝초: 2.5 }])).toEqual({ 행동초: 1.5 });
    expect(손셈([{ 초: 0, 행동: '놓기' }])).toBeNull();
  });

  it('잰 손을 모델에 넣을 때 입력이 더 빠르면 잰 값, 걷기도 잰 속도가 느리면 그 속도다', () => {
    const m = 모델로(기본({ 손: { 행동초: 0.1 }, 캐릭터: { 자리: [5, 1], 걷기속도: 8 } }));
    expect(손넣기(m, { 행동초: 1.2, 종류별: { 줍기: 0.3 }, 걷기속도: 3 })).toMatchObject({ 손: { 행동초: 1.2, 종류별: { 줍기: 0.3 } }, 캐릭터: { 걷기속도: 3 } });
    expect(손넣기(m, { 행동초: 0.05, 걷기속도: 20 })).toMatchObject({ 손: { 행동초: 0.1 }, 캐릭터: { 걷기속도: 8 } });
  });
});
