// 원장 대조의 칸 번호 · 「다음 요청」 · 표 번호 채우기 검사 — 작성 에이전트가 케이스 경계와 tcId 를 코드로 정한다 (작성 §3.6 「칸과 번호」)
import { describe, expect, it } from 'vitest';

import { 사람이뺀번호, 요구줄들, 원장대조, 원장판정, 제외번호들, 표번호채우기 } from './authoring-ledger-check.js';
import type { 설계 } from './authoring-design.js';
import { type 칸재료, 칸재료만들기 } from './authoring-slots.js';

const 표 = (요구줄: string[], 제외줄: string[] = []) =>
  [
    '# X',
    '',
    '## 요구사항',
    '',
    '| 요구 | 축 | 전제 | 조작 | 결과 | 출처 | tcId | 작성 시점 |',
    '|---|---|---|---|---|---|---|---|',
    ...요구줄,
    '',
    '## 제외',
    '',
    '| 요구 | 종류 | 사유 |',
    '|---|---|---|',
    ...제외줄,
    '',
  ].join('\n');
const 원장 = ['REQ-A-1', 'REQ-A-2', 'REQ-A-3'].map((번호) => ({ 번호, 자료: 'a', 지문: '0000000000000000' }));

describe('칸 번호 · 「다음 요청」 — 작성 에이전트 (2026-10-04 게이트 1 · 작성 §3.6 「칸과 번호」)', () => {
  const 칸줄 = (축: string, 출처: string, tcId: string) => `| 1 | ${축} | 전 | 조 | 결 | ${출처} | ${tcId} | 2026-10-04 |`;
  const 번호들 = 원장.map((h) => h.번호);
  const 빈재료: 칸재료 = { 접두사: 'X', 기준줄: [], 칸: {}, 쓰인: [] };

  it('요구줄들 이 백틱을 벗기고 \\| 든 칸을 안 깬다', () => {
    const 글 = 표([칸줄('UI', 'a §2 REQ-A-2 · 「A \\| B」', '`X-UI-002`')]);
    expect(요구줄들(글)).toEqual([{ 차례: 0, 출처: 'a §2 REQ-A-2 · 「A \\| B」', 축: 'UI', tcId: 'X-UI-002' }]);
  });

  it('제외번호들 이 종류별 번호를 뽑고 사람이뺀번호 는 그것을 쓴다', () => {
    const 글 = 표([], ['| REQ-A-1 | 다음 요청 | 다음 |', '| REQ-A-2 | 사람이 뺌 | 판정 |', '| REQ-A-3 | 다음 요청 | 다음 |']);
    expect([...제외번호들(글, '다음 요청')]).toEqual(['REQ-A-1', 'REQ-A-3']);
    expect([...사람이뺀번호(글)]).toEqual(['REQ-A-2']);
  });

  it('에이전트가 새로 쓴 「다음 요청」은 형식 오류이고 빠짐으로 센다 · 기준에 있던 번호는 인정한다', () => {
    const 글 = 표([], ['| REQ-A-1 | 다음 요청 | 다음 |', '| REQ-A-2 | 다음 요청 | 다음 |', '| REQ-A-3 | 요구 아님 | 목차 |']);
    const r = 원장대조(원장, 글, { 에이전트: true, 다음요청: new Set(['REQ-A-1']) });
    expect(r.형식오류).toEqual(['제외 줄 「REQ-A-2」 — 「다음 요청」은 작성 에이전트가 새로 못 쓴다']);
    expect(r.빠짐).toEqual(['REQ-A-2']);
    expect(r.셈.제외).toEqual({ '다음 요청': 1, '요구 아님': 1 });
  });

  it('사람 세션(에이전트 아님)은 「다음 요청」을 막지 않는다', () => {
    const 글 = 표([], ['| REQ-A-1 | 다음 요청 | 다음 |']);
    expect(원장대조(원장, 글, { 에이전트: false }).형식오류).toEqual([]);
  });

  it('tcId 가 칸 번호와 다른 줄은 칸어긋남에 싣되 그 요구는 덮음이다', () => {
    const 글 = 표([칸줄('UI', 'a REQ-A-2', 'X-UI-002'), 칸줄('정상', 'a REQ-A-2', 'X-FN-010')]);
    const r = 원장대조(원장, 글, { 있는케이스: new Set(['X-UI-002', 'X-FN-010']), 에이전트: true, 칸재료: 빈재료 });
    expect(r.칸어긋남).toEqual(['요구 줄 2 tcId X-FN-010 — 칸 번호 X-FN-004']);
    expect(r.빠짐).toEqual(['REQ-A-1', 'REQ-A-3']);
    expect(r.형식오류).toEqual([]);
    expect([...(r.덮음.get('REQ-A-2') ?? [])]).toEqual(['X-UI-002', 'X-FN-010']);
  });

  it('기준 줄(같은 tcId · 같은 출처)은 칸 번호와 달라도 안 본다', () => {
    const 기준 = 표([칸줄('정상', 'a REQ-A-2', 'X-010')]);
    const 재료 = 칸재료만들기('X', 요구줄들(기준), ['X-010'], 번호들);
    const r = 원장대조(원장, 기준, { 에이전트: true, 칸재료: 재료 });
    expect(r.칸어긋남).toEqual([]);
  });

  it('칸재료가 없거나 에이전트가 아니면 번호를 안 본다', () => {
    const 글 = 표([칸줄('정상', 'a REQ-A-2', 'X-FN-010')]);
    expect(원장대조(원장, 글, { 에이전트: true }).칸어긋남).toEqual([]);
    expect(원장대조(원장, 글, { 에이전트: false, 칸재료: 빈재료 }).칸어긋남).toEqual([]);
  });

  it('원장판정 이 칸 번호 어긋남 · 재료 없음을 머리글에 싣는다', () => {
    const 값 = { 항목: 원장, 가족: {}, 모드: {}, 경고: [], 빠진자료: [], 꼴: {} };
    const 글 = 표([칸줄('정상', 'a REQ-A-1 · REQ-A-2 · REQ-A-3', 'X-FN-010')]);
    const 있음 = new Set(['X-FN-010']);
    const 어긋 = 원장판정(값, 글, 있음, { 사람이뺌: new Set(), 다음요청: new Set(), 칸재료: 빈재료 });
    expect(어긋.머리글).toContain('⚠️ 칸 번호 어긋남 1 — 요구 줄 1 tcId X-FN-010 — 칸 번호 X-FN-001');
    const 없음 = 원장판정(값, 글, 있음, { 사람이뺌: new Set(), 다음요청: new Set(), 칸재료: null });
    expect(없음.머리글).toContain('칸 번호 · 설계 칸 — 기준 표를 못 읽어 안 봤다');
    expect(원장판정(값, 글, 있음).머리글).not.toContain('칸 번호');
  });
});

describe('원장판정 — 번호 상한 알림', () => {
  it('원장이 333개를 넘으면 기능 번호를 칸 차례로 매겼다는 줄을 머리글에 싣는다', () => {
    const 큰원장 = Array.from({ length: 334 }, (_, i) => ({ 번호: `REQ-B-${String(i + 1).padStart(3, '0')}`, 자료: 'a', 지문: '0000000000000000' }));
    const 값 = { 항목: 큰원장, 가족: {}, 모드: {}, 경고: [], 빠진자료: [], 꼴: {} };
    const 글 = 표([`| 1 | 정상 | 전 | 조 | 결 | a REQ-B-001 | X-FN-001 | 2026-10-04 |`]);
    const r = 원장판정(값, 글, new Set(['X-FN-001']), { 사람이뺌: new Set(), 다음요청: new Set(), 칸재료: { 접두사: 'X', 기준줄: [], 칸: {}, 쓰인: [] } });
    expect(r.머리글).toContain('번호 상한 — 원장 334개라 기능 번호를 칸 차례로 매겼다');
    expect(r.머리글).not.toContain('칸 번호 어긋남');
  });
});

describe('원장판정 — 설계 줄 (작성 §3.6 「설계 기법」)', () => {
  const 경계만: 설계 = { 경계: [{ 근거: '4~12자', 값: ['3자', '4자', '12자', '13자'] }], 예외: [] };
  const 항목 = [
    { 번호: 'REQ-A-1', 자료: 'a', 지문: '0000000000000000', 설계: 경계만 },
    { 번호: 'REQ-A-2', 자료: 'a', 지문: '0000000000000000', 설계: 경계만 },
    { 번호: 'REQ-A-3', 자료: 'a', 지문: '0000000000000000' },
  ];
  const 값 = { 항목, 가족: {}, 모드: {}, 경고: [], 빠진자료: [], 꼴: {} };
  const 기준 = (칸재료: 칸재료 | null) => ({ 사람이뺌: new Set<string>(), 다음요청: new Set<string>(), 칸재료 });
  const 빈재료: 칸재료 = { 접두사: 'X', 기준줄: [], 칸: {}, 쓰인: [] };
  const 정상 = (출처: string, tcId: string) => `| 1 | 정상 | 전 | 조 | 결 | ${출처} | ${tcId} | 2026-10-05 |`;
  const 거절표 = (줄들: string[]) => ['## 설계 거절', '', '| 요구 | 축 | 까닭 |', '|---|---|---|', ...줄들, ''].join('\n');
  const 정상표 = (제외줄: string[] = []) => 표([정상('a REQ-A-1', 'X-FN-001'), 정상('a REQ-A-2', 'X-FN-004'), 정상('a REQ-A-3', 'X-FN-007')], 제외줄);
  const 있음 = new Set(['X-FN-001', 'X-FN-004', 'X-FN-007']);

  it('기준이 있으면 칸 줄 뒤에 설계 요약과 설계 칸 빠짐을 싣는다', () => {
    expect(원장판정(값, 정상표(), 있음, 기준(빈재료)).머리글.split('\n')).toEqual([
      '원장: 요구 3 → 케이스 3 · 제외 0 · 빠짐 0',
      '설계: 요구 3 중 경계 2 · 예외 0',
      '⚠️ 설계 칸 빠짐 2 — REQ-A-1 경계 · REQ-A-2 경계',
    ]);
  });

  it('「설계 거절」 줄이 빠짐을 지우고 거절로 센다 · 모든 칸이 빈 예시 행은 형식 오류가 아니다', () => {
    const 글 = 정상표() + 거절표(['|  |  |  |', '| REQ-A-1 | 경계 | 한도가 아니라 예시 글이다 |']);
    const 머리 = 원장판정(값, 글, 있음, 기준(빈재료)).머리글;
    expect(머리.split('\n').slice(-3)).toEqual(['설계: 요구 3 중 경계 2 · 예외 0', '⚠️ 설계 칸 빠짐 1 — REQ-A-2 경계', '설계 거절 1 — REQ-A-1 경계']);
    expect(머리).not.toContain('형식 오류');
  });

  it('기준이 없으면 설계 줄이 없다', () => {
    expect(원장판정(값, 정상표(), 있음).머리글).not.toContain('설계');
  });

  it('칸 재료가 없으면 요약 한 줄과 「칸 번호 · 설계 칸」 못 봄 줄만 싣는다', () => {
    const 머리 = 원장판정(값, 정상표(), 있음, 기준(null)).머리글;
    expect(머리.split('\n').slice(-2)).toEqual(['칸 번호 · 설계 칸 — 기준 표를 못 읽어 안 봤다', '설계: 요구 3 중 경계 2 · 예외 0']);
    expect(머리).not.toContain('설계 칸 빠짐');
  });

  it('제외된 요구는 케이스 아닌 줄이 남아 있어도 설계 칸 빠짐이 아니다', () => {
    const 글 = 표([정상('a REQ-A-1', 'X-FN-001'), 정상('a REQ-A-2', '—')], ['| REQ-A-2 | 요구 아님 | 목차 |']);
    const 머리 = 원장판정(값, 글, new Set(['X-FN-001']), 기준(빈재료)).머리글;
    expect(머리).toContain('⚠️ 설계 칸 빠짐 1 — REQ-A-1 경계');
    expect(머리).not.toContain('REQ-A-2 경계');
  });
});

describe('표번호채우기 — 「요구사항」 표의 tcId 칸만 바꾼다', () => {
  const 글 = [
    '# X',
    '',
    '## 요구사항',
    '',
    '| tcId | 요구 | 축 | 출처 |',
    '|---|---|---|---|',
    '| X-FN-010 | 1 | 정상 | a REQ-A-1 · 「A \\| B」 |',
    '| `X-UI-009` | 2 | UI | a REQ-A-2 |',
    '| 제거함(X-FN-003) | 3 | 예외 | a REQ-A-3 |',
    '',
    '## 미확정 케이스',
    '',
    '| tcId | 사유 |',
    '|---|---|',
    '| X-FN-010 | 화면 입력 검사 |',
    '',
  ].join('\n');

  it('기대가 있는 줄의 tcId 칸만 바꾸고 백틱 · 다른 칸 · 다른 절은 그대로 둔다', () => {
    const 새 = 표번호채우기(글, new Map([[0, 'X-FN-001'], [1, 'X-UI-002']]));
    const 줄 = 새.split('\n');
    expect(줄[6]).toBe('| X-FN-001 | 1 | 정상 | a REQ-A-1 · 「A \\| B」 |');
    expect(줄[7]).toBe('| `X-UI-002` | 2 | UI | a REQ-A-2 |');
    expect(줄[8]).toBe('| 제거함(X-FN-003) | 3 | 예외 | a REQ-A-3 |');
    expect(줄[14]).toBe('| X-FN-010 | 화면 입력 검사 |');
    expect(요구줄들(새).map((r) => r.tcId)).toEqual(['X-FN-001', 'X-UI-002', '제거함(X-FN-003)']);
  });

  it('칸이 모자란 줄은 건드리지 않는다 — 끝 가름이 사라지지 않게 (2026-10-04 코드 검토)', () => {
    const 짧은 = ['## 요구사항', '', '| 요구 | 축 | 결과 | tcId |', '|---|---|---|---|', '| 1 | 정상 | 된다 |', ''].join('\n');
    expect(표번호채우기(짧은, new Map([[0, 'X-FN-001']]))).toBe(짧은);
  });

  it('바꿀 것이 없으면 글이 한 글자도 안 바뀌고 두 번 해도 같다', () => {
    expect(표번호채우기(글, new Map())).toBe(글);
    const 한번 = 표번호채우기(글, new Map([[0, 'X-FN-001']]));
    expect(표번호채우기(한번, new Map([[0, 'X-FN-001']]))).toBe(한번);
  });

  it('줄 끝 \\r 를 지킨다', () => {
    const crlf = 글.replace(/\n/g, '\r\n');
    expect(표번호채우기(crlf, new Map([[0, 'X-FN-001']]))).toBe(표번호채우기(글, new Map([[0, 'X-FN-001']])).replace(/\n/g, '\r\n'));
  });
});

describe('덮음 — 백틱 tcId 도 케이스다 (2026-10-04 코드 검토)', () => {
  it('요구 줄 tcId 를 백틱으로 감싸도 덮음으로 센다', () => {
    const 글 = 표(['| 1 | 정상 | 전 | 조 | 결 | a REQ-A-1 | `X-FN-001` | 2026-10-04 |']);
    const r = 원장대조(원장, 글, { 있는케이스: new Set(['X-FN-001']), 에이전트: true });
    expect(r.빠짐).toEqual(['REQ-A-2', 'REQ-A-3']);
    expect(r.형식오류).toEqual([]);
  });
});
