// 칸 번호 검사 — 요구사항 표 줄마다 칸(요구 · 갈래 · 축 · 상태)과 tcId 를 코드가 같은 규칙으로 정하는지
import { describe, expect, it } from 'vitest';

import { type 칸재료, type 표줄, 기준줄열쇠, 오류추정줄인가, 줄상태, 칸번호, 칸재료만들기 } from './authoring-slots.js';

const 원장 = ['REQ-X-001', 'REQ-X-002', 'REQ-X-003'];
const 빈재료: 칸재료 = { 접두사: 'P', 기준줄: [], 칸: {}, 쓰인: [] };
const 줄 = (차례: number, 출처: string, 축: string, tcId = ''): 표줄 => ({ 차례, 출처, 축, tcId });
const 번호 = (줄들: 표줄[], 재료: 칸재료 = 빈재료, 원장번호들: string[] = 원장) =>
  칸번호(원장번호들, 줄들, 재료);

describe('칸번호 — 칸 열쇠와 고정 번호', () => {
  it('UI 칸은 원장 차례 i 를 번호로 쓴다', () => {
    expect(번호([줄(0, 'a §2 REQ-X-002', 'UI', 'P-UI-001')]).기대.get(0)).toBe('P-UI-002');
  });

  it('기능 칸은 (i−1)×3 + 정상 1 · 경계 2 · 예외 3', () => {
    const r = 번호([줄(0, 'REQ-X-002', '정상'), 줄(1, 'REQ-X-002', '경계'), 줄(2, 'REQ-X-003', '예외')]);
    expect([...r.기대]).toEqual([
      [0, 'P-FN-004'],
      [1, 'P-FN-005'],
      [2, 'P-FN-009'],
    ]);
    expect(r.어긋남).toEqual([]);
  });

  it('출처에 번호가 여럿이면 원장 차례가 가장 앞인 번호가 칸이다', () => {
    expect(번호([줄(0, 'REQ-X-003 · REQ-X-001', '정상')]).기대.get(0)).toBe('P-FN-001');
  });

  it('같은 칸 줄은 같은 번호다', () => {
    const r = 번호([줄(0, 'REQ-X-002', '정상'), 줄(1, '기획서 REQ-X-002 둘째 문장', ' 정상 ')]);
    expect(r.기대.get(0)).toBe('P-FN-004');
    expect(r.기대.get(1)).toBe('P-FN-004');
  });

  it('축이 넷 밖이면 번호를 안 매기고 어긋남에 싣는다', () => {
    const r = 번호([줄(0, 'REQ-X-001', '기타'), 줄(1, 'REQ-X-001', 'UI')]);
    expect(r.기대.has(0)).toBe(false);
    expect(r.기대.get(1)).toBe('P-UI-001');
    expect(r.어긋남).toEqual(['요구 줄 1 축 「기타」 — UI · 정상 · 경계 · 예외 중 하나가 아니다']);
  });

  it('상태 표시가 다르면 다른 칸 — 상태 칸은 고정 범위 끝 다음부터 정식 · 미확정 · 보류 · 모킹 차례', () => {
    const r = 번호([
      줄(0, '모킹 — REQ-X-002', '정상'),
      줄(1, '보류 — 관리자 비밀번호 없음 REQ-X-002', '정상'),
      줄(2, '차이 D5 REQ-X-002', '정상'),
      줄(3, '화면 검사 — REQ-X-002', '정상'),
      줄(4, 'REQ-X-002', '정상'),
    ]);
    expect(r.기대.get(4)).toBe('P-FN-004');
    expect(r.기대.get(3)).toBe('P-FN-010');
    expect(r.기대.get(2)).toBe('P-FN-010');
    expect(r.기대.get(1)).toBe('P-FN-011');
    expect(r.기대.get(0)).toBe('P-FN-012');
  });

  it('「화면에만 —」도 미확정이고, 표시가 둘이면 보류 → 미확정 → 모킹 차례로 먼저 맞는 것이다(글 안 자리가 아니다)', () => {
    const r = 번호([
      줄(0, 'REQ-X-002 · 화면에만 — 「선택 안 함」', '정상'),
      줄(1, 'REQ-X-002 · 화면 검사 — 칸 · 보류 — 관리자', '정상'),
      줄(2, 'REQ-X-002 · 모킹 — 401 · 차이 D2', '정상'),
    ]);
    expect(r.기대.get(0)).toBe('P-FN-010');
    expect(r.기대.get(2)).toBe('P-FN-010');
    expect(r.기대.get(1)).toBe('P-FN-011');
  });

  it('「오류 추정 —」은 미확정과 다른 칸이고 상태 차례 끝이다 — 모킹 표시가 같이 있어도 오류 추정, 보류가 같이 있으면 보류', () => {
    const r = 번호([
      줄(0, 'REQ-X-002 · 오류 추정 — 서버 실패 · 모킹 — 500', '예외'),
      줄(1, 'REQ-X-002 · 화면 검사 — 칸', '예외'),
      줄(2, 'REQ-X-002 · 오류 추정 — 빈 값', '예외'),
      줄(3, 'REQ-X-002 · 보류 — 다른 계정 없음 · 오류 추정 — 남의 것', '예외'),
    ]);
    expect(r.기대.get(1)).toBe('P-FN-010');
    expect(r.기대.get(3)).toBe('P-FN-011');
    expect(r.기대.get(0)).toBe('P-FN-012');
    expect(r.기대.get(2)).toBe('P-FN-012');
  });

  it('「제거함(…)」 줄은 건너뛴다', () => {
    const r = 번호([줄(0, 'REQ-X-001', '기타', '제거함(P-FN-001)'), 줄(1, 'REQ-X-001', '정상')]);
    expect(r.기대.has(0)).toBe(false);
    expect(r.기대.get(1)).toBe('P-FN-001');
    expect(r.어긋남).toEqual([]);
  });
});

describe('칸번호 — 기준 줄 · 물려받기 · 쓰인 번호', () => {

  it('tcId 가 「—」거나 축이 「—」인 기준 줄도 기준 줄이다 — 사람 세션의 판정 불가 · 철회 줄을 덮어쓰지 않는다 (2026-10-04 코드 검토)', () => {
    const 기준들 = [줄(0, 'REQ-X-001', '—', '—'), 줄(1, 'REQ-X-002 철회됨', '정상', '—')];
    const 재료 = 칸재료만들기('P', 기준들, [], 원장);
    const r = 번호(기준들, 재료);
    expect(r.기대.size).toBe(0);
    expect(r.어긋남).toEqual([]);
  });

  it('기준 줄 열쇠에 축이 든다 — 기준 줄의 축만 바꾸면 기준 줄이 아니라 칸 번호를 받는다', () => {
    const 재료 = 칸재료만들기('P', [줄(0, 'REQ-X-002', '정상', 'P-FN-004')], ['P-FN-004'], 원장);
    const r = 번호([줄(0, 'REQ-X-002', '예외', 'P-FN-004'), 줄(1, 'REQ-X-002', '정상')], 재료);
    expect(r.기대.get(0)).toBe('P-FN-006');
    expect(r.기대.get(1)).toBe('P-FN-004');
  });

  it('기준 덩이 첫 줄 tcId 가 비어도 덩이 안에서 번호가 적힌 줄을 물려준다', () => {
    const 재료 = 칸재료만들기('P', [줄(0, 'REQ-X-002', '정상', ''), 줄(1, 'REQ-X-002', '정상', 'P-FN-040')], ['P-FN-040'], 원장);
    expect(재료.칸['REQ-X-002|FN|정상|정식#0']).toBe('P-FN-040');
  });
  it('기준 표에 같은 tcId · 같은 출처로 있던 줄은 빠진다 — 출처의 빈칸 수는 안 본다', () => {
    const 재료 = 칸재료만들기('P', [줄(0, 'REQ-X-002  둘째 문장', '정상', 'P-FN-031')], ['P-FN-031'], 원장);
    const r = 번호(
      [줄(0, ' REQ-X-002 둘째   문장 ', '정상', 'P-FN-031'), 줄(1, 'REQ-X-002 셋째 문장', '정상', 'P-FN-031')],
      재료,
    );
    expect(r.기대.has(0)).toBe(false);
    expect(r.기대.has(1)).toBe(true);
    expect(기준줄열쇠({ tcId: 'P-FN-031', 축: ' 정상 ', 출처: ' a  b ' })).toBe('P-FN-031|정상|a b');
  });

  it('재료에 그 칸 · 덩이 번호가 있으면 물려받는다', () => {
    const 재료 = { ...빈재료, 칸: { 'REQ-X-002|FN|정상|정식#0': 'P-FN-040' } };
    expect(번호([줄(0, 'REQ-X-002', '정상')], 재료).기대.get(0)).toBe('P-FN-040');
  });

  it('문단 번호 요구는 물려받지 않는다 — 개정판에서 문단 자리가 밀린다', () => {
    const 재료 = { ...빈재료, 칸: { 'P-002|FN|정상|정식#0': 'P-FN-040' } };
    expect(번호([줄(0, '문단 P-002', '정상')], 재료, ['P-001', 'P-002']).기대.get(0)).toBe('P-FN-004');
  });

  it('고정 번호가 쓰인 번호면 고정을 못 쓰고 뒤 번호 — 직접 · 「제거함」 · 옛 꼴', () => {
    const 뒤 = (재료: 칸재료) => 번호([줄(0, 'REQ-X-002', '정상')], 재료).기대.get(0);
    expect(뒤({ ...빈재료, 쓰인: ['P-FN-004'] })).toBe('P-FN-010');
    expect(뒤({ ...빈재료, 쓰인: ['P-004'] })).toBe('P-FN-010');
    const 지운재료 = 칸재료만들기('P', [줄(0, 'REQ-X-002', '정상', '제거함(P-FN-004)')], ['P-FN-004'], 원장);
    expect(지운재료.칸).toEqual({});
    expect(뒤(지운재료)).toBe('P-FN-010');
  });
});

describe('칸재료만들기', () => {
  it('기준 줄을 같은 규칙으로 묶어 (칸, 덩이) → 첫 tcId — 다른 덩이가 이미 가진 번호는 안 준다', () => {
    const 재료 = 칸재료만들기(
      'P',
      [
        줄(0, 'REQ-X-002', '정상', 'P-FN-004'),
        줄(1, 'REQ-X-003 · REQ-X-002', '정상', 'P-FN-007'),
        줄(2, 'REQ-X-003', '정상', 'P-004'),
        줄(3, 'REQ-X-001', '정상', 'P-UI-001'),
        줄(4, 'REQ-X-001', '예외', '제거함(P-FN-003)'),
        줄(5, '화면 검사 — REQ-X-001', 'UI', 'P-UI-007'),
      ],
      ['P-FN-007', 'P-FN-004', 'P-FN-004'],
      원장,
    );
    expect(재료.칸).toEqual({ 'REQ-X-002|FN|정상|정식#0': 'P-FN-004', 'REQ-X-001|UI|UI|미확정#0': 'P-UI-007' });
    expect(재료.기준줄).toEqual([
      'P-FN-004|정상|REQ-X-002',
      'P-FN-007|정상|REQ-X-003 · REQ-X-002',
      'P-004|정상|REQ-X-003',
      'P-UI-001|정상|REQ-X-001',
      '제거함(P-FN-003)|예외|REQ-X-001',
      'P-UI-007|UI|화면 검사 — REQ-X-001',
    ]);
    expect(재료.쓰인).toEqual(['P-FN-004', 'P-FN-007']);
    expect(재료.접두사).toBe('P');
  });
});

describe('칸번호 — 뒤 번호 · 덩이 · 원장 밖 · 상한', () => {
  const 표로 = (r: { 기대: Map<number, string> }) => Object.fromEntries(r.기대);

  it('한 칸이 10줄을 넘으면 둘째 덩이는 뒤 번호다 — 재료도 덩이마다 따로', () => {
    const 열한줄 = (tcId: (i: number) => string) => Array.from({ length: 11 }, (_, i) => 줄(i, 'REQ-X-002', '정상', tcId(i)));
    const r = 번호(열한줄(() => ''));
    expect(r.기대.get(9)).toBe('P-FN-004');
    expect(r.기대.get(10)).toBe('P-FN-010');
    expect(칸재료만들기('P', 열한줄((i) => (i < 10 ? 'P-FN-004' : 'P-FN-012')), [], 원장).칸).toEqual({
      'REQ-X-002|FN|정상|정식#0': 'P-FN-004',
      'REQ-X-002|FN|정상|정식#1': 'P-FN-012',
    });
  });

  it('원장 밖 번호 줄은 그 번호가 칸이고 원장 칸 뒤에 번호 글자 차례로 매긴다', () => {
    const r = 번호([
      줄(0, 'ZZ-9 기획서 밖', '정상'),
      줄(1, 'YY-1', '정상'),
      줄(2, 'YY-1 둘째 문장', '정상'),
      줄(3, 'ZZ-9 · REQ-X-002', '정상'),
      줄(4, '화면 검사 — REQ-X-003', '경계'),
    ]);
    expect(표로(r)).toEqual({ 0: 'P-FN-012', 1: 'P-FN-011', 2: 'P-FN-011', 3: 'P-FN-004', 4: 'P-FN-010' });
  });

  it('번호가 없는 줄은 줄마다 칸이고 원장 밖 번호 뒤에 표 차례로 매긴다', () => {
    const r = 번호([줄(0, '기획서에 없는 동작', '정상'), 줄(1, 'YY-1', '정상'), 줄(2, '기획서에 없는 동작', '정상')]);
    expect(표로(r)).toEqual({ 0: 'P-FN-011', 1: 'P-FN-010', 2: 'P-FN-012' });
  });

  it('뒤 번호는 고정 범위 끝 · 쓰인 번호 · 정한 번호 가운데 그 열의 가장 큰 것 다음부터', () => {
    const 미확정 = [줄(0, '화면 검사 — REQ-X-001', '정상'), 줄(1, '화면 검사 — REQ-X-001', 'UI')];
    expect(표로(번호(미확정, { ...빈재료, 쓰인: ['P-FN-050', 'P-UI-020', 'Q-FN-090', 'P-005'] }))).toEqual({
      0: 'P-FN-051',
      1: 'P-UI-021',
    });
    expect(표로(번호(미확정, { ...빈재료, 쓰인: ['P-FN-005'] }))).toEqual({ 0: 'P-FN-010', 1: 'P-UI-004' });
    const 물려 = { ...빈재료, 칸: { 'REQ-X-002|FN|정상|정식#0': 'P-FN-070' } };
    expect(표로(번호([...미확정, 줄(2, 'REQ-X-002', '정상')], 물려))).toEqual({ 0: 'P-FN-071', 1: 'P-UI-004', 2: 'P-FN-070' });
  });

  it('지금 표 유지 — 앞 차례에 칸을 더해도 이미 매긴 뒤 번호는 그대로다', () => {
    expect(번호([줄(0, '화면 검사 — REQ-X-002', '정상')]).기대.get(0)).toBe('P-FN-010');
    const r = 번호([줄(0, '화면 검사 — REQ-X-001', '정상'), 줄(1, '화면 검사 — REQ-X-002', '정상', 'P-FN-010')]);
    expect(표로(r)).toEqual({ 0: 'P-FN-011', 1: 'P-FN-010' });
  });

  it('지금 표 유지 — 같은 칸 앞자리에 번호 없는 줄을 끼워도 그 칸 번호는 그대로다', () => {
    const 앞 = 번호([줄(0, '화면 검사 — REQ-X-001', '정상'), 줄(1, '화면 검사 — REQ-X-001', '경계')]);
    expect(표로(앞)).toEqual({ 0: 'P-FN-010', 1: 'P-FN-011' });
    const 뒤 = 번호([
      줄(0, '화면 검사 — REQ-X-001', '정상'),
      줄(1, '화면 검사 — REQ-X-001', '정상', 'P-FN-010'),
      줄(2, '화면 검사 — REQ-X-001', '경계', 'P-FN-011'),
    ]);
    expect(표로(뒤)).toEqual({ 0: 'P-FN-010', 1: 'P-FN-010', 2: 'P-FN-011' });
  });

  it('지금 표 유지 — 원장 밖 칸 맨 위에 빈 줄을 끼우고 앞 차례에 새 칸을 더해도 그 칸 번호는 그대로다 (2026-10-04 코드 검토)', () => {
    const r = 번호([줄(0, 'W-001', '정상'), 줄(1, 'X-001', '정상'), 줄(2, 'X-001', '정상', 'P-FN-010')]);
    expect(표로(r)).toEqual({ 0: 'P-FN-011', 1: 'P-FN-010', 2: 'P-FN-010' });
  });

  it('상태 표시는 줄표(—)로만 — 붙임표(-)가 든 낱말은 정식이다', () => {
    expect(번호([줄(0, 'REQ-X-002 · 주문 보류-해제 절', '정상')]).기대.get(0)).toBe('P-FN-004');
  });

  it('지금 표 유지는 종류 글자 없는 옛 꼴을 안 쓴다 — 새 번호는 -UI- · -FN- 을 단다(R17)', () => {
    expect(번호([줄(0, '화면 검사 — REQ-X-001', '정상', 'P-020')]).기대.get(0)).toBe('P-FN-010');
  });

  it('지금 표 유지는 고정 범위 안 · 쓰인 · 겹침 · 갈래나 머리가 다른 번호를 안 쓴다', () => {
    const r = 번호(
      [
        줄(0, '화면 검사 — REQ-X-001', '정상', 'P-FN-005'),
        줄(1, '화면 검사 — REQ-X-002', '정상', 'P-FN-020'),
        줄(2, '화면 검사 — REQ-X-003', '정상', 'P-FN-020'),
        줄(3, '화면 검사 — REQ-X-001', 'UI', 'P-FN-030'),
        줄(4, '보류 — REQ-X-001', '정상', 'Q-FN-040'),
        줄(5, '모킹 — REQ-X-001', '정상', 'P-FN-050'),
      ],
      { ...빈재료, 쓰인: ['P-FN-050'] },
    );
    expect(표로(r)).toEqual({
      0: 'P-FN-051',
      1: 'P-FN-020',
      2: 'P-FN-054',
      3: 'P-UI-004',
      4: 'P-FN-052',
      5: 'P-FN-053',
    });
  });

  it('원장이 334개면 기능은 고정을 안 쓰고 칸 차례로 매기며 알림 한 줄 — UI 는 고정', () => {
    const 큰원장 = Array.from({ length: 334 }, (_, i) => `REQ-X-${String(i + 1).padStart(3, '0')}`);
    const r = 번호(
      [줄(0, 'REQ-X-002', 'UI'), 줄(1, 'REQ-X-002', '정상'), 줄(2, 'REQ-X-003', '정상', 'P-FN-005')],
      빈재료,
      큰원장,
    );
    expect(표로(r)).toEqual({ 0: 'P-UI-002', 1: 'P-FN-006', 2: 'P-FN-005' });
    expect(r.알림).toEqual(['번호 상한 — 원장 334개라 기능 번호를 칸 차례로 매겼다']);
    const 끝원장 = 큰원장.slice(0, 333);
    const 끝 = 번호([줄(0, 'REQ-X-333', '예외')], 빈재료, 끝원장);
    expect(끝.기대.get(0)).toBe('P-FN-999');
    expect(끝.알림).toEqual([]);
  });

  it('새 번호가 999 를 넘으면 그 덩이 줄은 번호 없이 어긋남', () => {
    const r = 번호([줄(0, '화면 검사 — REQ-X-001', '정상'), 줄(3, '화면 검사 — REQ-X-001', '정상')], {
      ...빈재료,
      쓰인: ['P-FN-999'],
    });
    expect(r.기대.size).toBe(0);
    expect(r.어긋남).toEqual(['요구 줄 1 — 새 번호가 999 를 넘는다', '요구 줄 4 — 새 번호가 999 를 넘는다']);
  });

  it('같은 입력이면 같은 결과 — 줄 배열 순서를 섞어도 차례가 같으면 같다', () => {
    const 줄들 = [
      줄(0, 'ZZ-9', '정상', 'P-FN-030'),
      줄(1, '화면 검사 — REQ-X-002', 'UI'),
      줄(2, '기획서에 없는 동작', '예외'),
      줄(3, 'REQ-X-001', '경계'),
      줄(4, '보류 — REQ-X-003', '정상', 'P-FN-012'),
      줄(5, 'REQ-X-001', '기타'),
    ];
    const 재료 = { ...빈재료, 쓰인: ['P-FN-002'] };
    const 첫 = 번호(줄들, 재료);
    expect(번호(줄들, 재료)).toEqual(첫);
    const 뒤집은 = 번호([...줄들].reverse(), 재료);
    expect(표로(뒤집은)).toEqual(표로(첫));
    expect(뒤집은.어긋남).toEqual(첫.어긋남);
  });
});

