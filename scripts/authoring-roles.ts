// 역할 계정 이름 가운데 작성이 따로 다루는 둘 — 일회용 계정과 폰마다 계정 (도메인/작성 §3.6 「★ 역할별 계정」 · 「★ 테스트 데이터」)

// 가운뎃점은 자판마다 다른 글자가 들어온다(· ㆍ ・ •) — 역할 이름은 자유 글자라 비슷한 꼴도 같이 거른다. 「일회용품 관리자」는 일회용 역할이 아니다
export const 일회용역할 = /^\s*일회용(?:\s|[·ㆍ・•])/;

/** 「일반 회원 2」 · 「일반 회원 3」 … 의 번호(2 이상). 아니면 null — 폰 돌려 보기가 두 번째 폰부터 이 계정을 일반 회원 자리에 넣는다(「폰마다 계정」) */
export function 동시계정번호(역할: string): number | null {
  const 번호 = Number(/^\s*일반\s*회원\s*(\d{1,2})\s*$/.exec(역할)?.[1] ?? NaN);
  return 번호 >= 2 ? 번호 : null;
}
