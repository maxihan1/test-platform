// 게임 맵 격자 길찾기 — 범위(걷기 · 걸은 위치 · 맵 점 · 여백) · 막힘 형태 · 평면 · 걸음됨 우선 · 못감 반영 · 대각선 모서리 · 꺾임점 · 끝 점 · 막힌 출발점 · 길 없음
import { describe, expect, it } from 'vitest';

import { 걸음됨, 격자짓기, 기록칠, 길내기, 막힘, 막힘읽기, 모름, 여백, 좌표읽기, 칸수, 평면정하기, type 격자, type 점 } from './authoring-game-path.js';
import type { 판기록 } from './authoring-learn-check.js';

const 짓기 = (걷기: unknown, 막힘값: unknown = [], 칠들: Parameters<typeof 격자짓기>[2] = []): 격자 => {
  const g = 격자짓기(걷기, 막힘값, 칠들);
  if (typeof g === 'string') throw new Error(g);
  return g;
};
const 칸값 = (g: 격자, i: number, j: number): number => g.칸[(j - g.최소j) * g.너비 + (i - g.최소i)]!;
const 점들 = (r: ReturnType<typeof 길내기>): 점[] => ('점들' in r ? r.점들 : []);

describe('좌표 읽기', () => {
  it('두 수는 가로 세로 · 세 수와 {x,y,z} 는 높이를 빼고 x z · {x,y} 는 x y', () => {
    expect(좌표읽기([3, 4])).toEqual([3, 4]);
    expect(좌표읽기([3, 9, 4])).toEqual([3, 4]);
    expect(좌표읽기({ x: 3, y: 9, z: 4 })).toEqual([3, 4]);
    expect(좌표읽기({ x: 3, y: 4 })).toEqual([3, 4]);
    expect(좌표읽기([1, 2, 3, 4])).toBeNull();
  });
});

describe('격자 짓기', () => {
  it('범위는 걷기 점 · 걸은 위치 · 덧붙인 점을 감싸고 여백 칸을 둔다 · 걷기 바깥도 막힘이 아니라 모름이다', () => {
    const g = 짓기([[0, 0], [4, 3]]);
    expect([g.최소i, g.최소j, g.너비, g.높이]).toEqual([-여백, -여백, 5 + 2 * 여백, 4 + 2 * 여백]);
    expect(칸수(g).막힘).toBe(0);
    const 끝 = 길내기(g, [0.5, 0.5], [4, 3]);
    expect(점들(끝).at(-1)).toEqual([4, 3]);
    expect('요약' in 끝 && 끝.요약).not.toContain('옮김');
    const 덧 = 격자짓기([[0, 0], [4, 3]], [], [], 'xz', [[10, -6]]);
    expect(typeof 덧 !== 'string' && [덧.최소i + 덧.너비 - 1, 덧.최소j]).toEqual([10 + 여백, -6 - 여백]);
  });

  it('열째 맵 재현 — 걷기 점이 북쪽에만 있어도 남쪽 섬에서 걸은 위치가 칠해지고 길이 그리로 난다', () => {
    const 북 = [[0, 20], [10, 20], [10, 30], [0, 30]];
    const 남쪽걸음: 점[] = [];
    for (let z = 0.5; z < 20; z += 1) 남쪽걸음.push([5.5, z]);
    const g = 짓기(북, { 물: [{ 사각형: [[-3, 10], [4.9, 12]] }, { 사각형: [[6.1, 10], [14, 12]] }] }, [{ 걸음: 남쪽걸음, 못감: [] }]);
    expect(칸값(g, 5, 2)).toBe(걸음됨);
    const r = 길내기(g, [5.5, 2.5], [5.5, 25.5]);
    expect('요약' in r && r.요약).not.toContain('옮김');
    expect(점들(r)).toEqual([[5.5, 2.5], [5.5, 25.5]]);
  });

  it('막힘 사각형은 이름을 단 형태만 사각형이고 겹친 칸을 막는다 · 점 목록은 그 칸만 막는다', () => {
    const g = 짓기([[0, 0], [10, 10]], [{ 사각형: [[2, 2], [4, 3]] }, [7.5, 8.5], { 중심: [6, 2], 크기: [2, 2] }]);
    expect([칸값(g, 2, 2), 칸값(g, 3, 2), 칸값(g, 4, 2), 칸값(g, 3, 3), 칸값(g, 7, 8), 칸값(g, 8, 8), 칸값(g, 5, 1), 칸값(g, 6, 2), 칸값(g, 7, 2)]).toEqual([막힘, 막힘, 모름, 모름, 막힘, 모름, 막힘, 막힘, 모름]);
  });

  it('맨 배열의 점 둘은 사각형이 아니라 점 두 개다 — 물 오브젝트 두 자리를 넓은 막힘으로 칠하지 않는다', () => {
    expect(칸수(짓기([[0, 0], [10, 10]], [[1, 1], [9, 9]])).막힘).toBe(2);
    expect(칸수(짓기([[0, 0], [10, 10]], { 사각형: [[1, 1], [9, 9]] })).막힘).toBe(64);
  });

  it('형태를 모르는 막힘은 건너뛰고 몇 개인지 요약에 적는다 · 글은 이름표라 안 센다', () => {
    expect(막힘읽기([{ 반지름: 3 }, [1, 1]])).toMatchObject({ 모름: 1, 점: [[1, 1]] });
    const r = 길내기(짓기([[0, 0], [3, 3]], ['문', { 반지름: 2 }]), [0.5, 0.5], [2.5, 2.5]);
    expect('요약' in r && r.요약).toContain('형태를 모르는 막힘 1개 건너뜀');
  });

  it('막힘은 맨 사각형 하나 · 맨 점 하나 · 종류별로 묶은 객체도 읽는다', () => {
    expect(막힘읽기({ 사각형: [[2, 2], [4, 4]] })).toMatchObject({ 사각형: [[[2, 2], [4, 4]]], 점: [], 모름: 0 });
    expect(막힘읽기([[2, 2], [4, 4]])).toMatchObject({ 사각형: [], 점: [[2, 2], [4, 4]], 모름: 0 });
    expect(막힘읽기([3, 4])).toMatchObject({ 점: [[3, 4]], 모름: 0 });
    expect(막힘읽기({ 벽: [{ 사각형: [[0, 0], [2, 2]] }], 물: [[5, 5]] })).toMatchObject({ 사각형: [[[0, 0], [2, 2]]], 점: [[5, 5]], 모름: 0 });
    expect(막힘읽기([{ x: 1, y: 0, z: 2, 크기: 3 }])).toMatchObject({ 점: [], 모름: 1 });
  });

  it('평면 — 맵이 적었으면 그것, z 없는 {x,y} 좌표가 있으면 2D 로 보고 판 기록의 세 수 위치도 x y 로 읽는다', () => {
    expect(평면정하기({ 걷기: { 값: [{ x: 0, y: 0 }, { x: 20, y: 20 }] } })).toBe('xy');
    expect(평면정하기({ 걷기: { 값: [[0, 0], [20, 20]] } })).toBe('xz');
    expect(평면정하기({ 평면: 'xy', 걷기: { 값: [[0, 0, 0]] } })).toBe('xy');
    expect(좌표읽기([12, 7, 0], 'xy')).toEqual([12, 7]);
  });

  it('걸음됨은 모름보다 싸서 조금 돌아도 걸어 본 길로 간다', () => {
    const 걸음 = [0.5, 1.5, 2.5, 3.5, 4.5].map((x) => [x, 1.5] as 점).concat([[0.5, 0.5], [4.5, 0.5]]);
    expect(점들(길내기(짓기([[0, 0], [5, 3]]), [0.5, 0.5], [4.5, 0.5]))).toEqual([[0.5, 0.5], [4.5, 0.5]]);
    const g = 짓기([[0, 0], [5, 3]], [], [{ 걸음, 못감: [] }]);
    expect(칸수(g)).toMatchObject({ 걸음됨: 7, 막힘: 0 });
    expect(점들(길내기(g, [0.5, 0.5], [4.5, 0.5]))).toEqual([[0.5, 0.5], [1.5, 1.5], [3.5, 1.5], [4.5, 0.5]]);
  });

  it('못감은 칸을 막고 그 뒤 기록에서 걸으면 걸음됨이 이기고 같은 기록이면 못감이 이긴다', () => {
    const 못 = { 걸음: [], 못감: [[2.5, 2.5] as 점] };
    expect(칸값(짓기([[0, 0], [5, 5]], [], [못]), 2, 2)).toBe(막힘);
    expect(칸값(짓기([[0, 0], [5, 5]], [], [못, { 걸음: [[2.5, 2.5]], 못감: [] }]), 2, 2)).toBe(걸음됨);
    expect(칸값(짓기([[0, 0], [5, 5]], [], [{ 걸음: [[2.5, 2.5]], 못감: [[2.5, 2.5]] }]), 2, 2)).toBe(막힘);
  });

  it('걸음됨은 지도 막힘을 덮는다 — 걸어 본 것이 지도보다 확실하다', () => {
    const g = 짓기([[0, 0], [5, 5]], [[2.5, 2.5]], [{ 걸음: [[2.5, 2.5]], 못감: [] }]);
    expect(칸값(g, 2, 2)).toBe(걸음됨);
  });

  it('걷기 범위가 너무 크면 짓지 않고 이유를 돌려준다', () => {
    expect(격자짓기([[0, 0], [100000, 100000]], [], [])).toContain('너무 크다');
    expect(격자짓기('없음', [], [])).toContain('못 읽었다');
  });
});

describe('판 기록 칠하기', () => {
  const 줄들 = [
    { kind: 'TRIAL', key: 'trial:가', learned: { text: 'ㄱ', belief: 'GUESS', data: { 곳: 'stage:1' } } },
    { kind: 'TRIAL', key: 'trial:나', learned: { text: 'ㄱ', belief: 'GUESS', data: { 곳: 'stage:2' } } },
  ] as unknown as Parameters<typeof 기록칠>[1];
  const 기록 = (계획: string, 값?: unknown): 판기록 => ({
    이름: 'a',
    ...(값 === undefined ? {} : { 값 }),
    값기록: { 계획, 볼값: [], 간격ms: 2000, 어긋남: null, 화면다름: [], 때: [{ 초: 0, 값: {}, 위치: [1.2, 9, 3.7] }, { 초: 2, 값: {}, 위치: null }, { 초: 4, 값: {} }] },
  });

  it('그 곳을 적은 계획의 기록만 위치 x z 와 못감을 칠한다', () => {
    expect(기록칠(기록('trial:가', { 못감: [[5, 6], '잘못', { x: 7, y: 0, z: 8 }] }), 줄들, 'stage:1')).toEqual({ 걸음: [[1.2, 3.7]], 못감: [[5, 6], [7, 8]] });
    expect(기록칠(기록('trial:나'), 줄들, 'stage:1')).toBeNull();
    expect(기록칠({ 이름: 'b' }, 줄들, 'stage:1')).toBeNull();
    expect(기록칠({ 이름: 'c', 값기록: { 계획: 'trial:가' } } as never, 줄들, 'stage:1')).toEqual({ 걸음: [], 못감: [] });
    expect(기록칠(기록('trial:가'), 줄들, 'stage:1', 'xy')).toMatchObject({ 걸음: [[1.2, 9]] });
  });
});

describe('길찾기', () => {
  it('대각선은 양옆 칸이 다 열렸을 때만 지나 막힌 모서리를 안 자른다', () => {
    const 열림 = 짓기([[0, 0], [2, 2]], [[1.5, 0.5]]);
    expect(점들(길내기(열림, [0.5, 0.5], [1.5, 1.5]))).toEqual([[0.5, 0.5], [0.5, 1.5], [1.5, 1.5]]);
    const 통로 = 짓기([[0, 0], [3, 3]], { 가: [0.5, 1.5], 나: [1.5, 0.5], 왼: { 사각형: [[-5, -5], [-0.5, 5]] }, 아래: { 사각형: [[-5, -5], [5, -0.5]] } });
    expect(길내기(통로, [0.5, 0.5], [2.5, 2.5])).toMatchObject({ 길없음: true });
  });

  it('곧은 구간은 꺾이는 점만 남긴다', () => {
    const g = 짓기([[0, 0], [6, 6]], [{ 사각형: [[1, 0], [6, 5]] }]);
    expect(점들(길내기(g, [0.5, 0.5], [0.5, 5.5]))).toEqual([[0.5, 0.5], [0.5, 5.5]]);
    expect(점들(길내기(g, [0.5, 0.5], [5.5, 5.5]))).toEqual([[0.5, 0.5], [0.5, 5.5], [5.5, 5.5]]);
  });

  it('출발이 막힘이면 가장 가까운 열린 칸으로 옮기고 요약에 적는다', () => {
    const g = 짓기([[0, 0], [5, 1]], [{ 사각형: [[-5, -5], [1, 1]] }]);
    const r = 길내기(g, [0.5, 0.5], [4.5, 0.5]);
    expect(점들(r)[0]).toEqual([1.5, 0.5]);
    expect('요약' in r && r.요약).toContain('출발이 막혀 칸 1,0 로 옮김');
  });

  it('길이 없으면 이유를 돌려준다', () => {
    const g = 짓기([[0, 0], [5, 3]], [{ 사각형: [[2, -5], [3, 10]] }]);
    expect(길내기(g, [0.5, 1.5], [4.5, 1.5])).toMatchObject({ 길없음: true, 틀림: expect.stringContaining('길 없음') });
  });

  it('요약은 칸 수 · 걸음됨 · 막힘 · 모름 · 길 길이를 적는다', () => {
    const r = 길내기(짓기([[0, 0], [5, 1]], []), [0.5, 0.5], [4.5, 0.5]);
    expect('요약' in r && r.요약).toBe('칸 60 · 걸음됨 0 · 막힘 0 · 모름 60 · 길 길이 4');
  });

  it('끝 점은 칸 가운데가 아니라 실제 출발 · 도착이다 — 반 칸 뒤로 갔다가 출발하지 않게', () => {
    expect(점들(길내기(짓기([[0, 0], [5, 5]]), [0.9, 0.9], [0.9, 4.2]))).toEqual([[0.9, 0.9], [0.9, 4.2]]);
  });
});
