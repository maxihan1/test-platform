// 재현 비교 — 시계 맞추기 · 이어 부른 조각 · 처치 누적 · 짧은 흔들림 · 처음 어긋난 값과 잰 값 · 시뮬이 먼저 끝남
import { describe, expect, it } from 'vitest';

import { 어긋남글, 재현비교하기, 지속초, 판값들 } from './authoring-game-sim-compare.js';
import type { 값기록 } from './authoring-learn-check.js';

const 연결 = { 웨이브: '웨이브', 지킬것: '세계수', 재화: '고기', 처치: '처치' };
const 기록 = (때: { 초: number; 값: Record<string, number | null> }[], 시작때?: number): 값기록 => ({ 계획: 'trial:가', 볼값: [], 간격ms: 2000, 때, 어긋남: null, 화면다름: [], ...(시작때 === undefined ? {} : { 시작때 }) });
/** 2초마다 0 부터 끝초까지 — 값은 초를 받아 낸다 */
const 줄들 = (끝초: number, 값: (초: number) => Record<string, number>) => Array.from({ length: 끝초 / 2 + 1 }, (_, i) => ({ 초: i * 2, 값: 값(i * 2) }));
const 시뮬 = (끝초: number, 값: (초: number) => Record<string, number>, 이김 = false) => ({ 이김, 예상: 줄들(끝초, 값) });

describe('판 값을 순서대로 하기 시계로', () => {
  it('두 시작때의 차이만큼 당기고, 순서대로 하기가 끝난 뒤 값은 버린다', () => {
    const 판 = 판값들([{ 값기록: 기록([{ 초: 1, 값: { 웨이브: 0 } }, { 초: 5, 값: { 웨이브: 1, 고기: 30 } }, { 초: 9, 값: { 웨이브: 1 } }], 1_000), 따라감: { 시작때: 4_000, 걸린초: 3 } }], 연결);
    expect(판).toEqual([{ 초: 2, 웨이브: 1, 재화: 30 }]);
  });

  it('시작때가 없는 옛 기록은 값이 처음 읽힌 때를 0 으로 보고, 이어 부른 조각은 앞 조각이 흐른 초에서 잇는다', () => {
    const 첫 = { 값기록: 기록([{ 초: 0.2, 값: { 웨이브: null } }, { 초: 3, 값: { 웨이브: 1 } }, { 초: 5, 값: { 웨이브: 1 } }]), 따라감: { 걸린초: 10 } };
    const 뒤 = { 값기록: 기록([{ 초: 0, 값: { 웨이브: 2 } }, { 초: 2, 값: { 웨이브: 2 } }], 0), 따라감: { 시작초: 10, 시작때: 0 } };
    expect(판값들([첫, 뒤], 연결).map((x) => [x.초, x.웨이브])).toEqual([[0, 1], [2, 1], [10, 2], [12, 2]]);
  });

  it('처치는 판에서 올라간 수만 더한다 — 웨이브마다 0 으로 돌아가는 판도 누적으로 견준다', () => {
    const 판 = 판값들([{ 값기록: 기록([0, 3, 7, 0, 2].map((v, i) => ({ 초: i * 2, 값: { 처치: v } }))) }], 연결);
    expect(판.map((x) => x.처치)).toEqual([0, 3, 7, 7, 9]);
    // 2초 사이에 0 으로 돌아가 다시 2 까지 올라간 것도 센다
    expect(판값들([{ 값기록: 기록([0, 10, 2].map((v, i) => ({ 초: i * 2, 값: { 처치: v } }))) }], 연결).map((x) => x.처치)).toEqual([0, 10, 12]);
  });

  it('따라감이 없는 옛 판 함수 기록은 마지막 행동이 끝난 때까지만 본다 — 결과 화면 값으로 「판이 더 돌았다」고 짚지 않게', () => {
    const 판 = 판값들([{ 값기록: 기록(줄들(60, () => ({ 웨이브: 1 }))) }], 연결, 20);
    expect(판.at(-1)?.초).toBe(20);
  });
});

describe('판과 재현을 같은 시각끼리', () => {
  it('허용 안이면 맞고, 지속초보다 짧은 어긋남은 넘긴다(웨이브가 넘어가는 순간)', () => {
    const 판 = 판값들([{ 값기록: 기록(줄들(40, (t) => ({ 웨이브: t >= 20 ? 2 : 1, 세계수: 50, 고기: 10 + t }))) }], 연결);
    const r = 재현비교하기(판, 시뮬(40, (t) => ({ 웨이브: t >= 24 ? 2 : 1, 세계수: 49, 고기: 12 + t })), 연결, [], 50);
    expect(r).toMatchObject({ 맞음: true, 어긋남: null, 본수: 21 });
    expect(r.표.map((x) => x.초)).toEqual([0, 20, 40]);
  });

  it('처음 크게 어긋난 값 · 때 · 그 앞 행동과 판에서 잰 값(재화 변화 + 쓴 재화 · 줍기 · 처치)을 짚는다 — 16104 둘째 맵 재화 판 9 · 재현 0', () => {
    // 판은 줍기로 고기가 들어오고 재현은 하나도 못 줍는다 — 40초부터 지킬것도 갈라지지만 재화가 먼저다
    const 판 = 판값들([{ 값기록: 기록(줄들(60, (t) => ({ 웨이브: 1, 세계수: t >= 40 ? 40 : 50, 고기: t < 20 ? 5 : 9, 처치: t >= 20 ? 6 : 0 }))) }], 연결);
    const 행동 = [{ 초: 10, 행동: '놓기', 대상: '쌍둥이', 자리: [7.5, 31.8] as const, 끝초: 12, 됨: true, 값: 5 }, { 초: 16, 행동: '줍기', 자리: [8, 30] as const, 자리들: [[8, 30], [9, 30], [9, 31]] as [number, number][], 끝초: 19, 됨: true }];
    const r = 재현비교하기(판, 시뮬(60, (t) => ({ 웨이브: 1, 세계수: 50, 고기: 0, 처치: t >= 20 ? 6 : 0 })), 연결, 행동, 50);
    expect(r.맞음).toBe(false);
    // 처음 20초의 5 · 0 은 허용(5) 안이다
    expect(r.어긋남).toMatchObject({ 초: 20, 값: '재화', 판: 9, 시뮬: 0, 앞행동: '줍기 (8,30) 3개 됨 · 1초 전', 고칠곳: expect.stringContaining('적종류 보상') });
    expect(r.어긋남!.잰값).toBe('0~20초 판: 재화 5 → 9 · 들어온 재화 4 · 쓴 재화 0 · 줍기 3개 · 처치 6 / 시뮬: 재화 0 → 0 · 들어온 재화 0 · 쓴 재화 0 · 처치 6');
    expect(어긋남글(r.어긋남!)).toMatch(/^20초 재화: 판 9 · 시뮬 0 \(그 앞 행동 줍기/);
  });

  it('견주기 시작한 때부터 어긋난 때까지 들어온 재화(오른 합) · 쓴 재화(내린 합) · 처치를 판과 재현 시뮬 양쪽에서, 줍기는 판의 된 줍기에서 센다', () => {
    const 판 = 판값들([{ 값기록: 기록(줄들(60, (t) => ({ 고기: t < 20 ? 0 : 20, 처치: t < 20 ? 0 : 6 }))) }], 연결);
    const 행동 = [{ 초: 10, 행동: '놓기', 대상: '쌍둥이', 끝초: 12, 됨: true, 값: 5 }, { 초: 13, 행동: '키우기', 끝초: 14, 됨: false, 값: 8 }, { 초: 16, 행동: '줍기', 자리들: [[8, 30], [9, 30], [9, 31]] as [number, number][], 끝초: 19, 됨: true }];
    const r = 재현비교하기(판, 시뮬(60, () => ({ 고기: 0, 처치: 0 })), 연결, 행동, 50);
    expect(r.어긋남).toMatchObject({ 초: 20, 값: '재화', 판: 20, 시뮬: 0, 앞행동: '줍기 3개 됨 · 1초 전' });
    expect(r.어긋남!.잰값).toBe('0~20초 판: 재화 0 → 20 · 들어온 재화 20 · 쓴 재화 0 · 줍기 3개 · 처치 6 / 시뮬: 재화 0 → 0 · 들어온 재화 0 · 쓴 재화 0 · 처치 0');
  });

  it('판은 아직 도는데 재현 시뮬이 먼저 지면 그 때를 짚는다 — 16104 둘째 맵 판 6웨이브 · 재현 3웨이브', () => {
    const 판 = 판값들([{ 값기록: 기록(줄들(100, () => ({ 웨이브: 1, 세계수: 50 }))) }], 연결);
    const r = 재현비교하기(판, 시뮬(40, () => ({ 웨이브: 1, 세계수: 50 })), 연결, [], 50);
    expect(r.어긋남).toMatchObject({ 초: 40, 값: '끝', 잰값: '시뮬은 40초에 져 끝났는데 판은 100초까지 돌았다' });
    expect(재현비교하기(판.filter((x) => x.초 <= 40 + 지속초), 시뮬(40, () => ({ 웨이브: 1, 세계수: 50 })), 연결, [], 50).맞음).toBe(true);
    // 재현이 판의 첫 값보다 먼저 끝나도 견준 것으로 센다(본수는 판 값 줄 수)
    const 늦은판 = 판.map((x) => ({ ...x, 초: x.초 + 20 }));
    expect(재현비교하기(늦은판, 시뮬(10, () => ({ 웨이브: 1, 세계수: 50 })), 연결, [], 50)).toMatchObject({ 맞음: false, 본수: 51, 어긋남: { 값: '끝' } });
  });

  it('볼값을 시뮬과 하나도 못 이으면 본수 0 이다', () => {
    expect(판값들([{ 값기록: 기록([{ 초: 0, 값: { 나무: 5 } }]) }], 연결)).toEqual([]);
    expect(재현비교하기([], 시뮬(10, () => ({ 웨이브: 1 })), 연결, [], 50)).toMatchObject({ 맞음: true, 본수: 0 });
  });
});
