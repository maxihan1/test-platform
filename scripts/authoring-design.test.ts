// 설계 판정 검사 — 요구 글에서 경계 근거 · 시험 값 · 예외 근거를 코드가 같은 규칙으로 뽑는지
import { describe, expect, it } from 'vitest';

import { 설계글, 설계요약, 설계하기 } from './authoring-design.js';

const 값들 = (글: string) => 설계하기(글).경계.map((b) => b.값);
const 기법들 = (글: string) => 설계하기(글).예외.map((e) => e.기법);

describe('설계하기 — 경계값 분석', () => {
  it('범위 a~b단위는 a−1 · a · b · b+1 이고 같은 범위는 한 번만 싣는다', () => {
    const 글 =
      '아이디는 영문 소문자와 숫자로 4~12자다. 규칙에 맞지 않으면 입력칸 아래에 "아이디는 영문 소문자·숫자 4~12자입니다" 가 빨간 글자로 나온다.';
    expect(값들(글)).toEqual([['3자', '4자', '12자', '13자']]);
    expect(기법들(글)).toContain('동등 분할');
  });

  it('N 이상은 N−1 · N 이고 원문에 쉼표가 있으면 값도 쉼표다', () => {
    expect(설계하기('체크한 상품 금액 합이 50,000원 이상이면 배송비 0원, 미만이면 3,000원이다')).toEqual({
      경계: [{ 근거: '50,000원 이상', 값: ['49,999원', '50,000원'] }],
      예외: [],
    });
  });

  it('0 에서 시작하는 범위도 바로 밖 값을 싣고 500,000원은 HTTP 번호가 아니다', () => {
    const r = 설계하기('가격 범위 슬라이더(0원~500,000원, 10,000원 단위)로 최대 가격을 정한다');
    expect(r.경계.map((b) => b.값)).toContainEqual(['-1원', '0원', '500,000원', '500,001원']);
    expect(r.예외).toEqual([]);
  });

  it('연속 단위(MB)는 바깥 값을 초과 · 미만으로 적는다', () => {
    expect(값들('프로필 사진(jpg · png, 2MB 이하)을 올릴 수 있고')).toEqual([['2MB', '2MB 초과']]);
    expect(값들('첨부는 5MB 이상이어야 한다')).toEqual([['5MB 미만', '5MB']]);
    expect(값들('파일은 1~5MB 만 받는다')).toEqual([['1MB 미만', '1MB', '5MB', '5MB 초과']]);
  });

  it('px 는 내리기 같은 조작 한도일 때만 잡는다', () => {
    expect(값들('페이지를 80px 이상 내리면 머리글이 화면 위에 붙는다')).toEqual([['79px', '80px']]);
  });

  it('N번 연속은 N−1 · N 이고 잠금은 상태 전이 예외다', () => {
    const 글 = '같은 아이디로 5번 연속 비밀번호를 틀리면 그 계정은 10분간 잠기고';
    expect(값들(글)).toEqual([['4번', '5번']]);
    expect(기법들(글)).toContain('상태 전이');
  });

  it('비었을 때 화면이 달라지면 0건 경계다', () => {
    expect(값들('할 일이 하나도 없을 때는 아래쪽 영역이 보이지 않는다')).toEqual([['0건', '1건']]);
  });

  it('같은 한도가 「N개까지」 · 「최대 N개」로 두 번 나와도 경계 하나다', () => {
    const 글 =
      '관심 분야는 "패션" · "전자기기" · "도서" · "식품" 중 여러 개를 고를 수 있는 체크박스다. 최대 3개까지 고를 수 있고, 4번째를 고르면 토스트 "관심 분야는 최대 3개까지 선택할 수 있습니다" 가 나오고 선택되지 않는다.';
    expect(값들(글)).toEqual([['3개', '4개']]);
  });

  it('단위와 초과 사이의 조사를 건너뛴다', () => {
    expect(값들('제목은 20자를 초과하면 입력할 수 없다')).toEqual([['20자', '21자']]);
  });
});

describe('설계하기 — 잡지 않는 글', () => {
  it.each([
    '줄마다 체크박스가 있고, 처음에는 모두 체크되어 있다',
    '체크하고 닫으면 같은 날 다시 들어와도 팝업이 뜨지 않는다. 체크하지 않고 닫으면 다음에 또 뜬다',
    '회원 목록은 1,000명 이상이어도 한 화면 안에서 스크롤로 본다',
    '홈에 머문 지 5~15초 사이 어느 시점에 모달이 뜬다',
    '화면 너비가 768px 이하면 메뉴가 햄버거 버튼 하나로 접힌다',
    '검색 결과는 400ms 안에 나온다',
    '중복 없이 최신순으로 보여 준다',
    '결제 실패 내역을 목록으로 보여 준다',
    '이벤트는 2026년 12월 31일까지 진행한다',
    '주소는 101동 401호처럼 적는다',
  ])('%s', (글) => {
    expect(설계하기(글)).toEqual({ 경계: [], 예외: [] });
  });

  it('화면 배치 기준 px(「768px 이하에서는 2개」)는 경계가 아니다', () => {
    const 값 = 값들('상품은 한 줄에 4개(768px 이하에서는 2개)씩 나온다').flat();
    expect(값.filter((v) => v.includes('px'))).toEqual([]);
  });
});

describe('설계하기 — 예외', () => {
  it('없는 주소는 동등 분할이다', () => {
    expect(기법들('없는 주소로 들어가면 "페이지를 찾을 수 없습니다" 화면을 보여 준다')).toContain('동등 분할');
  });

  it.each([
    '필수 항목이 모두 채워지고 필수 약관 둘에 동의해야 "가입하기" 버튼이 눌린다',
    '모든 배너를 끄고 저장하면 "배너를 하나 이상 노출해야 합니다" 를 보여 주고 저장하지 않는다',
    '이메일과 휴대폰만 채우면 완료 버튼이 안 눌립니다',
    '미입력 시 "다음" 버튼이 비활성화된다',
  ])('결정 테이블 — %s', (글) => {
    expect(기법들(글)).toContain('결정 테이블');
  });

  it('HTTP 번호는 뒤에 쉼표 · 백틱 · 끝이 올 때 동등 분할 근거다', () => {
    expect(설계하기('`POST /api/auth/login` | 로그인. 틀리면 401, 잠기면 423 `LOCKED`').예외).toContainEqual({
      기법: '동등 분할',
      근거: '401',
    });
    expect(설계하기('회원가입. 아이디 중복이면 409').예외).toContainEqual({ 기법: '동등 분할', 근거: '409' });
    expect(설계하기('잠기면 423 `LOCKED`').예외).toContainEqual({ 기법: '동등 분할', 근거: '423' });
  });

  it.each([
    ['md', '| REQ-API-010 | `POST /api/auth/signup` | 회원가입. 아이디 중복이면 409 | 아니오 |'],
    ['서버 변환', '  REQ-API-010   POST /api/auth/signup        회원가입. 아이디 중복이면 409          아니오'],
    ['맥 변환', 'REQ-API-010\nPOST /api/auth/signup\n회원가입. 아이디 중복이면 409\n아니오'],
  ])('표 칸 끝의 HTTP 번호는 글자본 꼴(%s)이 달라도 같다', (_꼴, 글) => {
    expect(설계하기(글).예외).toEqual([{ 기법: '동등 분할', 근거: '중복' }, { 기법: '동등 분할', 근거: '409' }]);
  });

  it('필수 칸은 칸 이름째 근거로 싣는다', () => {
    expect(설계하기('이름(필수, 2~10자) · 이메일(필수, 이메일 형식) 을 입력받는다').예외).toContainEqual({
      기법: '동등 분할',
      근거: '이름(필수',
    });
  });
});

describe('설계하기 — 같은 글이면 같은 결과', () => {
  it('두 번 불러도 깊이 같다', () => {
    const 글 =
      '같은 아이디로 5번 연속 비밀번호를 틀리면 그 계정은 10분간 잠기고 "로그인 5회 실패로 10분간 로그인할 수 없습니다" 를 보여 준다. 아이디는 4~12자다.';
    expect(설계하기(글)).toEqual(설계하기(글));
  });
});

describe('설계요약 · 설계글 — 설계 목록 명령이 찍는 글', () => {
  const 아이디글 =
    '아이디는 영문 소문자와 숫자로 4~12자다. 규칙에 맞지 않으면 입력칸 아래에 "아이디는 영문 소문자·숫자 4~12자입니다" 가 빨간 글자로 나온다.';

  it('요약은 요구 수 · 경계가 있는 요구 수 · 예외가 있는 요구 수다', () => {
    const 항목들 = [
      { 설계: { 경계: [{ 근거: '4~12자', 값: ['3자', '4자', '12자', '13자'] }], 예외: [] } },
      { 설계: { 경계: [], 예외: [{ 기법: '동등 분할' as const, 근거: '맞지 않으면' }] } },
      {},
    ];
    expect(설계요약(항목들)).toBe('설계: 요구 3 중 경계 1 · 예외 1');
  });

  it('설계가 있는 요구만 한 줄씩 싣고 끝에 요약을 단다', () => {
    const 항목들 = [
      { 번호: 'REQ-MEM-001', 설계: 설계하기(아이디글) },
      { 번호: 'REQ-MEM-002' },
    ];
    expect(설계글(항목들)).toBe(
      [
        'REQ-MEM-001 · 경계 「4~12자」 3자 · 4자 · 12자 · 13자 · 예외 동등 분할 「맞지 않으면」',
        '설계: 요구 2 중 경계 1 · 예외 1',
      ].join('\n'),
    );
  });

  it('경계가 여럿이면 경계끼리, 예외가 여럿이면 예외끼리 차례대로 잇는다', () => {
    const 항목들 = [
      {
        번호: 'REQ-MEM-002',
        설계: {
          경계: [
            { 근거: '4~12자', 값: ['3자', '4자', '12자', '13자'] },
            { 근거: '5번 연속', 값: ['4번', '5번'] },
          ],
          예외: [
            { 기법: '동등 분할' as const, 근거: '맞지 않으면' },
            { 기법: '상태 전이' as const, 근거: '잠기' },
          ],
        },
      },
    ];
    expect(설계글(항목들).split('\n')[0]).toBe(
      'REQ-MEM-002 · 경계 「4~12자」 3자 · 4자 · 12자 · 13자 · 경계 「5번 연속」 4번 · 5번 · 예외 동등 분할 「맞지 않으면」 · 예외 상태 전이 「잠기」',
    );
  });

  it('설계가 있는 요구가 없으면 요약 한 줄만이다', () => {
    expect(설계글([{ 번호: 'REQ-MEM-001' }, { 번호: 'REQ-MEM-002' }])).toBe('설계: 요구 2 중 경계 0 · 예외 0');
  });
});
