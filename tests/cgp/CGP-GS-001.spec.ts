export const spec = defineCase({
  tcId: 'CGP-GS-001',
  name: '튜토리얼 「세계수」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다',
  platforms: ['windows'],
  precondition: ['메인 메뉴에서 「튜토리얼」로 들어간다 · 1인'],
  params: null,
  expected: null,
});

test(spec, async ({ game }) => {
  let 장면!: 튜토리얼장면;

  await test.step('메인 메뉴에서 「튜토리얼」로 들어간다', async () => {
    장면 = await 튜토리얼까지(game);
    await verify('튜토리얼이 열려 있다', await 장면.떴나(), true, { blocker: true });
  });

  await test.step('튜토리얼 과제를 차례로 해 「악마의 습격」 카드까지 간다', async () => {
    const 기록: 튜토리얼걸음[] = [];
    let 회복앞: number | null = null;
    let 회복뒤: number | null = null;
    let 만렙체력앞: number | null = null;
    let 만렙체력뒤: number | null = null;
    let 만렙고기앞: number | null = null;
    let 만렙고기뒤: number | null = null;
    let 습격봄 = false;
    let 멈춤: unknown;

    const 만렙재기 = async (): Promise<void> => {
      if (만렙체력앞 !== null) return;
      const 식물 = await 장면.식물();
      if (식물 === null || 식물.레벨 !== 5) return;
      만렙체력앞 = 식물.체력;
      만렙고기앞 = await 장면.먹인고기(식물.주소);
      await game.key('C', { duration: 0.6 });
      const 끝 = Date.now() + 5_000;
      let 지금 = 식물.체력;
      while (Date.now() < 끝) 지금 = (await 장면.식물())?.체력 ?? 지금;
      만렙체력뒤 = 지금;
      만렙고기뒤 = await 장면.먹인고기(식물.주소);
    };

    const 한걸음 = async (): Promise<void> => {
      const 지금 = await 장면.지금();
      const 회복단계 = 회복앞 === null && 지금.과제.includes('회복');
      if (회복단계) 회복앞 = (await 장면.식물())?.체력 ?? null;
      const 걸음 = await 장면.한걸음();
      기록.push(걸음);
      if (회복단계) 회복뒤 = (await 장면.식물())?.체력 ?? null;
      await 만렙재기();
      if (단계를봤나([걸음], 단계.습격)) 습격봄 = true;
    };

    try {
      await repeatUntil(한걸음, {
        progress: async () => (습격봄 ? 1_000 : 본단계수(기록)),
        goal: 1_000,
        stallMs: 90_000,
      });
    } catch (e) {
      멈춤 = e;
    }

    await verify.note('본 단계', 기록줄(기록));
    await verify('튜토리얼 「세계수」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.세계수), true);
    await verify('튜토리얼 「악마 출현 지점」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.출현지점), true);
    await verify('튜토리얼 「세계수 체력」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.세계수체력), true);
    await verify('튜토리얼 「웨이브」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.웨이브), true);
    await verify('튜토리얼 「미니맵」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.미니맵), true);
    await verify('튜토리얼 「고기 안내」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.고기안내), true);
    await verify('튜토리얼 「처치한 악마」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.처치한악마), true);
    await verify('튜토리얼 「이동」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.이동), true);
    await verify(
      '튜토리얼 이동 과제는 목표 지점에 닿으면 끝나고 다음 「공격」 카드가 뜬다',
      카드다음카드(기록, '목표 지점', 단계.공격.카드[0] ?? ''),
      true,
    );
    await verify('튜토리얼 「공격」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.공격), true);
    await verify('튜토리얼 「폭탄」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.폭탄), true);
    await verify('튜토리얼 「처치」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.처치), true);
    await verify('튜토리얼 「고기 줍기」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.고기줍기), true);
    await verify('튜토리얼 「식물 심기」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.식물심기), true);
    await verify('튜토리얼 「심기 준비」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.심기준비), true);
    await verify('튜토리얼 「식물의 공격」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.식물의공격), true);
    await verify('튜토리얼 「식물 체력」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.식물체력), true);
    await verify('튜토리얼 「식물 체력」 과제에서 C 로 고기를 먹이면 식물 체력이 오른다', 회복앞 !== null && 회복뒤 !== null && 회복뒤 > 회복앞, true);
    await verify('튜토리얼 「식물 성장」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.식물성장), true);
    await verify('레벨 5 가 된 식물은 체력이 줄지 않는다', 만렙체력앞 !== null && 만렙체력뒤 !== null && 만렙체력뒤 >= 만렙체력앞, true);
    await verify('레벨 5 식물 곁에서 C 를 눌러도 먹인 고기가 늘지 않는다', 만렙고기앞 !== null && 만렙고기뒤 === 만렙고기앞, true);
    await verify('튜토리얼 「식물 회수」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.식물회수), true);
    await verify('튜토리얼 「고기 지급」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 단계를봤나(기록, 단계.고기지급), true);
    await verify('튜토리얼 「악마의 습격」 단계에서 그 단계의 안내 카드 · 과제 · 키 안내 글이 보인다', 습격봄, true);
    if (멈춤 !== undefined) throw 멈춤;
  });
});
