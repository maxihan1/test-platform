// 길 따라 걷기 — 조작 도우미가 시뮬과 같은 격자 길찾기로 거쳐 갈 점을 받아 판 함수 걷기를 점마다 부른다 (도메인/게임 §3.10 「순서대로 하기」)
// 2026-11-29 사용자 — 판 함수 걷기는 미리 못 받은 자리(지킬것 둘레 · 바닥 재화 · 칠 자리)로 곧게 가다 물에 막혔다(16110 셋째 맵 이동 0/8). 시뮬은 같은 격자 길로 걷는 시간을 센다
import type { 점 } from './simInput.js';

/** 두 점 사이 거쳐 갈 점 — 첫 점은 출발(막힌 칸이면 옮긴 열린 칸) · 끝 점은 도착(막힌 칸이면 옮긴 열린 칸). 길이 없으면 null(그때는 곧게 간다) */
export type 길내기 = (a: 점, b: 점) => readonly 점[] | null;

/**
 * 목표까지 걷는다 — 길이 있으면 거쳐 갈 점마다, 없으면 곧게 한 번. 마지막은 늘 목표 자리 그대로다.
 * 실패하면 목표를 못감으로 넘기고 멈춘다 — 거쳐 갈 점(다리 위일 수 있다)을 남기면 다음 판부터 그 길이 영영 막힌다. 격자는 판을 열 때 지어 판 내내 쓰니 못감은 다음 판부터 든다
 */
export async function 길따라걷기(걷기: (p: 점) => Promise<boolean>, 길: 길내기 | undefined, 지금: 점, 목표: 점, 못감: (p: 점) => void): Promise<boolean> {
  for (const p of 거쳐갈점(길, 지금, 목표)) {
    if (await 걷기(p)) continue;
    못감(목표);
    return false;
  }
  return true;
}

const 같다 = (a: 점, b: 점): boolean => a[0] === b[0] && a[1] === b[1];
/** 걸을 점 차례 — 출발은 빼되 막힌 칸이라 옮긴 점이면 그리로 먼저, 끝은 목표 자리(막혀 옮긴 점이면 그 점을 거쳐 목표로) */
export function 거쳐갈점(길: 길내기 | undefined, 지금: 점, 목표: 점): 점[] {
  const 점들 = [...(길?.(지금, 목표) ?? [])];
  if (점들.length > 0 && 같다(점들[0]!, 지금)) 점들.shift();
  if (점들.length > 0 && 같다(점들.at(-1)!, 목표)) 점들.pop();
  return [...점들, 목표];
}
