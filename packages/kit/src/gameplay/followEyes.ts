/** 이만큼 이어 비면 못 읽는 것으로 본다(첫 값 · 적 못 봄과 같다) */
export const 떨어진못봄초 = 15;
/** 줍는 게임에서 웨이브 중 떨어진() 을 이만큼마다 한 번은 읽는다(첫 값) — 걷고 놓기만 이어지면 읽기 사이가 벌어 검사가 안 걸렸다 */
export const 떨어진읽기초 = 3;

/** 게임에서 아는 것 — 줍는 게임인가 · 초당 재화 · 적 하나가 지킬것에 닿을 때 깎는 가장 작은 값(0 이면 모른다) */
export interface 떨어진눈설정 { 줍는게임: boolean; 초당: number; 한번피해: number }

/**
 * 떨어진() 을 읽을 때마다 부른다 — 처음 잡힌 때 남길 것을 돌려주고, 아니면 null. 같은 웨이브에서 이어 읽은 동안만 센다(읽기 사이가 5초 넘게 벌면 다시 센다).
 * 처치는 남은 적이 줄어든 수에서 지킬것에 닿은 수(깎인 지킬것 ÷ 한번피해 · 한번피해를 모르면 다 닿은 것으로)를 뺀다.
 * 읽기 사이에 재화가 초당 재화보다 더 오르면 바닥 재화를 주운 것이라 다시 센다(중간에 재화를 써도 들어온 것을 놓치지 않게)
 */
export function 떨어진눈(설정: 떨어진눈설정): (상태: 판상태, 개수: number, 지금초: number) => { 초: number; 남은적: number; 이어진초: number } | null {
  let 빈: { 때: number; 웨이브: number; 앞: number; 남은적: number; 지킬것: number; 앞재화: number } | null = null;
  let 잡음 = false;
  return (상태, 개수, 지금초) => {
    const 들어옴 = 빈 !== null && 상태.재화 - 빈.앞재화 > 설정.초당 * (지금초 - 빈.앞) + 0.5;
    if (잡음 || !설정.줍는게임 || !상태.웨이브중 || 상태.남은적 === undefined || 개수 > 0 || 들어옴) {
      빈 = null;
      return null;
    }
    if (빈 === null || 빈.웨이브 !== 상태.웨이브 || 지금초 - 빈.앞 > 5) 빈 = { 때: 지금초, 웨이브: 상태.웨이브, 앞: 지금초, 남은적: 상태.남은적, 지킬것: 상태.지킬것, 앞재화: 상태.재화 };
    [빈.앞, 빈.앞재화] = [지금초, 상태.재화];
    // 지킬것에 닿아 사라진 적은 재화를 안 떨군다 — 줄어든 남은 적에서 뺀다
    const 깎임 = Math.max(0, 빈.지킬것 - 상태.지킬것);
    const 닿음 = 깎임 === 0 ? 0 : 설정.한번피해 > 0 ? Math.ceil(깎임 / 설정.한번피해) : Infinity;
    const 잡은 = 빈.남은적 - 상태.남은적 - 닿음;
    if (지금초 - 빈.때 < 떨어진못봄초 || 잡은 <= 0) return null;
    잡음 = true;
    return { 초: 빈.때, 남은적: 상태.남은적, 이어진초: Math.round((지금초 - 빈.때) * 100) / 100 };
  };
}

