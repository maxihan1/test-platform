/** 판 함수가 손동작을 돌려준 뒤 판 상태가 이만큼 안 읽히면 판에 못 들어간 것으로 본다(첫 값) — 16105 셋째 맵은 메뉴 · 캐릭터 · 맵 선택에 23초가 걸렸다 */
export const 판들어가기초 = 120;

/**
 * 판에 들어갈 때까지 1초마다 상태를 읽는다 — 판 함수가 메뉴에서 손동작을 돌려주면 메뉴에서 놓기가 나가 그 자리 둘레를 판 끝까지 뺐다(2026-11-28 16105 셋째 맵 2초 · 14초).
 * 이어 부른 판은 지킬것이 막 0 이 됐는데 끝이 아직 안 읽힌 때가 있다 — 새 판만 지킬것 > 0 을 본다. 때는 들어간 것을 본 시각(처음부터 들어가 있었으면 없다)
 */
export async function 판들어가기(상태읽기: () => Promise<판상태>, 이어: boolean, 지금: () => number, 쉼: (ms: number) => Promise<void>): Promise<{ 상태: 판상태; 때?: number } | { 못들어감: string }> {
  const 들어간 = (x: 판상태): boolean => x.판안 !== false && Number.isFinite(x.지킬것) && (이어 ? x.지킬것 >= 0 : x.지킬것 > 0) && Number.isFinite(x.재화) && x.자리.every((v) => Number.isFinite(v));
  const 기다림 = 지금();
  let 상태 = await 상태읽기();
  let 때: number | undefined;
  while (상태.끝 === undefined && !들어간(상태)) {
    if (지금() - 기다림 >= 판들어가기초 * 1000) return { 못들어감: `판 상태를 ${판들어가기초}초 동안 못 읽었다(판안 · 지킬것 · 재화 · 자리) — 판 함수가 판 장면에 들어간 뒤 손동작을 돌려주는지, 상태() 가 메뉴에서 판안: false 를 돌려주는지 본다` };
    await 쉼(1000);
    상태 = await 상태읽기();
    때 = 지금();
  }
  return { 상태, ...(때 === undefined ? {} : { 때 }) };
}
