// 판 함수의 눈 검사 — 줍는 게임에서 적을 잡았는데 재화는 안 늘고 떨어진() 이 이어 0 이면 화면 밖 바닥 재화를 못 읽는 것이다 (도메인/게임 §3.10 「순서대로 하기」 · follow.ts 가 300줄에 닿아 떼어 냈다)
// 2026-11-28 16105 다섯째 맵 — 화면 풀이로 거른 떨어진() 이 고양이 곁 고기를 못 읽어 30~133초 동안 재화 0 으로 서 있었다(16104 둘째 맵 41초 서 있음에 이어 두 번째)
import type { 판상태 } from './follow.js';

/** 이만큼 이어 비면 못 읽는 것으로 본다(첫 값 · 적 못 봄과 같다) */
export const 떨어진못봄초 = 15;

/** 떨어진() 을 읽을 때마다 부른다 — 처음 잡힌 때 남길 것을 돌려주고, 아니면 null. 같은 웨이브에서 이어 읽은 동안만 센다(읽기 사이가 5초 넘게 벌면 다시 센다) */
export function 떨어진눈(줍는게임: boolean): (상태: 판상태, 개수: number, 지금초: number) => { 초: number; 남은적: number; 이어진초: number } | null {
  let 빈: { 때: number; 웨이브: number; 앞: number; 남은적?: number; 재화: number } | null = null;
  let 잡음 = false;
  return (상태, 개수, 지금초) => {
    if (잡음 || !줍는게임 || !상태.웨이브중 || 개수 > 0) {
      빈 = null;
      return null;
    }
    if (빈 === null || 빈.웨이브 !== 상태.웨이브 || 지금초 - 빈.앞 > 5) 빈 = { 때: 지금초, 웨이브: 상태.웨이브, 앞: 지금초, ...(상태.남은적 === undefined ? {} : { 남은적: 상태.남은적 }), 재화: 상태.재화 };
    빈.앞 = 지금초;
    // 적을 잡았는데(남은 적이 줄었다) 재화는 안 늘었다 — 바닥에 떨어진 것이 있어야 하는데 0 으로 읽힌다
    const 잡았다 = 빈.남은적 !== undefined && 상태.남은적 !== undefined && 상태.남은적 < 빈.남은적;
    if (지금초 - 빈.때 < 떨어진못봄초 || !잡았다 || 상태.재화 > 빈.재화) return null;
    잡음 = true;
    return { 초: 빈.때, 남은적: 상태.남은적!, 이어진초: Math.round((지금초 - 빈.때) * 100) / 100 };
  };
}
