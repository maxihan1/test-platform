    expect(반응고르기(정책, 본, m, 0, {}, {})).toMatchObject({ 규칙: { 행동: { 무엇: '아이템' } }, 자리: [9, 0] });
    expect(반응고르기(정책, 본, m, 5, { 폭탄: 10 }, {})).toMatchObject({ 규칙: { 행동: { 무엇: '회복' } } });
    expect(반응고르기(정책, 본, m, 5, {}, { 폭탄: 1 })).toMatchObject({ 규칙: { 행동: { 무엇: '회복' } } });
    expect(반응고르기(정책, { ...본, 재화: 2 }, m, 5, { 폭탄: 10 }, {})).toBeNull();
    expect(반응고르기(정책, { ...본, 적: [[1, 0]], 지킬것: 10 }, m, 0, {}, {})).toBeNull();
    const 굽은 = 모델로(기본({ 지킬것: { 체력: 10, 자리: [0, 9] }, 길: { 가: [[10, 0], [10, 8], [0, 8], [0, 0]] }, 캐릭터: { 자리: [5, 4], 걷기속도: 1, 공격: { 사거리: 1, 공격력: 10, 간격: 3 } }, 정책: [{ 조건: [], 행동: { 무엇: '공격' } }] }));
