describe('손동작 검사', () => {
  const m = 모델로(기본());
  it('읽기 넷(적 포함 — 웨이브 중 다시 계산이 쓴다) · 걷기 · 순서가 쓰는 행동이 함수로 있어야 한다', () => {
    const 다 = { 상태: () => 0, 설치물: () => 0, 떨어진: () => 0, 적: () => 0, 걷기: () => 0, 놓기: () => 0 };
    expect(손읽기(다, m.정책들)).toBe(다);
    expect(손읽기({ ...다, 놓기: undefined }, m.정책들)).toContain('빠진 것: 놓기');
    expect(손읽기({ 이김: false }, m.정책들)).toContain('빠진 것: 상태 · 설치물 · 떨어진 · 적 · 걷기 · 놓기');
    expect(손읽기({ ...다, 적: undefined }, m.정책들)).toContain('빠진 것: 적');
    expect(손읽기(다, [[{ 조건: [], 행동: { 무엇: '공격' } }, { 조건: [], 행동: { 무엇: '이동', 자리: [1, 1] } }]])).toContain('빠진 것: 공격');
  });

  it('판 함수가 못들어감 을 돌려주면 그대로 넘기고, 손동작이 아니면 던진다', async () => {
    const 기록: 따라간기록 = { 행동기록: [], 다시계산: [] };
    const 갈 = { 모델: m, 정책: m.정책들[0]!, 버금: [] };
    expect(await 순서대로함수(() => ({ 못들어감: '맵 버튼이 없다' }), 갈, 기록)(null)).toEqual({ 못들어감: '맵 버튼이 없다' });
    await expect(순서대로함수(() => ({ 이김: true }), 갈, 기록)(null)).rejects.toThrow('손동작을 다 안 돌려줬다');
    expect(기록.행동기록).toEqual([]);
  });
});
