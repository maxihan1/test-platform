// 습관 — 계산과 상관없이 시뮬과 판이 늘 하는 먹이 · 바닥 재화 줍기 · 지킬것 앞 적 공격 순서를 본다
import { describe, expect, it } from 'vitest';

import { 따라가기 } from './follow.js';
import { 가짜판, 기본, 모델로, 사이, 중 } from './followFake.js';
import { 묶음경로 } from './habit.js';
import { 돌리기 } from './sim.js';
import type { 모델, 시작상태 } from './simInput.js';

const 유지 = { 체력: 5, 초당감소: 0.05, 다하면: '멈춤', 먹이: { 값: 3, 양: 5, 초: 1 }, 근거: 'rule:식물 유지' };
const 비싼탑 = [{ 이름: '탑', 레벨: [{ 값: 99, 사거리: 3, 공격력: 5, 간격: 2 }] }];
const 느린적 = [{ 이름: '슬라임', 체력: 100, 속도: 0.01, 닿으면피해: 5, 보상: 1 }];
const 시작에서 = (m: 모델, 덧: Partial<시작상태>) => 돌리기({ ...m, 시작: { 지킬것: 10, 재화: 0, 자리: m.캐릭터.자리, 설치물: [], 떨어진: [], 첫웨이브까지초: 0, ...덧 } }, m.정책들[0]!);

describe('시뮬의 습관', () => {
  it('정책에 먹이가 없어도 유지가 60% 아래로 내려간 설치물에 먹이를 준다', () => {
    const m = 모델로(기본({ 웨이브: [{ 시작초: 120, 출현: [{ 종류: '슬라임', 수: 1, 간격: 0, 길: '가' }] }], 설치물종류: [{ 이름: '탑', 유지, 레벨: [{ 값: 0, 사거리: 3, 공격력: 5, 간격: 2 }] }], 재화: { 시작: 30 } }));
    const r = 돌리기(m, m.정책들[0]!);
    const 놓은 = r.행동기록.find((x) => x.행동 === '놓기')!;
    const 먹이 = r.행동기록.find((x) => x.행동 === '먹이');
    expect(먹이).toBeDefined();
    // 유지 5 에서 3(60%) 아래가 되는 때는 놓고 40초 뒤다
    expect(먹이!.초 - 놓은.끝초!).toBeGreaterThanOrEqual(40);
    expect(먹이!.초 - 놓은.끝초!).toBeLessThan(42);
  });

  it('웨이브가 끝나면 정책에 줍기가 없어도 바닥 재화를 다 줍는다 — 다음 웨이브 전에 바닥에 남지 않는다', () => {
    const m = 모델로(기본({ 재화: { 시작: 0, 줍기: true } }));
    const r = 돌리기(m, m.정책들[0]!);
    const 끝 = r.웨이브[0]!.끝초;
    const 줍기 = r.행동기록.filter((x) => x.행동 === '줍기' && x.초 >= 끝);
    expect(줍기.length).toBeGreaterThanOrEqual(1);
    expect(줍기[0]!.끝초!).toBeLessThan(끝 + 15);
    expect(r.웨이브[1]!.끝재화).toBeGreaterThanOrEqual(1);
  });

  it('웨이브 중에는 바닥 재화 줍기가 공격보다 먼저고, 적이 지킬것 앞에 왔을 때만 공격이 먼저다', () => {
    const m = 모델로(기본({ 적종류: 느린적, 설치물종류: 비싼탑, 캐릭터: { 자리: [5, 1], 걷기속도: 1, 공격: { 사거리: 2, 공격력: 10, 간격: 1 } }, 재화: { 시작: 0, 줍기: true }, 정책: [{ 조건: [], 행동: { 무엇: '공격' } }] }));
    const 멀리 = 시작에서(m, { 떨어진: [[5, 3]], 적: [{ 종류: '슬라임', 길: '가', 진행: 4 }] });
    expect(멀리.행동기록[0]!.행동).toBe('줍기');
    const 앞 = 시작에서(m, { 떨어진: [[5, 3]], 적: [{ 종류: '슬라임', 길: '가', 진행: 8 }] });
    expect(앞.행동기록[0]!.행동).toBe('공격');
  });

  it('웨이브 중 줍기는 가장 가까운 하나가 아니라 걷는 거리 대비 많이 모인 묶음으로 간다', () => {
    const m = 모델로(기본({ 적종류: 느린적, 설치물종류: 비싼탑, 재화: { 시작: 0, 줍기: true }, 정책: [{ 조건: [], 행동: { 무엇: '놓기', 대상: '탑' } }] }));
    const 묶음 = [[11, 7], [11.5, 7], [12, 7], [11, 7.5], [12, 7.5]] as [number, number][];
    const r = 시작에서(m, { 떨어진: [[5, 3], ...묶음], 적: [{ 종류: '슬라임', 길: '가', 진행: 1 }] });
    expect(묶음).toContainEqual(r.행동기록.find((x) => x.행동 === '줍기')!.자리);
    expect(묶음경로([[5, 3], ...묶음], [5, 1])).toHaveLength(5);
  });
});

describe('판에서의 습관', () => {
  it('웨이브가 끝나면 다음 웨이브 전에 바닥 재화를 하나도 안 남기고 줍는다', async () => {
    const m = 모델로(기본({ 설치물종류: 비싼탑, 재화: { 시작: 0, 줍기: true } }));
    const 판 = 가짜판([사이(1), 사이(1), 사이(1), 중(2), { ...중(2), 끝: '이김' }], { 바닥: [[9, 3], [6.5, 1], [2, 1]] });
    await 따라가기(판.손, { 모델: m, 정책: m.정책들[0]!, 버금: [] }, 판.기록, 판.덧);
    const 주운 = 판.기록.행동기록.filter((x) => x.행동 === '줍기').flatMap((x) => x.자리들 ?? []);
    expect(주운).toHaveLength(3);
  });

  it('웨이브 중에는 바닥 재화를 먼저 줍고, 적이 지킬것 앞에 왔을 때만 공격이 먼저다', async () => {
    const m = 모델로(기본({ 설치물종류: 비싼탑, 캐릭터: { 자리: [5, 1], 걷기속도: 1, 공격: { 사거리: 1, 공격력: 10, 간격: 1 } }, 재화: { 시작: 0, 줍기: true }, 정책: [{ 조건: [], 행동: { 무엇: '공격' } }] }));
    const 해 = async (적자리: [number, number]) => {
      const 판 = 가짜판([중(1), 중(1), 중(1), { ...중(1), 끝: '이김' }], { 바닥: [[6, 3]], 적: async () => [적자리], 공격: async () => true });
      await 따라가기(판.손, { 모델: m, 정책: m.정책들[0]!, 버금: [] }, 판.기록, 판.덧);
      return 판.기록.행동기록.map((x) => x.행동);
    };
    expect((await 해([3, 0]))[0]).toBe('줍기');
    expect((await 해([9, 0]))[0]).toBe('공격');
  });

  it('유지가 60% 아래인 설치물이 있으면 먹이를 준다 — 순서표가 비어도 서 있지 않는다', async () => {
    const m = 모델로(기본({ 설치물종류: [{ 이름: '탑', 유지, 레벨: [{ 값: 99, 사거리: 3, 공격력: 5, 간격: 2 }] }], 재화: { 시작: 10 } }));
    const 먹인: string[] = [];
    const 판 = 가짜판([사이(0, { 재화: 10 }), 사이(0, { 재화: 10 }), { ...사이(0), 끝: '짐' }], {
      설치물: async () => [{ 종류: '탑', 레벨: 1, 자리: [5, 1], 유지: 먹인.length === 0 ? 0.4 : 1 }],
      먹이: async (종류, 자리) => (먹인.push(`${종류} ${자리.join(',')}`), true),
    });
    await 따라가기(판.손, { 모델: m, 정책: m.정책들[0]!, 버금: [] }, 판.기록, 판.덧);
    expect(먹인).toEqual(['탑 5,1']);
  });
});
