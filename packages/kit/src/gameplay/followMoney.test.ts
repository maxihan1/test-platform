// 순서대로 하기의 재화 모자람 — 바닥 재화부터 줍기 · 한 번만 다시 계산 · 할 수 있는 뒤 단계 먼저 · 기다림
import { describe, expect, it } from 'vitest';

import { 따라가기 } from './follow.js';
import { 가짜판, 기본, 모델로, 사이 } from './followFake.js';
import { type 점 } from './simInput.js';

describe('재화가 모자랄 때', () => {
  // 시뮬은 초당 재화로 2초 뒤 놓기를 계획하는데 판의 재화는 1 에 머문다 — 16104 둘째 맵은 이렇게 41초 동안 28번 다시 계산하며 서 있었다
  const 모자란판모델 = () => 모델로(기본({ 설치물종류: [{ 이름: '탑', 레벨: [{ 값: 3, 사거리: 3, 공격력: 5, 간격: 2 }] }], 재화: { 시작: 0, 초당: 1, 줍기: true } }));

  it('재화가 모자라면 그 단계를 미루고 바닥 재화부터 줍는다', async () => {
    const m = 모자란판모델();
    const 바닥: 점[] = [[9, 3]];
    let [놓음, n] = [false, 0];
    const 판 = 가짜판([사이(0)], {
      떨어진: async () => [...바닥],
      줍기: async () => (바닥.splice(0), true),
      놓기: async () => (놓음 = true),
      상태: async () => ((n += 1), { ...사이(0, { 재화: 바닥.length === 0 ? 3 : 1 }), ...(놓음 || n > 40 ? { 끝: '짐' as const } : {}) }),
    });
    await 따라가기(판.손, { 모델: m, 정책: m.정책들[0]!, 버금: [] }, 판.기록, 판.덧);
    expect(판.기록.행동기록.map((x) => [x.행동, x.됨])).toEqual([['줍기', true], ['놓기', true]]);
    expect(판.기록.다시계산.map((x) => x.까닭)).toEqual(['판 시작']);
  });

  it('재화가 모자라 다시 계산한 뒤 재화가 그대로면 다시 계산을 되풀이하지 않고 기다린다', async () => {
    const m = 모자란판모델();
    let n = 0;
    const 판 = 가짜판([사이(0)], { 상태: async () => ((n += 1), { ...사이(0, { 재화: 1 }), ...(n > 20 ? { 끝: '짐' as const } : {}) }) });
    await 따라가기(판.손, { 모델: m, 정책: m.정책들[0]!, 버금: [] }, 판.기록, 판.덧);
    expect(판.기록.다시계산.map((x) => x.까닭)).toEqual(['판 시작', '재화 1 가 모자라 놓기(3)을 못 한다']);
    expect(판.기록.행동기록).toEqual([]);
  });

  it('다시 계산해도 같은 재화로 또 모자라면 지금 재화로 할 수 있는 뒤 단계를 먼저 한다 — 서 있지 않는다', async () => {
    const m = 모델로(기본({ 설치물종류: [{ 이름: '탑', 레벨: [{ 값: 3, 사거리: 3, 공격력: 5, 간격: 2 }] }], 재화: { 시작: 0, 초당: 1 }, 정책: [{ 조건: [], 행동: { 무엇: '놓기', 대상: '탑' } }, { 조건: [{ 값: '재화', 비교: '<', 기준: 1 }], 행동: { 무엇: '이동', 자리: [6, 1] } }] }));
    let n = 0;
    const 판 = 가짜판([사이(0)], { 상태: async () => ((n += 1), { ...사이(0, { 재화: 1 }), ...(n > 30 ? { 끝: '짐' as const } : {}) }) });
    await 따라가기(판.손, { 모델: m, 정책: m.정책들[0]!, 버금: [] }, 판.기록, 판.덧);
    expect(판.기록.다시계산[0]!.단계).toBe(2);
    expect(판.기록.행동기록.map((x) => x.행동)).toContain('이동');
    expect(판.기록.행동기록.map((x) => x.행동)).not.toContain('놓기');
  });

  it('재화가 모자라면 걸어가기 전에 다시 계산한다', async () => {
    const m = 모델로(기본({ 설치물종류: [{ 이름: '탑', 레벨: [{ 값: 3, 사거리: 3, 공격력: 5, 간격: 2 }] }], 재화: { 시작: 0, 줍기: true }, 캐릭터: { 자리: [5, 1], 걷기속도: 4 }, 정책: [{ 조건: [], 행동: { 무엇: '놓기', 대상: '탑' } }, { 조건: [], 행동: { 무엇: '줍기' } }] }));
    // 시뮬은 셋을 주워 재화 3 으로 놓기를 계획한다 — 판에서는 주운 뒤 재화가 1 뿐이다
    const 판 = 가짜판([사이(0), 사이(0, { 재화: 1 }), 사이(0, { 재화: 1 }), { ...사이(0), 끝: '짐' }], { 바닥: [[7, 1], [9, 1], [9, 3]] });
    await 따라가기(판.손, { 모델: m, 정책: m.정책들[0]!, 버금: [] }, 판.기록, 판.덧);
    expect(판.기록.다시계산[0]).toMatchObject({ 까닭: '판 시작', 단계: 2 });
    expect(판.부름).toEqual(['줍기 7,1 9,1 9,3']);
    expect(판.기록.다시계산[1]!.까닭).toBe('재화 1 가 모자라 놓기(3)을 못 한다');
  });
});
