// 습관 — 계산이 시키든 안 시키든 시뮬과 판에서 늘 하는 것: 먹이 · 바닥 재화 줍기 · 지킬것 앞 적 (도메인/게임 §3.10 「게임플레이」 습관)
// 2026-11-29 사용자 — 계산이 「진다」고 보면 순서표가 비어 고양이가 서 있었고(16110 첫 맵 48초), 공격이 늘 먼저라 웨이브 중 고기를 안 주웠다(16108 60초).
// 순서는 먹이 → 웨이브 사이면 바닥 전부 → 지킬것 앞 적 → (정책의 놓기 · 키우기 · 먹이) → 바닥 묶음 → 정책 나머지. 예외를 두지 않는다(「시간이 모자라면 덜 줍기」 같은 예외는 핑계가 된다)
import type { 점 } from './simInput.js';
import type { 걷는거리 } from './sim.js';

/** 판을 보고 그때그때 하는 동작 — 순서표에 안 넣고 조건으로 넘긴다(적이 어디 있는지는 판에서만 안다) */
export const 반응행동: ReadonlySet<string> = new Set(['공격', '아이템', '회복']);

/** 유지 체력이 이 비율 아래인 설치물에 먹이를 준다(첫 값 · 11-26 첫 맵을 깬 작전의 값) */
export const 먹이문턱 = 0.6;
/** 지킬것에서 이 거리 안에 적이 있으면 바닥 재화가 있어도 공격 · 아이템을 먼저 한다(첫 값) */
export const 긴급반경 = 3;
/** 바닥 재화 하나에서 이 거리 안의 것을 한 묶음으로 친다(첫 값) */
export const 묶음반경 = 3;

const 곧은 = (a: 점, b: 점): number => Math.hypot(a[0] - b[0], a[1] - b[1]);

/** 가까운 것부터 한 바퀴 — 지금 자리에서 가장 가까운 것, 거기서 또 가장 가까운 것 차례로 */
export function 가까운순(들: readonly 점[], 어디서: 점): 점[] {
  const 남은 = [...들];
  const 차례: 점[] = [];
  let 지금 = 어디서;
  while (남은.length > 0) {
    let 가 = 0;
    for (let i = 1; i < 남은.length; i += 1) if (곧은(남은[i]!, 지금) < 곧은(남은[가]!, 지금)) 가 = i;
    지금 = 남은.splice(가, 1)[0]!;
    차례.push(지금);
  }
  return 차례;
}

/**
 * 웨이브 중에 쓸어 담을 바닥 재화 — 가장 가까운 하나가 아니라 걷는 거리 대비 많이 모인 묶음을 가까운 것부터 한 바퀴.
 * 바닥 하나마다 그 둘레 묶음반경 안의 것을 묶고 「수 / (거기까지 걷는 거리 + 1)」 가 가장 큰 묶음을 고른다. 걸어서 못 가는 것은 뺀다
 */
export function 묶음경로(바닥: readonly 점[], 어디서: 점, 걷기: 걷는거리 = 곧은): 점[] {
  const 갈 = 바닥.filter((p) => Number.isFinite(걷기(어디서, p)));
  let 고른: { 묶음: 점[]; 점수: number } | null = null;
  for (const p of 갈) {
    const 묶음 = 갈.filter((q) => 곧은(p, q) <= 묶음반경);
    const 점수 = 묶음.length / (걷기(어디서, p) + 1);
    if (고른 === null || 점수 > 고른.점수) 고른 = { 묶음, 점수 };
  }
  return 고른 === null ? [] : 가까운순(고른.묶음, 어디서);
}

/** 웨이브 사이에 주울 것 — 걸어서 갈 수 있는 바닥 재화 전부를 가까운 것부터 */
export const 전부경로 = (바닥: readonly 점[], 어디서: 점, 걷기: 걷는거리 = 곧은): 점[] => 가까운순(바닥.filter((p) => Number.isFinite(걷기(어디서, p))), 어디서);

/** 지킬것 앞에 적이 왔나 — 그때는 바닥 재화가 있어도 공격 · 아이템을 먼저 한다 */
export const 긴급 = (적: readonly 점[], 지킬자리: 점): boolean => 적.some((p) => 곧은(p, 지킬자리) <= 긴급반경);

/** 먹이를 줄 설치물 — 유지 비율이 먹이문턱 아래이고 먹이 값을 낼 수 있는 것 가운데 비율이 가장 낮은 것. 비율이 같으면 가까운 것 */
export function 먹일것<T extends { 종류: string; 자리: 점; 비율: number }>(설치물: readonly T[], 먹이값: (종류: string) => number | undefined, 재화: number, 어디서: 점, 걷기: 걷는거리 = 곧은): T | null {
  const 후보 = 설치물.filter((s) => { const 값 = 먹이값(s.종류); return 값 !== undefined && 재화 >= 값 && s.비율 < 먹이문턱 && Number.isFinite(걷기(어디서, s.자리)); });
  return 후보.sort((a, b) => a.비율 - b.비율 || 걷기(어디서, a.자리) - 걷기(어디서, b.자리))[0] ?? null;
}
