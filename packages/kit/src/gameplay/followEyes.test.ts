// 판 함수의 눈 검사 — 바닥 재화 못 봄(적을 잡았는데 재화는 안 늘고 떨어진() 이 15초 이어 0) · 적 못 봄(남은 적이 있는데 적() 이 15초 이어 0)
import { describe, expect, it } from 'vitest';

import type { 판상태 } from './follow.js';
import { 떨어진눈, 적눈 } from './followEyes.js';
import { 기본, 모델로, 중 } from './followFake.js';

const 줍는 = { 줍는게임: true, 초당: 0, 한번피해: 5 };
const 돌림 = (설정: Parameters<typeof 떨어진눈>[0], 들: Array<[판상태, number, number]>) => {
  const 눈 = 떨어진눈(설정);
  return 들.map(([s, n, t]) => 눈(s, n, t)).at(-1);
};
/** 0 · 4 · 8 · 12 · 15초에 이어 읽고 처음에는 남은 적 5 */
const 이어 = (가운데: Partial<판상태>, 끝: Partial<판상태>): Array<[판상태, number, number]> => [[중(1, { 남은적: 5 }), 0, 0], [중(1, { 남은적: 5, ...가운데 }), 0, 4], [중(1, { 남은적: 4, ...가운데 }), 0, 8], [중(1, { 남은적: 4, ...가운데 }), 0, 12], [중(1, 끝), 0, 15]];

describe('바닥 재화 못 봄', () => {
  it('줍는 게임에서 적을 잡았는데 재화는 안 늘고 15초 이어 0 이면 한 번만 잡는다 — 16105 다섯째 맵', () => {
    const 눈 = 떨어진눈(줍는);
    expect(눈(중(1, { 남은적: 5 }), 0, 10)).toBeNull();
    expect(눈(중(1, { 남은적: 4 }), 0, 14)).toBeNull();
    expect(눈(중(1, { 남은적: 4 }), 0, 18)).toBeNull();
    expect(눈(중(1, { 남은적: 3 }), 0, 22)).toBeNull();
    expect(눈(중(1, { 남은적: 3 }), 0, 25)).toEqual({ 초: 10, 남은적: 3, 이어진초: 15 });
    expect(눈(중(1, { 남은적: 2 }), 0, 29)).toBeNull();
  });

  it('줍는 게임이 아니거나 · 하나라도 읽히거나 · 적을 안 잡았거나 · 웨이브가 바뀌거나 · 읽기 사이가 5초 넘게 벌거나 · 남은 적을 모르면 안 잡는다', () => {
    expect(돌림(줍는, 이어({}, { 남은적: 3 }))).not.toBeNull();
    expect(돌림({ ...줍는, 줍는게임: false }, 이어({}, { 남은적: 3 }))).toBeNull();
    expect(돌림(줍는, [[중(1, { 남은적: 5 }), 0, 0], [중(1, { 남은적: 4 }), 1, 4], [중(1, { 남은적: 4 }), 0, 8], [중(1, { 남은적: 3 }), 0, 12], [중(1, { 남은적: 3 }), 0, 15]])).toBeNull();
    expect(돌림(줍는, 이어({}, { 남은적: 5 }))).toBeNull();
    expect(돌림(줍는, 이어({}, { 웨이브: 2, 남은적: 3 }))).toBeNull();
    expect(돌림(줍는, [[중(1, { 남은적: 5 }), 0, 0], [중(1, { 남은적: 3 }), 0, 15]])).toBeNull();
    expect(돌림(줍는, [[중(1), 0, 0], [중(1), 0, 8], [중(1), 0, 15]])).toBeNull();
  });

  it('적이 지킬것에 닿아 남은 적이 준 것은 처치로 안 센다 — 재화를 안 떨군다', () => {
    expect(돌림(줍는, 이어({}, { 남은적: 3, 지킬것: 0 }))).toBeNull();
    expect(돌림(줍는, 이어({}, { 남은적: 2, 지킬것: 5 }))).not.toBeNull();
    expect(돌림({ ...줍는, 한번피해: 0 }, 이어({}, { 남은적: 2, 지킬것: 5 }))).toBeNull();
  });

  it('초당 재화만큼 오른 것은 주운 것이 아니고, 중간에 재화를 써도 그 사이 더 오른 적이 있으면 주운 것이라 다시 센다', () => {
    const 초당 = { ...줍는, 초당: 1 };
    expect(돌림(초당, [[중(1, { 남은적: 5, 재화: 0 }), 0, 0], [중(1, { 남은적: 5, 재화: 4 }), 0, 4], [중(1, { 남은적: 4, 재화: 8 }), 0, 8], [중(1, { 남은적: 4, 재화: 12 }), 0, 12], [중(1, { 남은적: 3, 재화: 15 }), 0, 15]])).not.toBeNull();
    expect(돌림(줍는, [[중(1, { 남은적: 5, 재화: 10 }), 0, 0], [중(1, { 남은적: 5, 재화: 15 }), 0, 4], [중(1, { 남은적: 4, 재화: 5 }), 0, 8], [중(1, { 남은적: 4, 재화: 5 }), 0, 12], [중(1, { 남은적: 3, 재화: 5 }), 0, 15]])).toBeNull();
  });
});

describe('적 못 봄', () => {
  it('웨이브 중 남은 적이 있는데 15초 이어 0 이면 한 번 잡고, 출현 틈이 15초 이상인 웨이브는 안 본다', () => {
    const 눈 = 적눈(모델로(기본()));
    expect(눈(중(1, { 남은적: 1 }), 0, 0)).toBeNull();
    expect(눈(중(1, { 남은적: 1 }), 0, 4)).toBeNull();
    expect(눈(중(1, { 남은적: 1 }), 0, 8)).toBeNull();
    expect(눈(중(1, { 남은적: 1 }), 0, 12)).toBeNull();
    expect(눈(중(1, { 남은적: 1 }), 0, 15)).toEqual({ 초: 0, 남은적: 1, 이어진초: 15 });
    const 틈 = 적눈(모델로(기본({ 웨이브: [{ 이름: '1웨이브', 출현: [{ 종류: '슬라임', 수: 2, 간격: 20, 길: '가' }] }] })));
    expect([0, 4, 8, 12, 15].map((t) => 틈(중(1, { 남은적: 1 }), 0, t)).at(-1)).toBeNull();
  });
});
